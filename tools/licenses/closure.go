// A Go file that ports a Closure Java source names it in a
// "// Port of <path>.java" line at the top, and carries that source's own
// licence comment right after that line (PORTING.md, licence notices): the
// Apache 2.0 notice, or for a dual-licensed Rhino file the MPL 1.1 notice
// that mplOnlyNotice derives from it. A file that ports several sources
// carries each one's notice, once per distinct notice.

// noNotice lists the Closure sources that Go files port but that have no
// licence comment of their own, with the reason. Their ports need no notice
// for them; a port of such a source together with another one still needs
// the other one's notice.
var noNotice = map[string]string{
	"com/google/javascript/jscomp/AutoBuilder_AstAnalyzer_Options_Builder.java":                   generated,
	"com/google/javascript/jscomp/AutoBuilder_CheckAccessControls_PropertyReference_Builder.java": generated,
	"com/google/javascript/jscomp/AutoValue_PassFactory.java":                                     generated,
	"com/google/javascript/jscomp/modules/AutoBuilder_Export_Builder.java":                        generated,
	"com/google/javascript/jscomp/modules/AutoBuilder_Import_Builder.java":                        generated,
	"com/google/javascript/jscomp/modules/AutoBuilder_Module_Builder.java":                        generated,
	"com/google/javascript/jscomp/modules/AutoValue_ModuleMetadataMap_ModuleMetadata.java":        generated,
}

const generated = "generated by AutoValue or AutoBuilder when Closure is built; the generated source " +
	"has no licence comment, and the sources jar ships it under the Apache 2.0 like the rest of Closure"

// closureSourcePath returns the path of the Closure Java source that a
// "// Port of" or "// Derived from" line names, as written (with any "test/"
// or "src/" prefix), or "" if the line names none.
func closureSourcePath(line string) string {
	m := sourceMarker.FindStringSubmatch(line)
	if m == nil {
		return ""
	}
	path := strings.TrimRight(m[1], ",:;.)")
	if _, closure := classify(path); !closure || !strings.HasSuffix(path, ".java") {
		return ""
	}
	return path
}

// canonical strips the "test/" or "src/" prefix of a Closure source path.
func canonical(path string) string {
	return strings.TrimPrefix(strings.TrimPrefix(path, "test/"), "src/")
}

// packageClause returns the index of the package clause in lines, or
// len(lines) if there is none.
func packageClause(lines []string) int {
	for i, l := range lines {
		if strings.HasPrefix(l, "package ") {
			return i
		}
	}
	return len(lines)
}

// closureSources returns the Closure Java sources that the header of a Go
// file (lines before its package clause) names, in order and without
// duplicates, as written (with any "test/" or "src/" prefix).
func closureSources(header []string) []string {
	var paths []string
	seen := map[string]bool{}
	for _, l := range header {
		if p := closureSourcePath(l); p != "" && !seen[canonical(p)] {
			seen[canonical(p)] = true
			paths = append(paths, p)
		}
	}
	return paths
}

// closureCopyright, mplNotice and mplOnly identify the licence comments of
// Closure's sources once normalizeComment has run on them: Closure's own
// Apache 2.0 notice, and the Rhino MPL 1.1 notice with the line that
// mplOnlyNotice adds.
var (
	closureCopyright = regexp.MustCompile(`Copyright \d{4}(-\d{4})? The Closure Compiler Authors\.`)
	mplNotice        = regexp.MustCompile(`subject to the Mozilla Public License Version 1\.1`)
	mplOnly          = "This Go translation is distributed under the MPL 1.1 only"
)

// isClosureNotice reports whether a comment block is the licence comment of
// a Closure source as a Go port carries it.
func isClosureNotice(block string) bool {
	n := normalizeComment(strings.Split(block, "\n"))
	switch {
	case closureCopyright.MatchString(n) && apache2.MatchString(n):
		return true
	case mplNotice.MatchString(n) && strings.Contains(n, mplOnly):
		return true
	}
	return false
}

// looksLikeLicence reports whether a comment block is some licence comment,
// right or wrong: the blocks of a Go header that fixFile replaces.
func looksLikeLicence(block string) bool {
	for _, w := range []string{"Copyright", "LICENSE BLOCK", "Licensed under", "Mozilla Public License"} {
		if strings.Contains(block, w) {
			return true
		}
	}
	return false
}

// javaPackage matches the package declaration of a Java source.
var javaPackage = regexp.MustCompile(`(?m)^package\s`)

// javaNotices returns the licence comment of a Java source: the /* ... */
// comments before its package declaration that have a copyright line (most
// have one; DToA.java adds David M. Gay's notice to Rhino's). It returns
// none for a source with no licence comment, and an error for a licence
// comment it does not recognise.
func javaNotices(src []byte) ([]string, error) {
	s := string(src)
	if loc := javaPackage.FindStringIndex(s); loc != nil {
		s = s[:loc[0]]
	}
	var notices []string
	var rest strings.Builder
	at := 0
	for _, b := range commentBlocks(s) {
		if block := s[b.start:b.end]; strings.Contains(block, "Copyright") {
			notices = append(notices, block)
			rest.WriteString(s[at:b.start])
			at = b.end
		}
	}
	rest.WriteString(s[at:])
	if r := strings.ToLower(rest.String()); strings.Contains(r, "copyright") || strings.Contains(r, "licen") {
		return nil, fmt.Errorf("a licence comment that tools/licenses does not recognise (only /* */ comments with a copyright line before the package declaration are)")
	}
	return notices, nil
}

// portNotices returns the licence comments that a Go port of the given
// Closure sources must carry, in order and without duplicates. source
// reads a Java source (javaSource). A dual-licensed comment gives its
// MPL-only form.
func portNotices(paths []string, source func(string) ([]byte, error)) ([]string, error) {
	var notices, seen []string
	for _, p := range paths {
		src, err := source(p)
		if err != nil {
			return nil, err
		}
		blocks, err := javaNotices(src)
		if err != nil {
			return nil, fmt.Errorf("%s: %v", p, err)
		}
		_, allowed := noNotice[canonical(p)]
		switch {
		case len(blocks) == 0 && !allowed:
			return nil, fmt.Errorf("%s has no licence comment: if that is right, add it to noNotice in tools/licenses/closure.go with the reason", p)
		case len(blocks) == 0:
			continue
		case allowed:
			return nil, fmt.Errorf("%s has a licence comment, but noNotice in tools/licenses/closure.go lists it: remove it there", p)
		}
		closure := false
		for i, block := range blocks {
			mpl, dual, err := mplOnlyNotice([]byte(block))
			if err != nil {
				return nil, fmt.Errorf("%s: %v", p, err)
			}
			if dual {
				blocks[i] = mpl
			}
			closure = closure || isClosureNotice(blocks[i])
		}
		if !closure {
			return nil, fmt.Errorf("%s: -check would not recognise its licence comment as Closure's (isClosureNotice in tools/licenses/closure.go):\n%s", p, strings.Join(blocks, "\n"))
		}
		for _, block := range blocks {
			if n := normalizeComment(strings.Split(block, "\n")); !slices.Contains(seen, n) {
				seen = append(seen, n)
				notices = append(notices, block)
			}
		}
	}
	return notices, nil
}

// commentBlock is a /* ... */ comment of a text, from start to end.
type commentBlock struct{ start, end int }

// commentBlocks returns the /* ... */ comments of s that start a line.
func commentBlocks(s string) []commentBlock {
	var blocks []commentBlock
	for i := 0; i < len(s); {
		start := strings.Index(s[i:], "/*")
		if start < 0 {
			break
		}
		start += i
		end := strings.Index(s[start:], "*/")
		if end < 0 {
			break
		}
		end += start + 2
		if start == 0 || s[start-1] == '\n' {
			blocks = append(blocks, commentBlock{start, end})
		}
		i = end
	}
	return blocks
}

// withNotices returns the Go source src with the given licence comments
// right after its "// Port of" lines (the run of line comments that holds
// its first one), each followed by a blank line. The licence comments
// already there, separated by blank lines only, are kept if they are those
// notices, in that order, and replaced otherwise; replaced lists the ones
// that were not among notices. Comments further down are left alone: a
// header may name another source in a line of its own, followed by that
// source's notice.
func withNotices(src string, notices []string) (out string, replaced []string) {
	lines := strings.SplitAfter(src, "\n")
	pkg := packageClause(lines)
	port := -1
	for i := 0; i < pkg; i++ {
		if closureSourcePath(lines[i]) != "" {
			port = i
			break
		}
	}
	if port < 0 || len(notices) == 0 {
		return src, nil
	}
	group := port + 1
	for group < pkg && strings.HasPrefix(lines[group], "//") {
		group++
	}
	head := strings.Join(lines[:group], "")
	rest := strings.Join(lines[group:], "")

	want := make([]string, len(notices))
	for i, n := range notices {
		want[i] = normalizeComment(strings.Split(n, "\n"))
	}
	var have []string
	for {
		t := strings.TrimLeft(rest, "\n")
		end := strings.Index(t, "*/")
		if !strings.HasPrefix(t, "/*") || end < 0 || !looksLikeLicence(t[:end+2]) {
			break
		}
		block := t[:end+2]
		n := normalizeComment(strings.Split(block, "\n"))
		have = append(have, n)
		if !slices.Contains(want, n) {
			replaced = append(replaced, block)
		}
		rest = t[end+2:]
	}
	if slices.Equal(have, want) {
		return src, nil
	}
	var sb strings.Builder
	sb.WriteString(head)
	for _, n := range notices {
		sb.WriteString("\n")
		sb.WriteString(n)
		sb.WriteString("\n")
	}
	sb.WriteString("\n")
	sb.WriteString(strings.TrimLeft(rest, "\n"))
	return sb.String(), replaced
}

// checkClosureNotices returns the problem with the Closure licence notice of
// the Go source b (path f): its header names a Closure source that noNotice
// does not list, but holds no Closure licence comment (isClosureNotice)
// before its package clause. It adds the sources the header names to named,
// and reports whether it names any.
//
// It runs without the Java sources, so it cannot tell one Closure notice
// from another: fixFile, which reads them, puts in each source's own.
func checkClosureNotices(f string, b []byte, named map[string]bool) (problems []string, port bool) {
	lines := strings.Split(string(b), "\n")
	header := lines[:packageClause(lines)]
	paths := closureSources(header)
	var needs []string
	for _, p := range paths {
		named[canonical(p)] = true
		if _, ok := noNotice[canonical(p)]; !ok {
			needs = append(needs, p)
		}
	}
	if len(needs) == 0 {
		return nil, len(paths) > 0
	}
	text := strings.Join(header, "\n")
	for _, blk := range commentBlocks(text) {
		if isClosureNotice(text[blk.start:blk.end]) {
			return nil, true
		}
	}
	return []string{fmt.Sprintf("%s: ports %s but lacks its licence comment before the package clause (run go run ./tools/licenses)", f, strings.Join(needs, ", "))}, true
}

// checkNoNotice returns a problem for each source that noNotice lists but no
// tracked Go file names in its header: the entry is stale.
func checkNoNotice(named map[string]bool) []string {
	var problems []string
	for p := range noNotice {
		if !named[p] {
			problems = append(problems, fmt.Sprintf("tools/licenses/closure.go: noNotice lists %s, which no Go file ports: remove it", p))
		}
	}
	sort.Strings(problems)
	return problems
}
