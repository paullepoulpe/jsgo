"""Bench-scale workload checks for the behavioural oracle (PLAN.md §8 phase 3, brought forward; docs/behavioural-oracle.md).

tsc: TypeScript 5.6.3's lib/typescript.js (Apache 2.0; the bench input of the
bundle tasks, tools/bench/inputs.txt, 8.9 MB) compiled with a driver
(workloads/tsc/driver.js) that type-checks and emits a small fixed program in
memory (workloads/tsc/*.ts, written for the oracle, with a few deliberate type
errors) against TypeScript's own lib .d.ts files, at ES2015 with declarations
and source maps and at ES5/CommonJS, and prints every diagnostic and emitted
file. The builds' outputs are compared in full through stdout; the verdict is
that the run completes and prints TSC-DONE. The checker, the binder, the
emitter and the downlevel transforms all run, on a program of the size of the
bench bundles.

For ADVANCED, the driver is compiled together with typescript.js, so that
both are renamed consistently; generated externs keep the names TypeScript
reaches by string (identifier-like string literals: option names, enum
reverse maps); undeclared Node globals are warnings, as in the bench task.
"""
import json
import os

import closure_rt
import libs

HERE = os.path.dirname(os.path.abspath(__file__))
TSC_DIR = os.path.join(HERE, "workloads", "tsc")
TS_REL = os.path.join("bench-inputs", "typescript@5.6.3")
LIBS = ["lib.decorators.d.ts", "lib.decorators.legacy.d.ts", "lib.es5.d.ts", "lib.es2015.core.d.ts",
        "lib.es2015.collection.d.ts", "lib.es2015.iterable.d.ts", "lib.es2015.generator.d.ts",
        "lib.es2015.promise.d.ts", "lib.es2015.proxy.d.ts", "lib.es2015.reflect.d.ts", "lib.es2015.symbol.d.ts",
        "lib.es2015.symbol.wellknown.d.ts"]
SOURCES = ["shapes.ts", "store.ts", "util.ts"]


def tsc_verdict(rec, stdout):
    if rec is None:
        return False, "no-record"
    if rec.get("completion") == "throw":
        return False, f"threw-{(rec.get('error') or {}).get('name')}"
    if "TSC-DONE" not in stdout:
        return False, "not-done"
    return True, "ok"


def tsc_cases(cache):
    import core
    files = []
    for name in LIBS:
        with open(os.path.join(cache, TS_REL, "lib", name), encoding="utf-8") as f:
            files.append(["/lib/" + name, f.read()])
    for name in SOURCES:
        with open(os.path.join(TSC_DIR, name), encoding="utf-8") as f:
            files.append(["/src/" + name, f.read()])
    data = os.path.join("behave", "lib-gen", "tsc", "files_data.js")
    closure_rt.write_if_changed(
        os.path.join(cache, data),
        "// Generated by tools/behave/workloads.py: [path, text] of the TypeScript workload's files.\n"
        "var BEHAVE_TSC_FILES = " + json.dumps(files, ensure_ascii=True, indent=0) + ";\n")
    lib = os.path.join(TS_REL, "lib", "typescript.js")
    driver = os.path.join(TSC_DIR, "driver.js")
    with open(os.path.join(cache, lib), encoding="utf-8") as f:
        lib_src = f.read()
    with open(driver, encoding="utf-8") as f:
        driver_src = f.read()
    with open(os.path.join(cache, data), encoding="utf-8") as f:
        data_src = f.read()
    externs = libs.names_externs(cache, "tsc", libs.string_names(lib_src))
    flags = ["--externs", libs.QUNIT_EXTERNS, "--externs", externs, "--jscomp_warning=checkVars"]
    uncompiled = "\n;\n".join([lib_src, data_src, driver_src])
    return [core.Case("tsc", "typescript-5.6.3", cache, [lib, data, driver], flags, uncompiled, ["--freeze-date"],
                      tsc_verdict, stratum="tsc")]
