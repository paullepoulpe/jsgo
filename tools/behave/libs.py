"""Library test suites for the behavioural oracle (PLAN.md §8 phase 2; docs/behavioural-oracle.md).

Each library is compiled together with its own test suite, so that ADVANCED
renames both consistently, and the tests' results are the record (per test,
like goog.testing's: core.compare gives each test its own signal).

lodash 4.17.21 (MIT; pins.json "lodash", GitHub's tag: the npm package has no
tests): lodash.js and test/test.js, 1,747 QUnit tests over 307 modules, in one
case. The runner provides QUnit (--env qunit, uncompiled; libs/qunit_externs.js
declares it). test.js reads a second, "stable" lodash for its helpers
(root.lodashStable, from node_modules in lodash's own setup): the runner's
--pre script loads the same lodash.js uncompiled for that, so the helpers are
not the code under test, fixes process.argv (test.js prints it) and sets
root.ui (which test.js would work out with require()). The
clock is frozen (--freeze-date) so that debounce and throttle run on the
virtual clock, and each read moves it on by 1 ms (--date-step 1), since some
tests wait for it in a loop.

For ADVANCED, lodash and its tests reach methods by name (`_[methodName]`,
lists of method names): a generated externs file lists every identifier-like
string literal of the library and its tests, every property they read from
the global object, and lodash's public API (which test.js also calls on the
uncompiled lodashStable), so that property renaming leaves those names alone (the same device
as closure_rt.py's test-name externs).
"""
import json
import os
import re

import closure_rt

HERE = os.path.dirname(os.path.abspath(__file__))
QUNIT_EXTERNS = os.path.join(HERE, "libs", "qunit_externs.js")
MARKED_DRIVER = os.path.join(HERE, "libs", "marked_driver.js")
MARKED_SPEC_DIRS = (("new", {}), ("original", {"gfm": False, "pedantic": True}), ("redos", {}))
STRING_RE = re.compile(r"""'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)\"""")
IDENT_FULL_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
ROOT_PROP_RE = re.compile(r"\broot\.([A-Za-z_$][A-Za-z0-9_$]*)")
JS_RESERVED = frozenset("""break case catch class const continue debugger default delete do else enum export extends
false finally for function if import in instanceof new null return super switch this throw true try typeof var void
while with yield let static implements interface package private protected public await""".split())


REFLECT_RE = re.compile(r"\bObject\.(?:entries|keys|getOwnPropertyNames)\(\s*\{")
KEY_RE = re.compile(r"(?:^|[{,\s])([A-Za-z_$][A-Za-z0-9_$]*)\s*:")


REFLECT_NAME_RE = re.compile(r"\bObject\.(?:entries|keys|getOwnPropertyNames)\(\s*([A-Za-z_$][\w$]*)\s*\)")


def reflected_keys(src):
    """The keys of the object literals passed to Object.entries, Object.keys
    or Object.getOwnPropertyNames, directly or through a variable initialised
    with one (`new Map(Object.entries({...}))` tables): the program reads them
    back as strings."""
    names = set()
    starts = [m.end() for m in REFLECT_RE.finditer(src)]
    for name in set(REFLECT_NAME_RE.findall(src)):
        for m in re.finditer(r"\b(?:var|let|const)\s+" + re.escape(name) + r"\s*=\s*\{", src):
            starts.append(m.end())
    for start in starts:
        depth, i = 0, start - 1
        while i < len(src):
            if src[i] == "{":
                depth += 1
            elif src[i] == "}":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        body = src[start:i]
        # Keys at the literal's own level only.
        flat, d = [], 0
        for ch in body:
            if ch in "{[(":
                d += 1
            elif ch in "}])":
                d -= 1
            elif d == 0:
                flat.append(ch)
                continue
            flat.append(" ")
        names |= set(KEY_RE.findall("".join(flat)))
    return names


def string_names(src):
    """The identifier-like string literals of src, the properties it reads
    from `root` (the global object), and the keys it reads back from object
    literals (reflected_keys)."""
    names = set()
    for m in STRING_RE.finditer(src):
        s = m.group(1) if m.group(1) is not None else m.group(2)
        if IDENT_FULL_RE.match(s):
            names.add(s)
    names |= set(ROOT_PROP_RE.findall(src))
    names |= reflected_keys(src)
    return names


def names_externs(cache, lib, names):
    """Writes the generated externs object literal; returns its path relative
    to cache."""
    rel = os.path.join("behave", "lib-gen", lib, "string_names_externs.js")
    closure_rt.write_if_changed(
        os.path.join(cache, rel),
        "/**\n * @fileoverview Generated by tools/behave/libs.py: names the tests reach by string,\n"
        " * kept by ADVANCED's property renaming.\n * @externs\n */\n"
        "/** @const */\nvar behaveStringNames = {\n" + "".join(f"  {n}: 0,\n" for n in sorted(names)) + "};\n")
    return rel


def qunit_verdict(rec, stdout):
    return closure_rt.verdict(rec, stdout)


def lodash_cases(root, cache):
    import core
    rel = os.path.relpath(root, cache)
    lib = os.path.join(rel, "lodash.js")
    test = os.path.join(rel, "test", "test.js")
    with open(os.path.join(cache, lib), encoding="utf-8") as f:
        lib_src = f.read()
    with open(os.path.join(cache, test), encoding="utf-8") as f:
        test_src = f.read()
    # Also lodash's public API (`lodash.name = ...`): test.js calls it on the
    # uncompiled lodashStable too, which property renaming cannot reach.
    api = set(re.findall(r"\blodash(?:\.prototype)?\.([A-Za-z_$][\w$]*)\s*=", lib_src))
    api |= set(re.findall(r"\blodashStable\.([A-Za-z_$][\w$]*)", test_src))
    externs = names_externs(cache, "lodash", string_names(lib_src) | string_names(test_src) | api)
    pre = os.path.join("behave", "lib-gen", "lodash", "pre.js")
    closure_rt.write_if_changed(
        os.path.join(cache, pre),
        "// Generated by tools/behave/libs.py: lodash's test setup, run uncompiled before the build.\n"
        "// The \"stable\" lodash of test.js's helpers (lodash's own setup loads it from node_modules):\n"
        + lib_src +
        "\n;globalThis.lodashStable = globalThis._.noConflict();\n"
        "// test.js prints process.argv and derives the tested file from it.\n"
        "process.argv = ['node', 'test/test.js'];\n"
        "// What test.js would otherwise work out with require(): a monolithic, non-strict build.\n"
        "globalThis.ui = {buildPath: 'lodash.js', loaderPath: '', isModularize: false, isStrict: false,\n"
        "                 urlParams: {}};\n")
    flags = ["--externs", QUNIT_EXTERNS, "--externs", externs]
    run_opts = ["--env", "qunit", "--freeze-date", "--date-step", "1", "--pre", os.path.join(cache, pre)]
    uncompiled = lib_src + "\n;\n" + test_src
    return [core.Case("lodash", "test.js", cache, [lib, test], flags, uncompiled, run_opts, qunit_verdict,
                      stratum="lodash")]


def front_matter(src):
    """marked's spec front matter (`---` key: value lines `---`): (options, body)."""
    opts = {}
    if src.startswith("---\n"):
        end = src.find("\n---\n", 4)
        if end >= 0:
            for line in src[4:end].splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    v = v.strip()
                    opts[k.strip()] = {"true": True, "false": False}.get(v, v)
            src = src[end + 5:]
    return opts, src


def marked_cases(root, cache):
    """marked 15.0.12 (MIT): the corpus package's lib/marked.umd.js with its
    own spec tests (test/specs/new, original and redos: markdown in, HTML
    expected; pins.json "marked_tests", GitHub's tag). The CommonMark and GFM
    example files are left out: they are the specifications' text, under
    CC-BY-SA, not the libraries' licences. libs/marked_driver.js runs each
    spec as a QUnit test and prints a digest of every output."""
    import core
    rel = os.path.relpath(root, cache)
    specs = []
    names = set()
    for sub, defaults in MARKED_SPEC_DIRS:
        d = os.path.join(root, "test", "specs", sub)
        for fn in sorted(os.listdir(d)):
            if not fn.endswith(".md") or not os.path.exists(os.path.join(d, fn[:-3] + ".html")):
                continue
            with open(os.path.join(d, fn), encoding="utf-8") as f:
                opts, md = front_matter(f.read())
            with open(os.path.join(d, fn[:-3] + ".html"), encoding="utf-8") as f:
                html = f.read()
            o = dict(defaults)
            o.update({k: v for k, v in opts.items() if k in ("gfm", "pedantic", "breaks", "renderExact", "silent")})
            names |= set(o)
            specs.append([sub, fn[:-3], md, html, json.dumps(o, sort_keys=True)])
    data = os.path.join("behave", "lib-gen", "marked", "specs_data.js")
    closure_rt.write_if_changed(
        os.path.join(cache, data),
        "// Generated by tools/behave/libs.py from marked's test/specs: [suite, name, markdown, html, options].\n"
        "var BEHAVE_MARKED_SPECS = " + json.dumps(specs, ensure_ascii=True, indent=0) + ";\n")
    lib = os.path.join("corpus", "marked@15.0.12", "package", "lib", "marked.umd.js")
    externs = names_externs(cache, "marked", names | {"marked", "renderExact"})
    flags = ["--externs", QUNIT_EXTERNS, "--externs", externs]
    srcs = []
    for p in (lib, data, MARKED_DRIVER):
        with open(os.path.join(cache, p), encoding="utf-8") as f:
            srcs.append(f.read())
    return [core.Case("marked", "specs", cache, [lib, data, MARKED_DRIVER], flags, "\n;\n".join(srcs),
                      ["--env", "qunit"], qunit_verdict, stratum="marked")]
