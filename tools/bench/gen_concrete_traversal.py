#!/usr/bin/env python3
"""Generate an experimental concrete-callback copy of NodeTraversal's driver.

The original translated driver is the source of truth. Only receiver method
names and callback dispatch change. Regenerate after editing node_traversal.go;
--check verifies checked-in output without changing files.
"""
import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT/'internal/jscomp/node_traversal.go'
# Entry guards are excluded from generation, keeping the ordinary driver as the
# exact oracle and preventing dispatch back into the specialized entry.
BEGIN = '\t// concrete traversal experiment entry\n'
END = '\t// end concrete traversal experiment entry\n'
ENTRIES = ('Traverse', 'TraverseRoots', 'TraverseWithScope', 'TraverseAtScope', 'TraverseScopeRoot')


def end_of_body(source, start):
    """Find a Go brace boundary while ignoring comments and quoted literals."""
    depth, i = 1, start+1
    while i < len(source):
        if source.startswith('//', i):
            i = source.find('\n', i)
            if i < 0: raise ValueError('unterminated body')
        elif source.startswith('/*', i):
            i = source.index('*/', i+2)+2
        elif source[i] in ('"', "'", '`'):
            quote = source[i]
            i += 1
            while source[i] != quote:
                if source[i] == '\\' and quote != '`': i += 1
                i += 1
            i += 1
        else:
            if source[i] == '{': depth += 1
            elif source[i] == '}': depth -= 1
            i += 1
            if depth == 0: return i
    raise ValueError('unterminated body')


def generate(source, callback, prefix):
    methods, comments = {}, {}
    for match in re.finditer(r'^func \(t \*NodeTraversal\) (\w+)\(', source, re.M):
        body = source.index('{', match.end())
        doc = source[source.rfind('\n\n', 0, match.start())+2:match.start()]
        comments[match[1]] = doc if all(line.startswith('//') for line in doc.splitlines()) else ''
        methods[match[1]] = source[match.start():end_of_body(source, body)]
    calls = {name: set(re.findall(r'\bt\.(\w+)\(', text)) & methods.keys()
             for name, text in methods.items()}
    reachable = set(ENTRIES)
    while True:
        more = reachable | set().union(*(calls[name] for name in reachable))
        if more == reachable: break
        reachable = more
    targets = {name for name in reachable if 't.callback.' in methods[name] or 't.scopeCallback.' in methods[name]}
    # Include precisely the reachable methods on a path to callback dispatch.
    # State-only accessors remain shared with the unmodified driver.
    while True:
        more = targets | {name for name in reachable if calls[name] & targets}
        if more == targets: break
        targets = more
    generated = []
    for name, text in methods.items():
        if name not in targets: continue
        old = f'func (t *NodeTraversal) {name}('
        text = text.replace(old, f'func (t *NodeTraversal) {prefix}{name}(cb *{callback}'+
                            (', ' if text[len(old):].lstrip()[0] != ')' else ''), 1)
        for target in sorted(targets, key=len, reverse=True):
            pattern = r'\bt\.'+target+r'\(\s*(?P<empty>\))?'
            text = re.sub(pattern, lambda m: f't.{prefix}{target}(cb'+(')' if m['empty'] else ', '), text)
        text = text.replace('t.callback.', 'cb.').replace('t.scopeCallback.', 'cb.')
        # This callback always implements ScopedCallback; no per-node interface
        # assertions or dictionary method calls are introduced.
        text = text.replace('t.scopeCallback != nil', 'true')
        generated.append(comments[name]+text)
    return '\n\n'.join(generated)+'\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    source = SOURCE.read_text()
    source = re.sub(re.escape(BEGIN)+r'.*?'+re.escape(END), '', source, flags=re.S)
    notice = source[:source.index('package jscomp')]
    header = '// Code generated by tools/bench/gen_concrete_traversal.py; DO NOT EDIT.\n'+notice
    imports = '''package jscomp

import (
 "github.com/paullepoulpe/jsgo/internal/jutil"
 "github.com/paullepoulpe/jsgo/internal/rhino"
)

'''
    outputs = {
        'internal/jscomp/node_traversal_concrete_generated.go': generate(source, 'ReferenceCollector_CollectorCallback', 'referenceConcrete'),
        # A test-only recording/mutating callback exercises the same generated
        # algorithm independently of the collector's behavior.
        'internal/jscomp/node_traversal_concrete_generated_test.go': generate(source, 'concreteTraversalEvents', 'eventsConcrete'),
    }
    for relative, text in outputs.items():
        content = subprocess.run(['gofmt'], input=header+imports+text, capture_output=True, text=True, check=True).stdout
        path = ROOT/relative
        if args.check:
            if not path.exists() or path.read_text() != content: raise SystemExit('stale generated file: '+relative)
        else: path.write_text(content)


if __name__ == '__main__': main()
