  static void genMergeFrom(Descriptor m, String g, List<FieldDescriptor> fields) {
    p("// mergeFrom is GeneratedMessage.Builder.mergeFrom(" + m.getName() + ") on a mutable m.");
    p("func (m *" + g + ") mergeFrom(other *" + g + ") {");
    p("\tif other == " + g + "_GetDefaultInstance() {");
    p("\t\treturn");
    p("\t}");
    for (FieldDescriptor f : fields) {
      String mm = member(f);
      OneofDescriptor o = f.getRealContainingOneof();
      if (f.isRepeated()) {
        p("\tm." + mm + " = append(m." + mm + ", other." + mm + "...)");
      } else if (o != null) {
        // Handled below per oneof.
      } else if (isMessage(f)) {
        p("\tif other." + mm + " != nil {");
        p("\t\tif m." + mm + " != nil {");
        p("\t\t\tx := m." + mm + ".mutableCopy()");
        p("\t\t\tx.mergeFrom(other." + mm + ")");
        p("\t\t\tm." + mm + " = x.freeze()");
        p("\t\t} else {");
        p("\t\t\tm." + mm + " = other." + mm);
        p("\t\t}");
        p("\t}");
      } else {
        p("\tif " + present(f, "other") + " {");
        p("\t\tm." + mm + " = other." + mm);
        if (bit(f) >= 0) {
          p("\t\tm.bitField0_ |= 1 << " + bit(f));
        }
        p("\t}");
      }
    }
    for (OneofDescriptor o : oneofs(m)) {
      p("\tswitch other." + caseMember(o) + " {");
      for (FieldDescriptor f : o.getFields()) {
        String mm = member(f);
        p("\tcase " + f.getNumber() + ":");
        if (isMessage(f)) {
          p("\t\tif m." + caseMember(o) + " == " + f.getNumber() + " && m." + mm + " != nil {");
          p("\t\t\tx := m." + mm + ".mutableCopy()");
          p("\t\t\tx.mergeFrom(other." + mm + ")");
          p("\t\t\tm." + mm + " = x.freeze()");
          p("\t\t} else {");
          p("\t\t\tm." + mm + " = other." + mm);
          p("\t\t}");
        } else {
          p("\t\tm." + mm + " = other." + mm);
        }
        p("\t\tm." + caseMember(o) + " = " + f.getNumber());
      }
      p("\t}");
    }
    p("\tm.unknownFields = append(m.unknownFields, other.unknownFields...)");
    p("}");
    p("");
  }

  static void genEquals(Descriptor m, String g, List<FieldDescriptor> fields, List<OneofDescriptor> oneofs) {
    p("// Java: " + m.getName() + ".equals(Object)");
    p("func (m *" + g + ") Equals(obj any) bool {");
    p("\tother, ok := obj.(*" + g + ")");
    p("\tif !ok || other == nil {");
    p("\t\treturn false");
    p("\t}");
    p("\tif m == other {");
    p("\t\treturn true");
    p("\t}");
    for (FieldDescriptor f : fields) {
      String mm = member(f);
      if (f.getRealContainingOneof() != null) {
        continue;
      }
      if (f.isRepeated()) {
        p("\tif len(m." + mm + ") != len(other." + mm + ") {");
        p("\t\treturn false");
        p("\t}");
        p("\tfor i := range m." + mm + " {");
        p("\t\tif !(" + eq(f, "m." + mm + "[i]", "other." + mm + "[i]") + ") {");
        p("\t\t\treturn false");
        p("\t\t}");
        p("\t}");
      } else if (isMessage(f)) {
        p("\tif m.Has" + camel(f.getName()) + "() != other.Has" + camel(f.getName()) + "() {");
        p("\t\treturn false");
        p("\t}");
        p("\tif m.Has" + camel(f.getName()) + "() && !m." + mm + ".Equals(other." + mm + ") {");
        p("\t\treturn false");
        p("\t}");
      } else if (bit(f) >= 0) {
        p("\tif m.Has" + camel(f.getName()) + "() != other.Has" + camel(f.getName()) + "() {");
        p("\t\treturn false");
        p("\t}");
        p("\tif m.Has" + camel(f.getName()) + "() && !(" + eq(f, "m." + mm, "other." + mm) + ") {");
        p("\t\treturn false");
        p("\t}");
      } else {
        p("\tif !(" + eq(f, "m." + mm, "other." + mm) + ") {");
        p("\t\treturn false");
        p("\t}");
      }
    }
    for (OneofDescriptor o : oneofs) {
      p("\tif m." + caseMember(o) + " != other." + caseMember(o) + " {");
      p("\t\treturn false");
      p("\t}");
      p("\tswitch m." + caseMember(o) + " {");
      for (FieldDescriptor f : o.getFields()) {
        String mm = member(f);
        p("\tcase " + f.getNumber() + ":");
        p("\t\tif !(" + eq(f, "m." + mm, "other." + mm) + ") {");
        p("\t\t\treturn false");
        p("\t\t}");
      }
      p("\t}");
    }
    p("\treturn protoBytesEqual(protoCanonicalUnknownFields(m.unknownFields), protoCanonicalUnknownFields(other.unknownFields))");
    p("}");
    p("");
    p("// HashCode is consistent with Equals. (Java's generated hashCode mixes in");
    p("// the descriptor's identity hash, so its values are not reproducible.)");
    p("func (m *" + g + ") HashCode() int32 {");
    p("\th := int32(41)");
    for (FieldDescriptor f : fields) {
      String mm = member(f);
      String v = "m." + mm;
      if (f.isRepeated()) {
        p("\tfor _, x := range " + v + " {");
        p("\t\th = " + hash(f, "x") + "");
        p("\t}");
      } else if (f.getRealContainingOneof() != null) {
        p("\tif m." + caseMember(f.getRealContainingOneof()) + " == " + f.getNumber() + " {");
        p("\t\th = " + hash(f, v));
        p("\t}");
      } else if (isMessage(f)) {
        p("\tif " + v + " != nil {");
        p("\t\th = " + hash(f, v));
        p("\t}");
      } else {
        p("\th = " + hash(f, v));
      }
    }
    p("\treturn h");
    p("}");
    p("");
  }

  static String eq(FieldDescriptor f, String a, String b) {
    switch (storage(f)) {
      case "[]byte":
        return "protoBytesEqual(" + a + ", " + b + ")";
      case "float64":
        return "protoDoubleBits(" + a + ") == protoDoubleBits(" + b + ")";
      default:
        if (isMessage(f)) {
          return a + ".Equals(" + b + ")";
        }
        return a + " == " + b;
    }
  }

  static String hash(FieldDescriptor f, String v) {
    switch (storage(f)) {
      case "[]byte":
        return "protoHashBytes(h, " + v + ")";
      case "float64":
        return "protoHashInt64(h, protoDoubleBits(" + v + "))";
      case "string":
        return "protoHashString(h, " + v + ")";
      case "bool":
        return "protoHashBool(h, " + v + ")";
      case "int32":
        return "31*h + " + v;
      case "int64":
        return "protoHashInt64(h, " + v + ")";
      default:
        return "31*h + " + v + ".HashCode()";
    }
  }

