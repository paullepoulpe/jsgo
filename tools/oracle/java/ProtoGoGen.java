  // MessageReflection.MergeTarget methods used by TextFormat.merge
  // (internal/jscomp/proto_descriptors.go, proto_text_format.go).

  static void collectMessages(List<Descriptor> out, List<Descriptor> ms) {
    for (Descriptor m : ms) {
      out.add(m);
      collectMessages(out, m.getNestedTypes());
    }
  }

  static void collectEnums(List<EnumDescriptor> out, FileDescriptor fd, List<Descriptor> messages) {
    out.addAll(fd.getEnumTypes());
    for (Descriptor m : messages) {
      out.addAll(m.getEnumTypes());
    }
  }

  static String descVar(Descriptor m) {
    return lowerFirst(goName(m)) + "_descriptor";
  }

