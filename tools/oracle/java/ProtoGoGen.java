  static String appendValue(FieldDescriptor f, String b, String v) {
    switch (f.getType()) {
      case INT32: case ENUM:
        return "protoAppendInt32(" + b + ", " + v + ")";
      case UINT32:
        return "protoAppendUint32(" + b + ", " + v + ")";
      case SINT32:
        return "protoAppendSint32(" + b + ", " + v + ")";
      case INT64: case UINT64:
        return "protoAppendVarint(" + b + ", uint64(" + v + "))";
      case SINT64:
        return "protoAppendSint64(" + b + ", " + v + ")";
      case BOOL:
        return "protoAppendBool(" + b + ", " + v + ")";
      case FIXED32: case SFIXED32:
        return "protoAppendFixed32(" + b + ", uint32(" + v + "))";
      case FIXED64: case SFIXED64:
        return "protoAppendFixed64(" + b + ", uint64(" + v + "))";
      case DOUBLE:
        return "protoAppendDouble(" + b + ", " + v + ")";
      case STRING:
        return "protoAppendString(" + b + ", " + v + ")";
      case BYTES:
        return "protoAppendBytes(" + b + ", " + v + ")";
      default:
        throw new IllegalArgumentException();
    }
  }

  static String readValue(FieldDescriptor f, String r, boolean p3) {
    switch (f.getType()) {
      case INT32: case ENUM:
        return r + ".readInt32()";
      case UINT32:
        return r + ".readUint32()";
      case SINT32:
        return r + ".readSint32()";
      case INT64: case UINT64:
        return r + ".readInt64()";
      case SINT64:
        return r + ".readSint64()";
      case BOOL:
        return r + ".readBool()";
      case FIXED32: case SFIXED32:
        return "int32(" + r + ".readFixed32())";
      case FIXED64: case SFIXED64:
        return "int64(" + r + ".readFixed64())";
      case DOUBLE:
        return r + ".readDouble()";
      case STRING:
        return p3 ? r + ".readStringRequireUtf8()" : r + ".readStringProto2()";
      case BYTES:
        return r + ".readBytes()";
      default:
        throw new IllegalArgumentException();
    }
  }

  static void genSerialization(Descriptor m, String g, List<FieldDescriptor> byNumber) {
    p("// appendTo is " + m.getName() + ".writeTo(CodedOutputStream): fields in number order, then unknown fields.");
    p("func (m *" + g + ") appendTo(b []byte) []byte {");
    for (FieldDescriptor f : byNumber) {
      String mm = member(f);
      int n = f.getNumber();
      if (f.isRepeated()) {
        if (isMessage(f)) {
          p("\tfor _, x := range m." + mm + " {");
          p("\t\tb = protoAppendTag(b, " + n + ", 2)");
          p("\t\tb = protoAppendVarint(b, uint64(x.serializedSize()))");
          p("\t\tb = x.appendTo(b)");
          p("\t}");
        } else if (f.isPacked()) {
          p("\tif len(m." + mm + ") > 0 {");
          p("\t\tvar packed []byte");
          p("\t\tfor _, x := range m." + mm + " {");
          p("\t\t\tpacked = " + appendValue(f, "packed", "x"));
          p("\t\t}");
          p("\t\tb = protoAppendTag(b, " + n + ", 2)");
          p("\t\tb = protoAppendBytes(b, packed)");
          p("\t}");
        } else {
          p("\tfor _, x := range m." + mm + " {");
          p("\t\tb = protoAppendTag(b, " + n + ", " + wireType(f) + ")");
          p("\t\tb = " + appendValue(f, "b", "x"));
          p("\t}");
        }
      } else {
        p("\tif " + present(f, "m") + " {");
        p("\t\tb = protoAppendTag(b, " + n + ", " + wireType(f) + ")");
        if (isMessage(f)) {
          p("\t\tb = protoAppendVarint(b, uint64(m." + mm + ".serializedSize()))");
          p("\t\tb = m." + mm + ".appendTo(b)");
        } else {
          p("\t\tb = " + appendValue(f, "b", "m." + mm));
        }
        p("\t}");
      }
    }
    p("\tif len(m.unknownFields) > 0 {");
    p("\t\tb = append(b, protoCanonicalUnknownFields(m.unknownFields)...)");
    p("\t}");
    p("\treturn b");
    p("}");
    p("");
    p("// serializedSize is getSerializedSize() (memoized once immutable).");
    p("func (m *" + g + ") serializedSize() int {");
    p("\tif m.frozen && m.memoizedSize >= 0 {");
    p("\t\treturn m.memoizedSize");
    p("\t}");
    p("\tsize := 0");
    for (FieldDescriptor f : byNumber) {
      if (isMessage(f)) {
        String mm = member(f);
        int tagSize = tagSize(f.getNumber());
        if (f.isRepeated()) {
          p("\tfor _, x := range m." + mm + " {");
          p("\t\ts := x.serializedSize()");
          p("\t\tsize += " + tagSize + " + protoVarintLen(uint64(s)) + s");
          p("\t}");
        } else {
          p("\tif " + present(f, "m") + " {");
          p("\t\ts := m." + mm + ".serializedSize()");
          p("\t\tsize += " + tagSize + " + protoVarintLen(uint64(s)) + s");
          p("\t}");
        }
      }
    }
    p("\tsize += len(m.appendScalarsOnly(nil))");
    p("\tif m.frozen {");
    p("\t\tm.memoizedSize = size");
    p("\t}");
    p("\treturn size");
    p("}");
    p("");
    p("// appendScalarsOnly encodes the non-message fields and unknown fields (for sizing).");
    p("func (m *" + g + ") appendScalarsOnly(b []byte) []byte {");
    for (FieldDescriptor f : byNumber) {
      if (isMessage(f)) {
        continue;
      }
      String mm = member(f);
      int n = f.getNumber();
      if (f.isRepeated()) {
        if (f.isPacked()) {
          p("\tif len(m." + mm + ") > 0 {");
          p("\t\tvar packed []byte");
          p("\t\tfor _, x := range m." + mm + " {");
          p("\t\t\tpacked = " + appendValue(f, "packed", "x"));
          p("\t\t}");
          p("\t\tb = protoAppendTag(b, " + n + ", 2)");
          p("\t\tb = protoAppendBytes(b, packed)");
          p("\t}");
        } else {
          p("\tfor _, x := range m." + mm + " {");
          p("\t\tb = protoAppendTag(b, " + n + ", " + wireType(f) + ")");
          p("\t\tb = " + appendValue(f, "b", "x"));
          p("\t}");
        }
      } else {
        p("\tif " + present(f, "m") + " {");
        p("\t\tb = protoAppendTag(b, " + n + ", " + wireType(f) + ")");
        p("\t\tb = " + appendValue(f, "b", "m." + mm));
        p("\t}");
      }
    }
    p("\tif len(m.unknownFields) > 0 {");
    p("\t\tb = append(b, protoCanonicalUnknownFields(m.unknownFields)...)");
    p("\t}");
    p("\treturn b");
    p("}");
    p("");
    p("// Java: " + m.getName() + ".getSerializedSize()");
    p("func (m *" + g + ") GetSerializedSize() int { return m.serializedSize() }");
    p("");
    p("// Java: " + m.getName() + ".toByteArray()");
    p("func (m *" + g + ") ToByteArray() []byte { return m.appendTo(make([]byte, 0, m.serializedSize())) }");
    p("");
    p("// Java: " + m.getName() + ".toByteString()");
    p("func (m *" + g + ") ToByteString() []byte { return m.ToByteArray() }");
    p("");
    p("// Java: " + m.getName() + ".isInitialized()");
    p("func (m *" + g + ") IsInitialized() bool { return true }");
    p("");
  }

  static int tagSize(int number) {
    int v = number << 3;
    int n = 1;
    while ((v & ~0x7F) != 0) {
      v >>>= 7;
      n++;
    }
    return n;
  }

  static void genParse(Descriptor m, String g, List<FieldDescriptor> byNumber, boolean p3) {
    p("// mergeFromReader is " + m.getName() + ".Builder.mergeFrom(CodedInputStream) on a mutable m.");
    p("func (m *" + g + ") mergeFromReader(r *protoReader) {");
    p("\tfor {");
    p("\t\tstart := r.pos");
    p("\t\ttag := r.readTag()");
    p("\t\tswitch tag {");
    p("\t\tcase 0:");
    p("\t\t\treturn");
    for (FieldDescriptor f : byNumber) {
      String mm = member(f);
      int n = f.getNumber();
      OneofDescriptor o = f.getRealContainingOneof();
      int wt = wireType(f);
      if (f.isRepeated() && !isMessage(f) && wt != 2) {
        // Accept both packed and unpacked encodings.
        p("\t\tcase " + (n << 3 | wt) + ", " + (n << 3 | 2) + ":");
        p("\t\t\tr.readRepeated(tag, " + wt + ", func(r *protoReader) {");
        if (closedEnum(f)) {
          p("\t\t\t\tv := " + readValue(f, "r", p3));
          p("\t\t\t\tif " + goName(f.getEnumType()) + "_ForNumber(v) == nil {");
          p("\t\t\t\t\tm.unknownFields = protoAppendTag(m.unknownFields, " + n + ", 0)");
          p("\t\t\t\t\tm.unknownFields = protoAppendInt32(m.unknownFields, v)");
          p("\t\t\t\t} else {");
          p("\t\t\t\t\tm." + mm + " = append(m." + mm + ", v)");
          p("\t\t\t\t}");
        } else {
          p("\t\t\t\tm." + mm + " = append(m." + mm + ", " + readValue(f, "r", p3) + ")");
        }
        p("\t\t\t})");
        continue;
      }
      p("\t\tcase " + (n << 3 | wt) + ":");
      if (isMessage(f)) {
        String sub = goName(f.getMessageType());
        p("\t\t\tdata := r.readMessageBytes()");
        if (f.isRepeated()) {
          p("\t\t\tx := &" + sub + "{memoizedSize: -1}");
          p("\t\t\tx.mergeFromReader(r.sub(data))");
          p("\t\t\tx.frozen = true");
          p("\t\t\tm." + mm + " = append(m." + mm + ", x)");
        } else {
          String has = o != null ? "m." + caseMember(o) + " == " + n + " && m." + mm + " != nil" : "m." + mm + " != nil";
          p("\t\t\tvar x *" + sub);
          p("\t\t\tif " + has + " {");
          p("\t\t\t\tx = m." + mm + ".mutableCopy()");
          p("\t\t\t} else {");
          p("\t\t\t\tx = &" + sub + "{memoizedSize: -1}");
          p("\t\t\t}");
          p("\t\t\tx.mergeFromReader(r.sub(data))");
          p("\t\t\tx.frozen = true");
          p("\t\t\tm." + mm + " = x");
          if (o != null) {
            p("\t\t\tm." + caseMember(o) + " = " + n);
          }
        }
      } else if (f.isRepeated()) {
        p("\t\t\tm." + mm + " = append(m." + mm + ", " + readValue(f, "r", p3) + ")");
      } else if (closedEnum(f)) {
        p("\t\t\tv := " + readValue(f, "r", p3));
        p("\t\t\tif " + goName(f.getEnumType()) + "_ForNumber(v) == nil {");
        p("\t\t\t\tm.unknownFields = protoAppendTag(m.unknownFields, " + n + ", 0)");
        p("\t\t\t\tm.unknownFields = protoAppendInt32(m.unknownFields, v)");
        p("\t\t\t} else {");
        p("\t\t\t\tm." + mm + " = v");
        if (bit(f) >= 0) {
          p("\t\t\t\tm.bitField0_ |= 1 << " + bit(f));
        }
        if (o != null) {
          p("\t\t\t\tm." + caseMember(o) + " = " + n);
        }
        p("\t\t\t}");
      } else {
        p("\t\t\tm." + mm + " = " + readValue(f, "r", p3));
        if (bit(f) >= 0) {
          p("\t\t\tm.bitField0_ |= 1 << " + bit(f));
        }
        if (o != null) {
          p("\t\t\tm." + caseMember(o) + " = " + n);
        }
      }
    }
    p("\t\tdefault:");
    p("\t\t\tr.skipField(tag)");
    p("\t\t\tm.unknownFields = append(m.unknownFields, r.b[start:r.pos]...)");
    p("\t\t}");
    p("\t}");
    p("}");
    p("");
  }

  static String textValue(FieldDescriptor f, String v) {
    switch (f.getType()) {
      case INT32: case SINT32: case SFIXED32:
        return "protoTextInt32(" + v + ")";
      case UINT32: case FIXED32:
        return "protoTextUint32(" + v + ")";
      case INT64: case SINT64: case SFIXED64:
        return "protoTextInt64(" + v + ")";
      case UINT64: case FIXED64:
        return "protoTextUint64(" + v + ")";
      case BOOL:
        return "protoTextBool(" + v + ")";
      case DOUBLE:
        return "protoTextDouble(" + v + ")";
      case STRING:
        return "protoTextString(" + v + ")";
      case BYTES:
        return "protoTextBytes(" + v + ")";
      case ENUM:
        return enumConv(f) + "_text(" + v + ")";
      default:
        throw new IllegalArgumentException();
    }
  }

  static void genText(Descriptor m, String g, List<FieldDescriptor> byNumber) {
    p("func (m *" + g + ") printText(p *protoTextPrinter) {");
    for (FieldDescriptor f : byNumber) {
      String mm = member(f);
      String name = f.getName();
      if (f.isRepeated()) {
        p("\tfor _, x := range m." + mm + " {");
        if (isMessage(f)) {
          p("\t\tp.message(\"" + name + "\", x.printText)");
        } else {
          p("\t\tp.scalar(\"" + name + "\", " + textValue(f, "x") + ")");
        }
        p("\t}");
      } else {
        p("\tif " + present(f, "m") + " {");
        if (isMessage(f)) {
          p("\t\tp.message(\"" + name + "\", m." + mm + ".printText)");
        } else {
          p("\t\tp.scalar(\"" + name + "\", " + textValue(f, "m." + mm) + ")");
        }
        p("\t}");
      }
    }
    p("\tp.unknownFields(m.unknownFields)");
    p("}");
    p("");
    p("// String is " + m.getName() + ".toString() (protobuf text format).");
    p("func (m *" + g + ") String() string {");
    p("\tp := &protoTextPrinter{}");
    p("\tm.printText(p)");
    p("\treturn p.sb.String()");
    p("}");
    p("");
  }

