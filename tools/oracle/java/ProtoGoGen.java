  /** Statements that mark field f as set on b.m (presence bit / oneof case). */
  static String markSet(FieldDescriptor f) {
    OneofDescriptor o = f.getRealContainingOneof();
    if (o != null) {
      StringBuilder r = new StringBuilder();
      for (FieldDescriptor other : o.getFields()) {
        if (other != f) {
          r.append("\tb.m.").append(member(other)).append(" = ").append(zero(other)).append("\n");
        }
      }
      r.append("\tb.m.").append(caseMember(o)).append(" = ").append(f.getNumber()).append("\n");
      return r.toString();
    }
    if (bit(f) >= 0) {
      return "\tb.m.bitField0_ |= 1 << " + bit(f) + "\n";
    }
    return "";
  }

