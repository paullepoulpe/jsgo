#!/usr/bin/env python3
# File-level dependency analysis of the Go `jscomp` package (the Java jscomp
# SCC: jscomp + deps, graph, lint, modules, transpile, type, ...). Same-package
# Java references need no import, so dependencies are found by matching
# identifiers (comments and strings stripped) against top-level class names.
# Files are condensed into SCCs and each SCC gets a level: 1 + the highest
# level among its dependencies. Files on the same level can be ported in
# parallel once all lower levels exist. Writes docs/port-waves.md.
#
# usage: python3 -I tools/oracle/jscompdeps.py .cache/closure-src/com/google/javascript out.json [docs/port-waves.md]
import os, re, sys, collections, json
root = sys.argv[1]  # .cache/closure-src/com/google/javascript
pkgs = ['jscomp','jscomp/bundle','jscomp/deps','jscomp/disambiguate','jscomp/graph','jscomp/ijs','jscomp/instrumentation','jscomp/js','jscomp/lint','jscomp/modules','jscomp/serialization','jscomp/transpile','jscomp/type','refactoring']
files = {}
for p in pkgs:
    d = os.path.join(root, p)
    if not os.path.isdir(d): continue
    for f in sorted(os.listdir(d)):
        if f.endswith('.java'):
            files[f[:-5] if p == 'jscomp' else p.split('/')[-1] + '/' + f[:-5]] = os.path.join(d, f)
def strip(src):
    src = re.sub(r'/\*.*?\*/', ' ', src, flags=re.S)
    src = re.sub(r'//[^\n]*', ' ', src)
    src = re.sub(r'"""(.*?)"""', '""', src, flags=re.S)
    src = re.sub(r'"(\\.|[^"\\\n])*"', '""', src)
    src = re.sub(r"'(\\.|[^'\\\n])*'", "''", src)
    return src
def sloc(src):
    return sum(1 for l in src.split('\n') if l.strip())
simple = {}  # simple class name -> key
for k in files:
    simple[k.split('/')[-1]] = k
code = {k: strip(open(v, encoding='utf-8').read()) for k, v in files.items()}
size = {k: sloc(c) for k, c in code.items()}
deps = {}
for k, c in code.items():
    ids = set(re.findall(r'\b[A-Z][A-Za-z0-9_]*\b', c))
    deps[k] = sorted(simple[i] for i in ids if i in simple and simple[i] != k)
# Tarjan
sys.setrecursionlimit(100000)
idx, low, st, on, comps, c = {}, {}, [], set(), [], [0]
def sc(v):
    idx[v] = low[v] = c[0]; c[0] += 1; st.append(v); on.add(v)
    for w in deps[v]:
        if w not in idx: sc(w); low[v] = min(low[v], low[w])
        elif w in on: low[v] = min(low[v], idx[w])
    if low[v] == idx[v]:
        comp = []
        while True:
            w = st.pop(); on.discard(w); comp.append(w)
            if w == v: break
        comps.append(sorted(comp))
for v in sorted(deps):
    if v not in idx: sc(v)
compof = {v: i for i, comp in enumerate(comps) for v in comp}
# level = longest path from leaves (comps are in reverse topo order already)
level = {}
for i, comp in enumerate(comps):
    lv = 0
    for v in comp:
        for w in deps[v]:
            j = compof[w]
            if j != i: lv = max(lv, level[j] + 1)
    level[i] = lv
print('files', len(files), 'sloc', sum(size.values()), 'sccs', len(comps))
big = sorted(comps, key=lambda cp: -sum(size[v] for v in cp))[:5]
for cp in big:
    print(f'SCC of {len(cp)} files, {sum(size[v] for v in cp)} sloc: e.g. {cp[:12]}')
bylevel = collections.defaultdict(lambda: [0, 0])
for i, comp in enumerate(comps):
    bylevel[level[i]][0] += len(comp); bylevel[level[i]][1] += sum(size[v] for v in comp)
print('levels (files, sloc):', dict(sorted(bylevel.items())))
json.dump({'deps': deps, 'size': size, 'comps': comps, 'level': {str(i): level[i] for i in level}}, open(sys.argv[2], 'w'))

if len(sys.argv) > 3:
    out = ['# jscomp porting waves', '',
           'Generated by `tools/oracle/jscompdeps.py` from the pinned Java sources. Each level',
           'depends only on lower levels (and on packages below `jscomp`: `rhino` incl. `jstype`,',
           '`parsing`, `parser`, `sourcemap`, `regex`, ...). Files in one level can be ported in',
           'parallel. Multi-file SCCs (marked) must be ported together: their files reference',
           'each other.', '',
           f'{len(files)} files, {sum(size.values())} SLOC, {len(comps)} SCCs.', '']
    for lv in sorted(set(level.values())):
        cs = [comps[i] for i in level if level[i] == lv]
        n = sum(len(c) for c in cs); sl = sum(size[v] for c in cs for v in c)
        out.append(f'## Level {lv}: {n} files, {sl} SLOC')
        out.append('')
        for c in sorted(cs, key=lambda c: -sum(size[v] for v in c)):
            if len(c) > 1:
                out.append(f'- **SCC of {len(c)} files ({sum(size[v] for v in c)} SLOC):** ' + ', '.join(f'{v} ({size[v]})' for v in sorted(c, key=lambda v: -size[v])))
            else:
                out.append(f'- {c[0]} ({size[c[0]]})')
        out.append('')
    open(sys.argv[3], 'w').write('\n'.join(out))
