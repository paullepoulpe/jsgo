package main

// The Java side: every class of the pinned jar that belongs to the Go
// package internal/jscomp (PORTING.md §2), with the Go names PORTING.md §3
// gives its members.

import (
	"sort"
	"strings"
	"unicode"
)

// jscompPackages are the Java packages of the Go package internal/jscomp.
var jscompPackages = []string{
	"com/google/javascript/jscomp/",
	"com/google/javascript/refactoring/",
}

// otherGoPackages maps Java package prefixes (longest first) to the Go
// package holding their classes.
var otherGoPackages = []struct{ java, goPath, goName string }{
	{"com/google/javascript/jscomp/parsing/parser/", "github.com/paullepoulpe/jsgo/internal/parser", "parser"},
	{"com/google/javascript/jscomp/parsing/", "github.com/paullepoulpe/jsgo/internal/parsing", "parsing"},
	{"com/google/javascript/jscomp/base/", "github.com/paullepoulpe/jsgo/internal/base", "base"},
	{"com/google/javascript/jscomp/colors/", "github.com/paullepoulpe/jsgo/internal/colors", "colors"},
	{"com/google/javascript/jscomp/diagnostic/", "github.com/paullepoulpe/jsgo/internal/diagnostic", "diagnostic"},
	{"com/google/javascript/jscomp/resources/", "github.com/paullepoulpe/jsgo/internal/resources", "resources"},
	{"com/google/javascript/jscomp/regex/", "github.com/paullepoulpe/jsgo/internal/regex", "regex"},
	{"com/google/javascript/rhino/dtoa/", "github.com/paullepoulpe/jsgo/internal/dtoa", "dtoa"},
	{"com/google/javascript/rhino/", "github.com/paullepoulpe/jsgo/internal/rhino", "rhino"},
	{"com/google/debugging/sourcemap/", "github.com/paullepoulpe/jsgo/internal/sourcemap", "sourcemap"},
}

// goPackageOf returns the Go package of a Java class: "" for
// internal/jscomp, else the import path and name.
func goPackageOf(internalName string) (path, name string, ok bool) {
	for _, p := range otherGoPackages {
		if strings.HasPrefix(internalName, p.java) {
			return p.goPath, p.goName, true
		}
	}
	for _, p := range jscompPackages {
		if strings.HasPrefix(internalName, p) {
			return "", "", true
		}
	}
	return "", "", false
}

func inJscomp(internalName string) bool {
	path, _, ok := goPackageOf(internalName)
	return ok && path == ""
}

// Kind is how a pending Java class is declared in Go.
type Kind int

const (
	KindStruct Kind = iota // concrete class without subclasses: *T
	KindIface              // interface, abstract class, class with subclasses: T
	KindEnum               // enum: type T int32
)

// Model indexes the jar.
type Model struct {
	classes    map[string]*ClassInfo
	subclasses map[string][]string
	goNames    map[string]string // internal name → Go type name (jscomp SCC)
	byGoName   map[string]*ClassInfo
}

func newModel(classes map[string]*ClassInfo) *Model {
	m := &Model{
		classes:    classes,
		subclasses: map[string][]string{},
		goNames:    map[string]string{},
		byGoName:   map[string]*ClassInfo{},
	}
	for _, c := range classes {
		if c.Super != "" {
			m.subclasses[c.Super] = append(m.subclasses[c.Super], c.Name)
		}
		for _, i := range c.Interfaces {
			m.subclasses[i] = append(m.subclasses[i], c.Name)
		}
	}
	// Simple names that more than one jscomp-SCC top-level class uses: the
	// ones outside the root jscomp package are prefixed with their package
	// (e.g. deps/SourceFile → Deps_SourceFile), as the ports do.
	simpleCount := map[string]int{}
	for name, c := range classes {
		if !inJscomp(name) || c.OuterOf != "" || c.Anonymous {
			continue
		}
		simpleCount[c.SimpleName]++
	}
	var names []string
	for name := range classes {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		c := classes[name]
		if !inJscomp(name) || c.Anonymous {
			continue
		}
		g := m.computeGoName(c, simpleCount)
		if g == "" {
			continue
		}
		m.goNames[name] = g
		m.byGoName[g] = c
	}
	return m
}

func (m *Model) computeGoName(c *ClassInfo, simpleCount map[string]int) string {
	if c.OuterOf != "" {
		outer, ok := m.classes[c.OuterOf]
		if !ok || outer.Anonymous {
			return ""
		}
		og := m.computeGoName(outer, simpleCount)
		if og == "" {
			return ""
		}
		return og + "_" + c.SimpleName
	}
	dir := c.Name[:strings.LastIndexByte(c.Name, '/')]
	if simpleCount[c.SimpleName] > 1 && dir != "com/google/javascript/jscomp" {
		pkg := dir[strings.LastIndexByte(dir, '/')+1:]
		return capitalize(pkg) + "_" + c.SimpleName
	}
	return c.SimpleName
}

// topLevel returns the top-level class enclosing c.
func (m *Model) topLevel(c *ClassInfo) *ClassInfo {
	for c.OuterOf != "" {
		o, ok := m.classes[c.OuterOf]
		if !ok {
			break
		}
		c = o
	}
	return c
}

// javaFile is the source path of a top-level class, e.g.
// com/google/javascript/jscomp/Foo.java.
func (m *Model) javaFile(c *ClassInfo) string {
	return m.topLevel(c).Name + ".java"
}

func (m *Model) isAutoGenerated(name string) bool {
	simple := name[strings.LastIndexByte(name, '/')+1:]
	return strings.HasPrefix(simple, "AutoValue_") || strings.HasPrefix(simple, "AutoBuilder_")
}

// kind is how class c is declared in Go (PORTING.md §4): an enum, an
// interface (Java interfaces, abstract classes and classes with subclasses,
// except AutoValue/AutoBuilder ones, which are plain structs), or a struct.
func (m *Model) kind(c *ClassInfo) Kind {
	if c.Access&accEnum != 0 {
		return KindEnum
	}
	if c.Access&accInterface != 0 {
		return KindIface
	}
	subs := m.subclasses[c.Name]
	real := 0
	for _, s := range subs {
		if !m.isAutoGenerated(s) {
			real++
		}
	}
	if real > 0 {
		return KindIface
	}
	if c.Access&accAbstract != 0 && len(subs) == 0 {
		return KindIface
	}
	return KindStruct
}

// supertypes lists c's superclass and interfaces, transitively, nearest
// first.
func (m *Model) supertypes(c *ClassInfo) []string {
	var out []string
	seen := map[string]bool{}
	queue := []string{}
	if c.Super != "" {
		queue = append(queue, c.Super)
	}
	queue = append(queue, c.Interfaces...)
	for len(queue) > 0 {
		n := queue[0]
		queue = queue[1:]
		if seen[n] {
			continue
		}
		seen[n] = true
		out = append(out, n)
		if s, ok := m.classes[n]; ok {
			if s.Super != "" {
				queue = append(queue, s.Super)
			}
			queue = append(queue, s.Interfaces...)
		}
	}
	return out
}

// methodsNamed returns the methods of c (then its supertypes) with the
// given Java name, skipping synthetic/bridge methods and those overridden
// by an earlier class (same descriptor).
func (m *Model) methodsNamed(c *ClassInfo, name string, static bool) []methodRef {
	var out []methodRef
	seenDesc := map[string]bool{}
	visit := func(cls *ClassInfo) {
		for i, mi := range cls.Methods {
			if mi.Name != name || mi.Access&(accSynthetic|accBridge) != 0 {
				continue
			}
			if (mi.Access&accStatic != 0) != static {
				continue
			}
			if seenDesc[mi.Desc] {
				continue
			}
			seenDesc[mi.Desc] = true
			out = append(out, methodRef{cls, mi, i})
		}
	}
	visit(c)
	if !static {
		for _, s := range m.supertypes(c) {
			if sc, ok := m.classes[s]; ok {
				visit(sc)
			}
		}
	}
	return out
}

// fieldNamed finds a field of c or its superclasses.
func (m *Model) fieldNamed(c *ClassInfo, name string, static bool) *fieldRef {
	cls := c
	for cls != nil {
		for i, f := range cls.Fields {
			if f.Name == name && (f.Access&accStatic != 0) == static {
				return &fieldRef{cls, f, i}
			}
		}
		if static {
			break
		}
		cls = m.classes[cls.Super]
	}
	return nil
}

type methodRef struct {
	owner *ClassInfo
	m     *MethodInfo
	index int
}

type fieldRef struct {
	owner *ClassInfo
	f     *FieldInfo
	index int
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

func decapitalize(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

// methodSig parses the generic signature of a method, or its descriptor.
func methodSig(mi *MethodInfo) *JMethodSig {
	if mi.Signature != "" {
		sig := parseMethodSig(mi.Signature)
		// Signatures of inner-class constructors omit the synthetic outer
		// parameter that the descriptor has; the descriptor's parameter
		// count wins.
		d := parseMethodSig(mi.Desc)
		if len(d.Params) == len(sig.Params) {
			return sig
		}
		return d
	}
	return parseMethodSig(mi.Desc)
}

func fieldType(f *FieldInfo) *JType {
	if f.Signature != "" {
		return parseFieldType(f.Signature)
	}
	return parseFieldType(f.Desc)
}

// classTypeParams returns the type parameters of a class, from its
// signature.
func classTypeParams(c *ClassInfo) []JTypeParam {
	if c.Signature == "" {
		return nil
	}
	tps, _ := parseClassSig(c.Signature)
	return tps
}
