package main

// Rendering the pending declarations as Go source, with Java types mapped
// to Go types the way the ports map them (PORTING.md §3, §6).

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"go/types"
	"sort"
	"strconv"
	"strings"
)

const header = `// Code generated by tools/pending; DO NOT EDIT.

// Pending declarations (PORTING.md §1, the one sanctioned exception): the
// not-yet-ported Java classes that the files of this package (tests
// included) reference, with exactly the members those files use.
// Signatures are derived from the pinned closure-compiler jar. Every
// function body panics with &PendingPort{...} (pending_port.go), which
// RunJUnit4 reports as a skip. A static field keeps its Java value when it
// is a constant, a DiagnosticType or a DiagnosticGroup; any other static
// field is its zero value (an empty collection for collection types).
//
// Regenerate with ` + "`go run ./tools/pending`" + ` after every merge: a declaration
// disappears as soon as the real port of its class lands.
`

// renderer accumulates one rendering of the file.
type renderer struct {
	g       *Gen
	imports map[string]string // path → name
}

func (g *Gen) render() []byte {
	r := &renderer{g: g, imports: map[string]string{}}
	var body bytes.Buffer
	var names []string
	for n := range g.classes {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		r.class(&body, g.classes[n])
	}
	var out bytes.Buffer
	out.WriteString(header)
	out.WriteString("\npackage jscomp\n\n")
	if len(r.imports) > 0 {
		var paths []string
		for p := range r.imports {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		out.WriteString("import (\n")
		for _, std := range []bool{true, false} {
			wrote := false
			for _, p := range paths {
				if !strings.Contains(p, ".") == std {
					fmt.Fprintf(&out, "\t%q\n", p)
					wrote = true
				}
			}
			if std && wrote {
				out.WriteString("\n")
			}
		}
		out.WriteString(")\n\n")
	}
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes()
	}
	return src
}

func (r *renderer) use(path, name string) string {
	r.imports[path] = name
	return name
}

func javaDotted(internal string) string {
	return strings.ReplaceAll(strings.ReplaceAll(internal, "/", "."), "$", ".")
}

// javaClassLabel is the simple, dotted class name (Outer.Inner).
func (g *Gen) javaClassLabel(c *ClassInfo) string {
	name := c.Name[strings.LastIndexByte(c.Name, '/')+1:]
	return strings.ReplaceAll(name, "$", ".")
}

func (r *renderer) class(w *bytes.Buffer, p *PClass) {
	g := r.g
	c := p.c
	members := sortedMembers(p.members)
	needType := p.typeNeeded || p.kind == KindEnum || len(members) > 0
	for _, m := range p.statics {
		if m.kind == MCtor || m.kind == MEnumConst {
			needType = true
		}
	}
	if needType {
		fmt.Fprintf(w, "// %s is pending.\n//\n// Java class: %s\n", p.goName, javaDotted(c.Name))
	}
	switch {
	case !needType:
	case p.funcSig != nil:
		params, results := r.methodParts(p.funcSig, false)
		fmt.Fprintf(w, "//\n// Java: %s (functional interface)\ntype %s func(%s)%s\n\n", r.javaSig(p.funcSig), p.goName, params, results)
		return
	case p.kind == KindEnum:
		fmt.Fprintf(w, "type %s int32\n\n", p.goName)
	case p.kind == KindIface:
		fmt.Fprintf(w, "type %s interface {\n", p.goName)
		for _, e := range r.embeddedIfaces(p) {
			fmt.Fprintf(w, "\t%s\n", e)
		}
		for _, m := range members {
			switch m.kind {
			case MMethod:
				params, results := r.methodParts(m.method, false)
				fmt.Fprintf(w, "\t// Java: %s\n\t%s(%s)%s\n", r.javaSig(m.method), m.goName, params, results)
			case MGoIfaceMethod:
				// covered by the embedded interface
			case MField:
				g.warn(fmt.Sprintf("field %s.%s of an interface-kind class cannot be declared", p.goName, m.goName))
			}
		}
		w.WriteString("}\n\n")
	default:
		fmt.Fprintf(w, "type %s struct {\n", p.goName)
		for _, m := range members {
			if m.kind == MField {
				fmt.Fprintf(w, "\t// Java: %s %s.%s\n\t%s %s\n", javaSimpleName(fieldType(m.field.f)), g.javaClassLabel(m.field.owner), m.field.f.Name, m.goName, r.goTypeNullable(fieldType(m.field.f), m.field.f.Nullable))
			}
		}
		w.WriteString("}\n\n")
	}
	// Package-level members: constructors, static fields, enum constants,
	// static methods.
	statics := sortedMembers(p.statics)
	for _, m := range statics {
		switch m.kind {
		case MEnumConst:
			ord := 0
			for _, f := range m.field.owner.Fields {
				if f.Access&accEnum != 0 {
					if f == m.field.f {
						break
					}
					ord++
				}
			}
			fmt.Fprintf(w, "// Java: %s.%s (ordinal %d)\nconst %s %s = %d\n\n", g.javaClassLabel(m.field.owner), m.field.f.Name, ord, m.goName, p.goName, ord)
		case MStaticVar:
			r.staticVar(w, p, m)
		case MCtor:
			params, _ := r.methodParts(m.method, true)
			ret := p.goName
			if p.kind == KindStruct {
				ret = "*" + ret
			}
			sig := r.javaSig(m.method)
			fmt.Fprintf(w, "// Java: %s\nfunc %s(%s) %s {\n\tpanic(&PendingPort{Signature: %s})\n}\n\n", sig, m.goName, params, ret, strconv.Quote(sig))
		case MStaticFunc:
			params, results := r.methodParts(m.method, true)
			sig := r.javaSig(m.method)
			fmt.Fprintf(w, "// Java: %s\nfunc %s(%s)%s {\n\tpanic(&PendingPort{Signature: %s})\n}\n\n", sig, m.goName, params, results, strconv.Quote(sig))
		}
	}
	if p.kind == KindIface {
		return
	}
	recv := "*" + p.goName
	if p.kind == KindEnum {
		recv = p.goName
	}
	for _, m := range members {
		switch m.kind {
		case MMethod:
			params, results := r.methodParts(m.method, false)
			sig := r.javaSig(m.method)
			fmt.Fprintf(w, "// Java: %s\nfunc (%s) %s(%s)%s {\n\tpanic(&PendingPort{Signature: %s})\n}\n\n", sig, recv, m.goName, params, results, strconv.Quote(sig))
		case MGoIfaceMethod:
			params, results := r.goSigParts(m.goSig)
			label := g.javaClassLabel(c) + "." + decapitalize(m.goName) + " (for " + m.goIface + ")"
			if ref := g.javaMethodForGo(c, m.goName, m.goSig.Params().Len()); ref != nil {
				label = r.javaSig(&methodRef{owner: c, m: ref.m, index: ref.index})
			}
			fmt.Fprintf(w, "// Java: %s\nfunc (%s) %s(%s)%s {\n\tpanic(&PendingPort{Signature: %s})\n}\n\n", label, recv, m.goName, params, results, strconv.Quote(label))
		case MAsAdapter:
			label := g.javaClassLabel(c) + " as " + javaDotted(m.asType)
			fmt.Fprintf(w, "// Go-only: language-adapter — %s\nfunc (%s) %s() %s {\n\tpanic(&PendingPort{Signature: %s})\n}\n\n", label, recv, m.goName, r.goType(&JType{Kind: JClass, Class: m.asType}), strconv.Quote(label))
		}
	}
}

// embeddedIfaces lists the interfaces an interface-kind pending class
// embeds: the ported Go interfaces and pending interfaces among its Java
// supertypes.
func (r *renderer) embeddedIfaces(p *PClass) []string {
	g := r.g
	var out []string
	seen := map[string]bool{}
	direct := append([]string{}, p.c.Interfaces...)
	if p.c.Super != "" {
		direct = append([]string{p.c.Super}, direct...)
	}
	for _, s := range direct {
		if sp, ok := g.classes[g.model.goNames[s]]; ok && g.model.goNames[s] != "" {
			if sp.kind == KindIface && !seen[sp.goName] {
				seen[sp.goName] = true
				out = append(out, sp.goName)
			}
			continue
		}
		if iface, name := g.realInterface(s); iface != nil && !seen[name] {
			seen[name] = true
			if i := strings.IndexByte(name, '.'); i >= 0 {
				path, pkgName, _ := goPackageOf(s)
				r.use(path, pkgName)
			}
			out = append(out, name)
		}
	}
	return out
}

func (r *renderer) staticVar(w *bytes.Buffer, p *PClass, m *PMember) {
	g := r.g
	f := m.field.f
	jt := fieldType(f)
	gt := r.goTypeNullable(jt, f.Nullable)
	label := fmt.Sprintf("%s.%s", g.javaClassLabel(m.field.owner), f.Name)
	if f.Constant != nil && f.Access&accFinal != 0 {
		var lit string
		switch f.Constant.tag {
		case 8:
			lit = goQuote(f.Constant.str)
		case 3, 5:
			if jt.Kind == JPrim && jt.Prim == 'Z' {
				lit = strconv.FormatBool(f.Constant.i64 != 0)
			} else if jt.Kind == JPrim && jt.Prim == 'C' {
				lit = fmt.Sprintf("uint16(%d)", f.Constant.i64)
			} else {
				lit = strconv.FormatInt(f.Constant.i64, 10)
			}
		case 4, 6:
			lit = strconv.FormatFloat(f.Constant.f64, 'g', -1, 64)
		}
		if lit != "" {
			fmt.Fprintf(w, "// Java: %s\nconst %s = %s\n\n", label, m.goName, lit)
			return
		}
	}
	if init, ok := m.field.owner.StaticInits[f.Name]; ok && (gt == "*DiagnosticType" || gt == "*DiagnosticGroup") {
		expr := init.Expr
		for _, ref := range init.Refs {
			expr = strings.ReplaceAll(expr, "\x00"+ref[0]+"."+ref[1]+"\x00", g.staticFieldGoName(ref[0], ref[1]))
		}
		fmt.Fprintf(w, "// Java: %s\nvar %s = %s\n\n", label, m.goName, expr)
		return
	}
	for _, coll := range []string{"LinkedHashSet", "LinkedHashMap", "ArrayList", "ObjectLinkedHashSet", "ObjectLinkedHashMap"} {
		prefix := "*jutil." + coll + "["
		if strings.HasPrefix(gt, prefix) {
			fmt.Fprintf(w, "// Java: %s (value pending: empty)\nvar %s = jutil.New%s[%s]()\n\n", label, m.goName, coll, gt[len(prefix):len(gt)-1])
			return
		}
	}
	fmt.Fprintf(w, "// Java: %s (value pending: zero)\nvar %s %s\n\n", label, m.goName, gt)
}

// javaSig renders a member like the `// Java:` lines: Class.method(Types)
// or Class(Types) for constructors.
func (r *renderer) javaSig(ref *methodRef) string {
	label := r.g.javaClassLabel(ref.owner)
	sig := methodSig(ref.m)
	params := javaParamList(sig, ref.m.Access&accVarargs != 0)
	if ref.m.Name == "<init>" {
		return label + "(" + params + ")"
	}
	return label + "." + ref.m.Name + "(" + params + ")"
}

// hasVariance reports whether a parameter type's type arguments (or array
// element) contain a type variable or a bounded wildcard.
func hasVariance(t *JType) bool {
	var inner func(t *JType) bool
	inner = func(t *JType) bool {
		switch t.Kind {
		case JTypeVar:
			return true
		case JWildcard:
			return t.Bound != nil
		case JArray:
			return inner(t.Elem)
		}
		for _, a := range t.Args {
			if inner(a) {
				return true
			}
		}
		return false
	}
	if t.Kind == JArray {
		return inner(t.Elem)
	}
	for _, a := range t.Args {
		if inner(a) {
			return true
		}
	}
	return false
}

var goKeywords = map[string]bool{}

func init() {
	for tok := token.BREAK; tok <= token.VAR; tok++ {
		if tok.IsKeyword() {
			goKeywords[tok.String()] = true
		}
	}
	for _, n := range []string{"string", "int", "bool", "any", "error", "len", "cap", "new", "make", "copy", "append", "byte", "rune", "nil", "true", "false", "iota", "close", "delete", "panic", "print", "println", "real", "imag", "complex", "min", "max", "clear", "recover"} {
		goKeywords[n] = true
	}
}

// methodParts renders a method's Go parameter list and result.
func (r *renderer) methodParts(ref *methodRef, static bool) (string, string) {
	sig := methodSig(ref.m)
	var params []string
	used := map[string]bool{}
	for i, pt := range sig.Params {
		name := ""
		if i < len(ref.m.ParamNames) {
			name = ref.m.ParamNames[i]
		}
		if name == "" || strings.ContainsAny(name, "$<>") {
			name = fmt.Sprintf("p%d", i)
		}
		if goKeywords[name] {
			name += "_"
		}
		for used[name] {
			name += "_"
		}
		used[name] = true
		var gt string
		if ref.m.Access&accVarargs != 0 && i == len(sig.Params)-1 && pt.Kind == JArray {
			gt = "..." + r.goType(pt.Elem)
		} else if hasVariance(pt) {
			// Go has no variance: a Collection<? extends Foo> or a
			// StaticSymbolTable<S, R> parameter accepts any concrete
			// instantiation in Java, so the declaration takes any.
			gt = "any"
		} else {
			gt = r.goTypeNullable(pt, ref.m.NullableParams[i])
		}
		params = append(params, name+" "+gt)
	}
	result := ""
	if ref.m.Name != "<init>" && !(sig.Result.Kind == JPrim && sig.Result.Prim == 'V') {
		result = " " + r.goTypeNullable(sig.Result, ref.m.NullableReturn)
	}
	_ = static
	return strings.Join(params, ", "), result
}

// goSigParts renders a go/types signature (for methods of ported Go
// interfaces).
func (r *renderer) goSigParts(sig *types.Signature) (string, string) {
	q := func(p *types.Package) string {
		if p.Path() == jscompPath {
			return ""
		}
		return r.use(p.Path(), p.Name())
	}
	var params []string
	for i := 0; i < sig.Params().Len(); i++ {
		v := sig.Params().At(i)
		name := v.Name()
		if name == "" || name == "_" {
			name = fmt.Sprintf("p%d", i)
		}
		t := types.TypeString(v.Type(), q)
		if sig.Variadic() && i == sig.Params().Len()-1 {
			t = "..." + strings.TrimPrefix(t, "[]")
		}
		params = append(params, name+" "+t)
	}
	result := ""
	switch sig.Results().Len() {
	case 0:
	case 1:
		result = " " + types.TypeString(sig.Results().At(0).Type(), q)
	default:
		var rs []string
		for i := 0; i < sig.Results().Len(); i++ {
			rs = append(rs, types.TypeString(sig.Results().At(i).Type(), q))
		}
		result = " (" + strings.Join(rs, ", ") + ")"
	}
	return strings.Join(params, ", "), result
}

func goQuote(s string) string {
	return strconv.Quote(s)
}

// goTypeNullable maps a top-level parameter, result or field type: a
// @Nullable String (or boxed primitive) is a pointer, as in the ports.
func (r *renderer) goTypeNullable(t *JType, nullable bool) string {
	gt := r.goType(t)
	if nullable && t.Kind == JClass {
		switch gt {
		case "string", "int", "int64", "bool", "float64", "float32", "uint16":
			return "*" + gt
		}
	}
	return gt
}

// goType maps a Java type to the Go type the ports use for it.
func (r *renderer) goType(t *JType) string {
	switch t.Kind {
	case JPrim:
		return map[byte]string{'Z': "bool", 'B': "byte", 'C': "uint16", 'S': "int16", 'I': "int", 'J': "int64", 'F': "float32", 'D': "float64", 'V': ""}[t.Prim]
	case JArray:
		return "[]" + r.goType(t.Elem)
	case JTypeVar:
		return "any"
	case JWildcard:
		if t.Bound == nil || t.Super {
			return "any"
		}
		return r.goType(t.Bound)
	}
	arg := func(i int) string {
		if i < len(t.Args) {
			return r.goType(t.Args[i])
		}
		return "any"
	}
	jutil := func(s string) string { r.use("github.com/paullepoulpe/jsgo/internal/jutil", "jutil"); return s }
	switch t.Class {
	case "java/lang/String", "java/lang/CharSequence":
		return "string"
	case "java/lang/Object":
		return "any"
	case "java/lang/Integer", "java/lang/Short", "java/lang/Byte":
		return "int"
	case "java/lang/Long":
		return "int64"
	case "java/lang/Boolean":
		return "bool"
	case "java/lang/Double":
		return "float64"
	case "java/lang/Float":
		return "float32"
	case "java/lang/Character":
		return "uint16"
	case "java/lang/Void":
		return "struct{}"
	case "java/lang/Iterable":
		// As the ports do (JSChunk.getInputsIterable, PrebuildAst.prebuild).
		r.use("iter", "iter")
		return "iter.Seq[" + arg(0) + "]"
	case "java/util/Collection", "java/util/List", "java/util/Queue", "java/util/Deque",
		"com/google/common/collect/ImmutableList", "com/google/common/collect/ImmutableCollection",
		"java/util/stream/Stream", "com/google/common/collect/FluentIterable", "java/util/SortedSet",
		"com/google/common/collect/ImmutableSortedSet":
		return "[]" + arg(0)
	case "java/util/ArrayList", "java/util/LinkedList", "java/util/ArrayDeque":
		return jutil("*jutil.ArrayList[" + arg(0) + "]")
	case "java/util/Set", "java/util/HashSet", "java/util/LinkedHashSet", "com/google/common/collect/ImmutableSet", "java/util/EnumSet":
		return jutil("*jutil.LinkedHashSet[" + arg(0) + "]")
	case "java/util/Map", "java/util/HashMap", "java/util/LinkedHashMap", "com/google/common/collect/ImmutableMap",
		"java/util/concurrent/ConcurrentHashMap", "java/util/concurrent/ConcurrentMap", "java/util/IdentityHashMap",
		"java/util/EnumMap", "com/google/common/collect/ImmutableSortedMap", "java/util/SortedMap":
		return jutil("*jutil.LinkedHashMap[" + arg(0) + ", " + arg(1) + "]")
	case "java/util/TreeMap":
		return jutil("*jutil.TreeMap[" + arg(0) + ", " + arg(1) + "]")
	case "java/util/TreeSet":
		return jutil("*jutil.TreeSet[" + arg(0) + "]")
	case "com/google/common/collect/Multimap", "com/google/common/collect/ListMultimap", "com/google/common/collect/ArrayListMultimap",
		"com/google/common/collect/ImmutableListMultimap", "com/google/common/collect/LinkedHashMultimap", "com/google/common/collect/ImmutableMultimap",
		"com/google/common/collect/LinkedListMultimap":
		return jutil("*jutil.ListMultimap[" + arg(0) + ", " + arg(1) + "]")
	case "com/google/common/collect/SetMultimap", "com/google/common/collect/ImmutableSetMultimap", "com/google/common/collect/HashMultimap":
		return jutil("*jutil.SetMultimap[" + arg(0) + ", " + arg(1) + "]")
	case "com/google/common/collect/Multiset", "com/google/common/collect/ImmutableMultiset", "com/google/common/collect/HashMultiset":
		return jutil("*jutil.ImmutableMultiset[" + arg(0) + "]")
	case "com/google/common/collect/BiMap", "com/google/common/collect/HashBiMap", "com/google/common/collect/ImmutableBiMap":
		return jutil("*jutil.BiMap[" + arg(0) + ", " + arg(1) + "]")
	case "com/google/common/collect/Table", "com/google/common/collect/HashBasedTable":
		return jutil("*jutil.HashBasedTable[" + arg(0) + ", " + arg(1) + ", " + arg(2) + "]")
	case "java/util/Optional", "com/google/common/base/Optional":
		a := arg(0)
		if a == "string" || a == "int" || a == "bool" || a == "int64" || a == "float64" {
			return "*" + a
		}
		return a
	case "java/util/function/Supplier", "java/util/concurrent/Callable":
		return "func() " + arg(0)
	case "java/util/function/Function":
		return "func(" + arg(0) + ") " + arg(1)
	case "java/util/function/BiFunction":
		return "func(" + arg(0) + ", " + arg(1) + ") " + arg(2)
	case "java/util/function/UnaryOperator":
		return "func(" + arg(0) + ") " + arg(0)
	case "java/util/function/BinaryOperator":
		return "func(" + arg(0) + ", " + arg(0) + ") " + arg(0)
	case "java/util/function/Predicate", "com/google/common/base/Predicate":
		return "func(" + arg(0) + ") bool"
	case "java/util/function/BiPredicate":
		return "func(" + arg(0) + ", " + arg(1) + ") bool"
	case "java/util/function/Consumer":
		return "func(" + arg(0) + ")"
	case "java/util/function/BiConsumer":
		return "func(" + arg(0) + ", " + arg(1) + ")"
	case "java/util/function/ToIntFunction":
		return "func(" + arg(0) + ") int"
	case "java/lang/Runnable":
		return "func()"
	case "java/util/Comparator":
		return "func(a, b " + arg(0) + ") int"
	case "java/util/Iterator":
		r.use("iter", "iter")
		return "iter.Seq[" + arg(0) + "]"
	case "java/io/PrintStream":
		return jutil("*jutil.PrintStream")
	case "java/nio/file/Path":
		return jutil("*jutil.Path")
	case "java/nio/charset/Charset":
		return jutil("*jutil.Charset")
	case "java/util/logging/Logger":
		return jutil("*jutil.Logger")
	case "java/util/logging/Level":
		return jutil("*jutil.Level")
	case "java/io/OutputStream", "java/io/ByteArrayOutputStream":
		r.use("io", "io")
		return "io.Writer"
	case "java/io/InputStream", "java/io/ByteArrayInputStream":
		r.use("io", "io")
		return "io.Reader"
	case "java/io/Reader":
		return jutil("jutil.JavaReader")
	case "java/io/Writer":
		return jutil("*jutil.Writer")
	case "java/lang/Appendable":
		return jutil("jutil.Appendable")
	case "java/lang/StringBuilder":
		return jutil("*jutil.StringBuilder")
	case "java/lang/Throwable", "java/lang/Exception", "java/lang/RuntimeException":
		return jutil("jutil.Throwable")
	case "java/lang/Class":
		r.use("reflect", "reflect")
		return "reflect.Type"
	case "java/util/regex/Pattern":
		return jutil("*jutil.Pattern")
	case "java/math/BigInteger":
		r.use("math/big", "big")
		return "*big.Int"
	case "java/net/URI":
		return jutil("*jutil.URI")
	case "java/util/Random":
		return jutil("*jutil.Random")
	case "java/util/BitSet":
		return jutil("*jutil.BitSet")
	case "java/io/File":
		return "string"
	}
	path, pkgName, ok := goPackageOf(t.Class)
	if !ok {
		r.g.warn("no Go mapping for Java type " + javaDotted(t.Class) + " (using any)")
		return "any"
	}
	c, known := r.g.model.classes[t.Class]
	if !known {
		return "any"
	}
	if path == "" {
		name := r.g.model.goNames[t.Class]
		if obj := r.g.realObject(name); obj != nil {
			return r.realTypeRef("", name, obj, t)
		}
		p := r.g.typeOf(c)
		if p == nil {
			r.g.warn(fmt.Sprintf("Java type %s is ported but %s is not defined (using any)", javaDotted(t.Class), name))
			return "any"
		}
		if p.kind == KindStruct {
			return "*" + p.goName
		}
		return p.goName
	}
	name := r.g.otherGoName(c)
	pkg := r.g.importedPackage(path)
	if pkg == nil {
		return "any"
	}
	obj := pkg.Scope().Lookup(name)
	if obj == nil {
		r.g.warn(fmt.Sprintf("Java type %s: no %s.%s (using any)", javaDotted(t.Class), pkgName, name))
		return "any"
	}
	r.use(path, pkgName)
	return r.realTypeRef(pkgName, name, obj, t)
}

// realTypeRef refers to a ported Go type: a pointer for structs, the type
// itself otherwise, instantiated with the Java type arguments if generic.
func (r *renderer) realTypeRef(pkgName, name string, obj types.Object, t *JType) string {
	tn, ok := obj.(*types.TypeName)
	if !ok {
		return "any"
	}
	ref := name
	if pkgName != "" {
		ref = pkgName + "." + name
	}
	if named, ok := tn.Type().(*types.Named); ok && named.TypeParams().Len() > 0 {
		var args []string
		for i := 0; i < named.TypeParams().Len(); i++ {
			if i < len(t.Args) && len(t.Args) == named.TypeParams().Len() {
				args = append(args, r.goType(t.Args[i]))
			} else {
				args = append(args, "any")
			}
		}
		ref += "[" + strings.Join(args, ", ") + "]"
	}
	if _, isStruct := tn.Type().Underlying().(*types.Struct); isStruct {
		return "*" + ref
	}
	return ref
}
