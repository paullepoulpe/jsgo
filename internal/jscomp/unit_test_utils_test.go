// UnitTestUtils are helpers for JSCompiler unit tests.

// UnitTestUtils_UpdateGenericVarNamesInExpectedFilesWithMapping: NOTE:
// Prefer to not directly call this method. Instead, call
// CompilerTestCase.setGenericNameReplacements from your test setup.
//
// Replaces the generic variable names in each of the expected test output
// files with a specific name.
//
// The specific name is generated by using the replacement value as prefix
// and appending the calculated uniqueID hashString based on the
// corresponding test's input file.
//
// The vars created during certain compiler passes have a filePath based
// uniqueID in them. For readability of tests, this uniqueID is obfuscated
// by using a generic name, e.g. `TAGGED_TEMPLATE_TMP_VAR` in the test
// sources. This function replaces that generic name by a specific name
// consisting of the runtime-computed uniqueID before test execution.
//
// inputs: input FlatSources. Does not work for ChunkSources. outputs:
// expected sources. replacementPrefixes: mapping from generic variable
// names and actual variable name prefix. genericNameReplacements: Out.
// Mapping from actual variable names to their resolved generic names.
// Returns the updated output files with correct runtime variable names.
//
// Java: UnitTestUtils.updateGenericVarNamesInExpectedFiles(FlatSources, Expected, ImmutableMap<String, String>, Map<String, String>)
func UnitTestUtils_UpdateGenericVarNamesInExpectedFilesWithMapping(
	inputs *CompilerTestCase_FlatSources,
	outputs *CompilerTestCase_Expected,
	replacementPrefixes *jutil.LinkedHashMap[string, string],
	genericNameReplacements *jutil.LinkedHashMap[string, string]) []*SourceFile {
	jutil.CheckState(inputs != nil)
	// In FlatSources, we correspond each input SourceFile (i.e. each CompilerInput) with an
	// expected SourceFile. We can know what uniqueID to generate in the expected string by knowing
	// its CompilerInput.
	// ChunkSources consist of JSChunks, and each chunk has multiple CompilerInputs which can
	// correspond to an expected SourceFile. The uniqueID in the expected code could come from code
	// in any of those CompilerInputs, i.e. we do not know what uniqueID to generate in the expected
	// string. Hence ChunkSources are unsupported.
	inLength := len(inputs.sources)
	outLength := len(outputs.expected)
	jutil.CheckArgument(inLength == outLength)

	updatedOutputs := []*SourceFile{}
	for i := 0; i < inLength; i++ {
		inputScript := inputs.sources[i]
		outputScript := outputs.expected[i]

		// UniqueIDSupplier creates IDs by hashing input's file name.
		fileHashCode := jutil.StringHashCode(inputScript.GetName())
		var fileHashString string
		if fileHashCode < 0 {
			fileHashString = "m" + fmt.Sprint(-fileHashCode)
		} else {
			fileHashString = fmt.Sprint(fileHashCode)
		}
		expectedCodeFileName := outputScript.GetName()
		expectedCode := outputScript.GetCode()
		for shortName, prefix := range replacementPrefixes.All() {
			longName := prefix + fileHashString
			expectedCode = strings.ReplaceAll(expectedCode, shortName, longName)
			genericNameReplacements.Put(longName, shortName)
		}
		updatedOutputs = append(updatedOutputs, SourceFile_FromCode(expectedCodeFileName, expectedCode))
	}
	return updatedOutputs
}

// Java: UnitTestUtils.updateGenericVarNamesInExpectedFiles(FlatSources, Expected, ImmutableMap<String, String>)
func UnitTestUtils_UpdateGenericVarNamesInExpectedFiles(
	inputs *CompilerTestCase_FlatSources, outputs *CompilerTestCase_Expected, replacementPrefixes *jutil.LinkedHashMap[string, string]) []*SourceFile {
	return UnitTestUtils_UpdateGenericVarNamesInExpectedFilesWithMapping(
		inputs, outputs, replacementPrefixes, jutil.NewLinkedHashMap[string, string]())
}
