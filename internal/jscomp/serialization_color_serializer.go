// ColorSerializer serializes `Color`s and information about them into a
// `TypePool`.
//
// Client code should call `addColor()` for each of the colors it wants to
// have included in the `TypePool`, then call `generateTypePool()` to get the
// result.
type ColorSerializer struct {
	serializationMode *SerializationOptions
	// Used to find the index at which a `String` will appear in the
	// `StringPoolProto` that will eventually be serialized with the
	// `TypePool` generated by this `ColorSerializer`.
	getStringPoolIndexFn func(string) int
	// Only property names that pass this predicate will be serialized.
	propertyFilter func(string) bool
	// Optional combined fast path that checks if a property is used and returns
	// its stringPool index in a single lookup.
	lookupUsedPropIndexFn func(string) (int, bool)

	// Stores the `Integer` values assigned to `Color`s as they are added for
	// serialization, so they can be looked up and used for references
	// between the output `TypeProto`s.
	colorIdToTypePointer map[colors.ColorId]int
	lastColor            *colors.Color
	lastPointer          int

	// Stores the `Color`s to be serialized in the order they will be
	// serialized.
	//
	// This is used as a worklist when the `TypePool` is generated.
	colorsInSerializedOrder []*colors.Color

	typeProtoSlab  jutil.Slab[TypeProto]
	objProtoSlab   jutil.Slab[ObjectTypeProto]
	unionProtoSlab jutil.Slab[UnionTypeProto]
	edgeSlab       jutil.Slab[SubtypingEdge]
	int32Slab      []int32
	scratchInt32s  []int32
}

// NewColorSerializer creates a ColorSerializer.
//
// serializationMode determines what parts of the `TypePool` proto to fill
// in. stringPoolIndexFn is used to request an integer index to encode in
// place of string value. The `TypePool` generated by this object will use
// these indices, so a `StringPoolProto` that contains the actual `String`
// values needs to be serialized along with it. Property names for which
// propertyFilter returns `false` will not be included in the generated
// `TypeProto`s.
//
// Java: ColorSerializer(SerializationOptions, Function<String, Integer>, Predicate<String>)
func NewColorSerializer(
	serializationMode *SerializationOptions,
	stringPoolIndexFn func(string) int,
	propertyFilter func(string) bool) *ColorSerializer {
	s := &ColorSerializer{
		serializationMode:       serializationMode,
		getStringPoolIndexFn:    stringPoolIndexFn,
		propertyFilter:          propertyFilter,
		colorIdToTypePointer:    make(map[colors.ColorId]int, 1024),
		colorsInSerializedOrder: make([]*colors.Color, 0, 1024),
	}
	// We must pre-populate the type pointers with the few axiomatic colors
	// that won't actually be serialized. These types are required to get the
	// first few offsets in the order they are specified by
	// `TypePointers.OFFSET_TO_AXIOMATIC_COLOR`.
	for _, color := range TypePointers_OFFSET_TO_AXIOMATIC_COLOR {
		s.AddColor(color)
	}
	return s
}

// AddColors adds a collection of `Color`s to the list of those that must be
// serialized, and returns the `Integer`s that will refer to the input
// `Color`s in the TypePool` that this object will create. The order will
// match the order of the input `Color`s.
//
// Java: ColorSerializer.addColors(Collection<Color>)
func (s *ColorSerializer) AddColors(cs []*colors.Color) []int {
	builder := make([]int, 0, len(cs))
	for _, color := range cs {
		builder = append(builder, s.AddColor(color))
	}
	return builder
}

// AddColor adds `color` to the list of those that must be serialized (if it
// wasn't already there) and returns the `Integer` value that will refer to
// it in the `TypePool` that this object will create.
//
// Java: ColorSerializer.addColor(Color)
func (s *ColorSerializer) AddColor(color *colors.Color) int {
	if color == s.lastColor && color != nil {
		return s.lastPointer
	}
	id := color.GetId()
	idx, ok := s.colorIdToTypePointer[id]
	if !ok {
		idx = len(s.colorsInSerializedOrder)
		s.colorsInSerializedOrder = append(s.colorsInSerializedOrder, color)
		s.colorIdToTypePointer[id] = idx
	}
	s.lastColor = color
	s.lastPointer = idx
	return idx
}

func (s *ColorSerializer) allocTypeProto() *TypeProto {
	return s.typeProtoSlab.New()
}

func (s *ColorSerializer) allocObjectTypeProto() *ObjectTypeProto {
	return s.objProtoSlab.New()
}

func (s *ColorSerializer) allocUnionTypeProto() *UnionTypeProto {
	return s.unionProtoSlab.New()
}

func (s *ColorSerializer) allocSubtypingEdge(subtype, supertype int32) *SubtypingEdge {
	e := s.edgeSlab.New()
	edgeSize := 0
	if subtype != 0 {
		edgeSize += 1 + protoVarintLen(uint64(int64(subtype)))
	}
	if supertype != 0 {
		edgeSize += 1 + protoVarintLen(uint64(int64(supertype)))
	}
	*e = SubtypingEdge{
		subtype_:     subtype,
		supertype_:   supertype,
		frozen:       true,
		memoizedSize: edgeSize,
	}
	return e
}

func (s *ColorSerializer) allocInt32Slice(src []int32) []int32 {
	n := len(src)
	if n == 0 {
		return nil
	}
	if len(s.int32Slab) < n {
		s.int32Slab = make([]int32, max(n, 4096))
	}
	out := s.int32Slab[:n:n]
	s.int32Slab = s.int32Slab[n:]
	copy(out, src)
	return out
}

func (s *ColorSerializer) addColorSliceInt32s(cs []*colors.Color) []int32 {
	if len(cs) == 0 {
		return nil
	}
	tmp := s.scratchInt32s[:0]
	for _, c := range cs {
		tmp = append(tmp, int32(s.AddColor(c)))
	}
	s.scratchInt32s = tmp
	return s.allocInt32Slice(tmp)
}

func (s *ColorSerializer) ownPropertyInt32s(color *colors.Color) []int32 {
	props := color.GetOwnProperties()
	if len(props) == 0 {
		return nil
	}
	tmp := s.scratchInt32s[:0]
	if s.lookupUsedPropIndexFn != nil {
		for _, ownProperty := range props {
			if idx, ok := s.lookupUsedPropIndexFn(ownProperty); ok {
				tmp = append(tmp, int32(idx))
			}
		}
	} else {
		for _, ownProperty := range props {
			if s.propertyFilter(ownProperty) {
				tmp = append(tmp, int32(s.getStringPoolIndexFn(ownProperty)))
			}
		}
	}
	s.scratchInt32s = tmp
	return s.allocInt32Slice(tmp)
}

// GenerateTypePool generates a `TypePool` proto built from the previously
// added `Color`s and the arguments supplied to this method.
//
// getDisambiguationSupertypesFn: given a `Color` return a set of `Color`s it
// inherits from. getMismatchSourceRefsFn may be `null` if this
// `serializationMode` does not include debug info. Otherwise, this function
// must provide a set of all the source reference strings indicating code
// locations where the given `Color` encountered a type mismatch.
//
// Java: ColorSerializer.generateTypePool(Function<Color, ImmutableSet<Color>>, Function<Color, ImmutableSet<String>>)
func (s *ColorSerializer) GenerateTypePool(
	getDisambiguationSupertypesFn func(*colors.Color) *jutil.ObjectLinkedHashSet[*colors.Color],
	getMismatchSourceRefsFn func(*colors.Color) *jutil.LinkedHashSet[string]) *TypePool {
	startIdx := TypePointers_UntrimOffset(0)
	initialCap := max(0, len(s.colorsInSerializedOrder)-startIdx)
	var types []*TypeProto
	if initialCap > 0 {
		types = make([]*TypeProto, 0, initialCap)
	}
	var disambiguationEdges []*SubtypingEdge
	// We use an indexed loop here for 2 reasons.
	// 1. We must skip serialization of the axiomatic colors that start our
	//    list of serialized colors.
	// 2. The logic in the loop may end up adding more colors to the list.
	//    It's often hard to tell what effect changing an iterable will have on
	//    an iteration that is in progress.
	for i := startIdx; i < len(s.colorsInSerializedOrder); i++ {
		color := s.colorsInSerializedOrder[i]
		typePointer := int32(i)
		types = append(types, s.GenerateTypeProto(color))
		for supertype := range getDisambiguationSupertypesFn(color).All() {
			disambiguationEdges = append(disambiguationEdges, s.allocSubtypingEdge(typePointer, int32(s.AddColor(supertype))))
		}
	}

	var debugInfoProto *TypePool_DebugInfo
	if s.serializationMode.IncludeDebugInfo() {
		jutil.CheckNotNull(getMismatchSourceRefsFn)
		debugInfoBuilder := TypePool_DebugInfo_NewBuilder()

		// Construct a map from source reference string to type pointers,
		// because that's the way the Mismatch protos work.
		// Construct entries only for those colors that we have actually
		// serialized in order to save space.
		srcRefToTypePointerList := jutil.NewLinkedHashMap[string, []int32]()
		for i, color := range s.colorsInSerializedOrder {
			typePointer := int32(i)
			for srcRef := range getMismatchSourceRefsFn(color).All() {
				srcRefToTypePointerList.Put(srcRef, append(srcRefToTypePointerList.Get(srcRef), typePointer))
			}
		}

		// Now use the map to build the Mismatch protos and put them into the
		// debug info.
		for key, value := range srcRefToTypePointerList.All() {
			debugInfoBuilder.
				AddMismatchBuilder().
				SetSourceRef(key).
				AddAllInvolvedColor(value)
		}
		debugInfoProto = debugInfoBuilder.Build()
	}
	return &TypePool{
		type_:                types,
		disambiguationEdges_: disambiguationEdges,
		debugInfo_:           debugInfoProto,
		frozen:               true,
		memoizedSize:         -1,
	}
}

func (s *ColorSerializer) GenerateTypeProto(color *colors.Color) *TypeProto {
	tp := s.allocTypeProto()
	if color.IsUnion() {
		up := s.allocUnionTypeProto()
		members := s.addColorSliceInt32s(color.GetUnionElements())
		uSize := 0
		if len(members) > 0 {
			p := protoPackedInt32PayloadSize(members)
			uSize = 1 + protoVarintLen(uint64(p)) + p
		}
		*up = UnionTypeProto{
			unionMember_: members,
			frozen:       true,
			memoizedSize: uSize,
		}
		*tp = TypeProto{
			union_:       up,
			kindCase_:    TypeProto_UNION_FIELD_NUMBER,
			frozen:       true,
			memoizedSize: 1 + protoVarintLen(uint64(uSize)) + uSize,
		}
	} else {
		op := s.allocObjectTypeProto()
		inst := s.addColorSliceInt32s(color.GetInstanceColors())
		own := s.ownPropertyInt32s(color)
		protos := s.addColorSliceInt32s(color.GetPrototypes())
		closureAssert := color.IsClosureAssert()
		isInvalidating := color.IsInvalidating()
		markedCtor := color.IsConstructor()
		keepOrig := color.GetPropertiesKeepOriginalName()
		uuid := color.GetId().AsByteString()
		oSize := 0
		if isInvalidating {
			oSize += 2
		}
		if len(uuid) != 0 {
			oSize += 1 + protoVarintLen(uint64(len(uuid))) + len(uuid)
		}
		if keepOrig {
			oSize += 2
		}
		if len(inst) > 0 {
			p := protoPackedInt32PayloadSize(inst)
			oSize += 1 + protoVarintLen(uint64(p)) + p
		}
		if len(protos) > 0 {
			p := protoPackedInt32PayloadSize(protos)
			oSize += 1 + protoVarintLen(uint64(p)) + p
		}
		if markedCtor {
			oSize += 2
		}
		if len(own) > 0 {
			p := protoPackedInt32PayloadSize(own)
			oSize += 1 + protoVarintLen(uint64(p)) + p
		}
		if closureAssert {
			oSize += 2
		}
		*op = ObjectTypeProto{
			instanceType_:               inst,
			ownProperty_:                own,
			prototype_:                  protos,
			closureAssert_:              closureAssert,
			isInvalidating_:             isInvalidating,
			markedConstructor_:          markedCtor,
			propertiesKeepOriginalName_: keepOrig,
			uuid_:                       uuid,
			frozen:                      true,
			memoizedSize:                oSize,
		}
		*tp = TypeProto{
			object_:      op,
			kindCase_:    TypeProto_OBJECT_FIELD_NUMBER,
			frozen:       true,
			memoizedSize: 1 + protoVarintLen(uint64(oSize)) + oSize,
		}
	}
	return tp
}

func (s *ColorSerializer) GetOwnPropertyStringPoolOffsets(color *colors.Color) []int {
	var builder []int
	for _, ownProperty := range color.GetOwnProperties() {
		// The client code may know that some properties are unused in the
		// AST, so there's no need to serialize them.
		if s.propertyFilter(ownProperty) {
			builder = append(builder, s.getStringPoolIndexFn(ownProperty))
		}
	}
	return builder
}
