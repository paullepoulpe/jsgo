// PhaseOptimizer is an object that optimizes the order of compiler passes.
type PhaseOptimizer struct {
	compiler          AbstractCompiler
	changeTracker     *ChangeTracker
	tracker           *PerformanceTracker
	passes            []CompilerPass
	inLoop            bool
	validityCheck     *PassFactory
	printAstHashcodes bool

	// These fields are used during optimization loops.
	// They are declared here for two reasons:
	// 1) Loop and ScopedChangeHandler can communicate via shared state
	// 2) Compiler talks to PhaseOptimizer, not Loop or ScopedChangeHandler
	currentPass *PhaseOptimizer_NamedPass
	// For each pass, remember the time at the end of the pass's last run.
	lastRuns *jutil.LinkedHashMap[*PhaseOptimizer_NamedPass, int32]
	// The time of the last change made to the program by any pass.
	lastChange int32
	jsRoot     *rhino.Node

	useSizeHeuristicToStopOptimizationLoop bool

	// Checks that passes have reported code changes correctly.
	changeVerifier *ChangeVerifier

	// See CompilerOptions#optimizationLoopMaxIterations
	optimizationLoopMaxIterations int
}

var PhaseOptimizer_logger = jutil.Logger_GetLogger("com.google.javascript.jscomp.PhaseOptimizer")

const PhaseOptimizer_START_TIME int32 = 0

// PhaseOptimizer_State: when processing loopable passes in order, the
// PhaseOptimizer can be in one of these two states.
//
// This enum is used by Loop/process only, but enum types can't be local.
//
// Java: PhaseOptimizer.State
type PhaseOptimizer_State int32

const (
	PhaseOptimizer_State_RUN_PASSES_NOT_RUN_IN_PREV_ITER PhaseOptimizer_State = iota
	PhaseOptimizer_State_RUN_PASSES_THAT_CHANGED_STH_IN_PREV_ITER
)

var phaseOptimizer_State_names = [...]string{
	"RUN_PASSES_NOT_RUN_IN_PREV_ITER", "RUN_PASSES_THAT_CHANGED_STH_IN_PREV_ITER",
}

// Java: PhaseOptimizer.State.values()
func PhaseOptimizer_State_values() []PhaseOptimizer_State {
	return []PhaseOptimizer_State{
		PhaseOptimizer_State_RUN_PASSES_NOT_RUN_IN_PREV_ITER,
		PhaseOptimizer_State_RUN_PASSES_THAT_CHANGED_STH_IN_PREV_ITER,
	}
}

// String is Enum.name().
func (s PhaseOptimizer_State) String() string { return phaseOptimizer_State_names[s] }

// Ordinal is Enum.ordinal().
func (s PhaseOptimizer_State) Ordinal() int { return int(s) }

var PhaseOptimizer_CODE_REMOVING_PASSES = []string{PassNames_PEEPHOLE_OPTIMIZATIONS}

const PhaseOptimizer_MAX_LOOPS = 100

const PhaseOptimizer_OPTIMIZE_LOOP_ERROR = "Fixed point loop exceeded the maximum number of iterations."

// NewPhaseOptimizer: comp is the compiler that owns/creates this; tracker
// is an optional performance tracker (may be nil).
//
// Java: PhaseOptimizer(AbstractCompiler, PerformanceTracker)
func NewPhaseOptimizer(comp AbstractCompiler, tracker *PerformanceTracker) *PhaseOptimizer {
	p := &PhaseOptimizer{}
	p.printAstHashcodes = false
	p.compiler = comp
	p.jsRoot = comp.GetJsRoot()
	p.tracker = tracker
	p.changeTracker = comp.GetChangeTracker()
	p.passes = nil
	p.inLoop = false
	p.lastChange = PhaseOptimizer_START_TIME
	p.useSizeHeuristicToStopOptimizationLoop =
		comp.GetOptions().ShouldUseSizeHeuristicToStopOptimizationLoop()
	maxIterations := comp.GetOptions().GetMaxOptimizationLoopIterations()
	if maxIterations > 0 && maxIterations <= PhaseOptimizer_MAX_LOOPS {
		p.optimizationLoopMaxIterations = maxIterations
	} else {
		p.optimizationLoopMaxIterations = PhaseOptimizer_MAX_LOOPS
	}
	return p
}

// Consume adds the passes generated by the given factories to the compile
// sequence.
//
// Automatically pulls multi-run passes into fixed point loops. If there are
// 1 or more multi-run passes in a row, they will run together in the same
// fixed point loop. The passes will run until they are finished making
// changes.
//
// The PhaseOptimizer is free to tweak the order and frequency of multi-run
// passes in a fixed-point loop.
//
// Java: PhaseOptimizer.consume(List<PassFactory>)
func (p *PhaseOptimizer) Consume(factories []*PassFactory) {
	currentLoop := NewPhaseOptimizer_Loop(p)
	for _, factory := range factories {
		if factory.IsRunInFixedPointLoop() {
			currentLoop.AddLoopedPass(factory)
		} else {
			if currentLoop.IsPopulated() {
				p.passes = append(p.passes, currentLoop)
				currentLoop = NewPhaseOptimizer_Loop(p)
			}
			p.AddOneTimePass(factory)
		}
	}

	if currentLoop.IsPopulated() {
		p.passes = append(p.passes, currentLoop)
	}
}

// AddOneTimePass adds the pass generated by the given factory to the compile
// sequence. This pass will be run once.
//
// Java: PhaseOptimizer.addOneTimePass(PassFactory)
func (p *PhaseOptimizer) AddOneTimePass(factory *PassFactory) {
	p.passes = append(p.passes, NewPhaseOptimizer_NamedPass(p, factory))
}

// AddFixedPointLoop adds a loop to the compile sequence. This loop will
// continue running until the AST stops changing.
//
// Returns the loop structure. Pass suppliers should be added to the loop.
//
// Java: PhaseOptimizer.addFixedPointLoop()
func (p *PhaseOptimizer) AddFixedPointLoop() *PhaseOptimizer_Loop {
	loop := NewPhaseOptimizer_Loop(p)
	p.passes = append(p.passes, loop)
	return loop
}

// SetValidityCheck adds a checker to be run after every pass. Intended for
// development.
//
// Java: PhaseOptimizer.setValidityCheck(PassFactory)
func (p *PhaseOptimizer) SetValidityCheck(validityCheck *PassFactory) {
	p.validityCheck = validityCheck
	p.changeVerifier = NewChangeVerifier(p.compiler).Snapshot(p.jsRoot)
}

// SetPrintAstHashcodes sets the hashcode of the AST to be logged every pass.
// Intended for development.
//
// Java: PhaseOptimizer.setPrintAstHashcodes(boolean)
func (p *PhaseOptimizer) SetPrintAstHashcodes(printAstHashcodes bool) {
	p.printAstHashcodes = printAstHashcodes
}

// Process runs all the passes in the optimizer.
//
// Java: PhaseOptimizer.process(Node, Node)
func (p *PhaseOptimizer) Process(externs *rhino.Node, root *rhino.Node) {
	defer evictCachedReusableCfgs()
	// When looking at this code, one can mistakenly think that the instance of
	// PhaseOptimizer keeps all compiler passes live. This would be undesirable. A pass can
	// create large data structures that are only useful to the pass, and we shouldn't
	// retain them until the end of the compilation. But if you look at
	// NamedPass#process, the actual pass is created and immediately executed, and no
	// reference to it is retained in PhaseOptimizer:
	//   factory.create(compiler).process(externs, root);
	for _, pass := range p.passes {
		if Platform_IsThreadInterrupted() {
			panic(jutil.NewRuntimeExceptionWithCause(jutil.NewInterruptedException()))
		}
		pass.Process(externs, root)
		if p.HasHaltingErrors() {
			return
		}
	}
}

// Java: PhaseOptimizer.maybePrintAstHashcodes(String, Node)
func (p *PhaseOptimizer) MaybePrintAstHashcodes(passName string, root *rhino.Node) {
	if p.printAstHashcodes {
		hashCodeMsg :=
			"AST hashCode after " + passName + ": " +
				jutil.ToJavaString(jutil.StringHashCode(p.compiler.ToSourceOfNode(root)))
		PhaseOptimizer_logger.Info(hashCodeMsg)
	}
}

// MaybeRunValidityCheck runs the validity check if it is available.
//
// Java: PhaseOptimizer.maybeRunValidityCheck(String, Node, Node)
func (p *PhaseOptimizer) MaybeRunValidityCheck(passName string, externs *rhino.Node, root *rhino.Node) {
	if p.validityCheck == nil {
		return
	}
	jutil.Try(func() {
		p.validityCheck.Create(p.compiler).Process(externs, root)
		p.changeVerifier.CheckRecordedChangesWithPassName(passName, p.jsRoot)
	}, func(e jutil.IRuntimeException) {
		panic(jutil.NewIllegalStateExceptionWithMessageAndCause("Validity checks failed for pass: "+passName, e))
	})
}

// Java: PhaseOptimizer.hasHaltingErrors()
func (p *PhaseOptimizer) HasHaltingErrors() bool {
	return p.compiler.HasHaltingErrors()
}

// PhaseOptimizer_NamedPass is a single compiler pass.
type PhaseOptimizer_NamedPass struct {
	outer *PhaseOptimizer

	name    string
	factory *PassFactory
	tracer  *Tracer
}

// Java: PhaseOptimizer.NamedPass(PassFactory)
func NewPhaseOptimizer_NamedPass(outer *PhaseOptimizer, factory *PassFactory) *PhaseOptimizer_NamedPass {
	n := &PhaseOptimizer_NamedPass{}
	n.outer = outer
	n.name = factory.GetName()
	n.factory = factory
	return n
}

// Java: PhaseOptimizer.NamedPass.process(Node, Node)
func (n *PhaseOptimizer_NamedPass) Process(externs *rhino.Node, root *rhino.Node) {
	p := n.outer
	PhaseOptimizer_logger.Fine("Running pass " + n.name)
	n.factory.ValidatePreconditions(p.compiler.GetOptions())
	if p.validityCheck != nil {
		// Before running the pass, clone the AST so you can check the
		// changed AST against the clone after the pass finishes.
		p.changeVerifier = NewChangeVerifier(p.compiler).Snapshot(p.jsRoot)
	}
	if p.tracker != nil {
		p.tracker.RecordPassStart(n.name, !n.factory.IsRunInFixedPointLoop())
	}
	tracerType := "Compiler"
	n.tracer = NewTracerWithType(&tracerType, &n.name)

	p.compiler.BeforePass(n.name)

	// Delay the creation of the actual pass until *after* all previous passes
	// have been processed.
	// Some precondition checks rely on this, eg, in CoalesceVariableNames.
	n.factory.Create(p.compiler).Process(externs, root)

	p.compiler.AfterPass(n.name)

	jutil.Try(func() {
		// Don't move this line in the IF. We create a Tracer even when the tracker
		// is null; so we must also stop the tracer when the tracker is null.
		// Otherwise, Tracer.ThreadTrace#events can become too big.
		traceRuntime := n.tracer.Stop()
		if p.tracker != nil {
			p.tracker.RecordPassStop(n.name, traceRuntime)
		}
		p.MaybePrintAstHashcodes(n.name, root)
		p.MaybeRunValidityCheck(n.name, externs, root)
	}, func(e jutil.IIllegalStateException) {
		// TODO(johnlenz): Remove this once the normalization checks report
		// errors instead of exceptions.
		panic(jutil.NewRuntimeExceptionWithMessageAndCause("Validity check failed for "+n.name, e))
	})
}

// Java: PhaseOptimizer.NamedPass.toString()
func (n *PhaseOptimizer_NamedPass) String() string {
	return "pass: " + n.name
}

// Java: PhaseOptimizer.hasScopeChanged(Node)
func (p *PhaseOptimizer) HasScopeChanged(n *rhino.Node) bool {
	// Outside loops we don't track changed scopes, so we visit them all.
	if !p.inLoop {
		return true
	}
	timeOfLastRun, ok := p.lastRuns.Lookup(p.currentPass)
	if !ok {
		// Go-only: language-adapter — unboxing the null Integer that Map.get
		// returns for a missing key.
		panic(jutil.NewNullPointerException())
	}
	// A pass looks at all functions when it first runs
	return timeOfLastRun == PhaseOptimizer_START_TIME || n.GetChangeTime() > timeOfLastRun
}

// PhaseOptimizer_ScopedChangeHandler is a change handler that marks scopes
// as changed when reportChange is called.
type PhaseOptimizer_ScopedChangeHandler struct {
	outer *PhaseOptimizer

	lastCodeChangeQuery int32
}

// Java: PhaseOptimizer.ScopedChangeHandler()
func NewPhaseOptimizer_ScopedChangeHandler(outer *PhaseOptimizer) *PhaseOptimizer_ScopedChangeHandler {
	h := &PhaseOptimizer_ScopedChangeHandler{}
	h.outer = outer
	h.lastCodeChangeQuery = outer.changeTracker.GetChangeStamp()
	return h
}

// Java: PhaseOptimizer.ScopedChangeHandler.reportChange()
func (h *PhaseOptimizer_ScopedChangeHandler) ReportChange() {
	h.outer.lastChange = h.outer.changeTracker.GetChangeStamp()
}

// Java: PhaseOptimizer.ScopedChangeHandler.hasCodeChangedSinceLastCall()
func (h *PhaseOptimizer_ScopedChangeHandler) HasCodeChangedSinceLastCall() bool {
	result := h.outer.lastChange > h.lastCodeChangeQuery
	h.lastCodeChangeQuery = h.outer.changeTracker.GetChangeStamp()
	// The next call to the method will happen at a different time
	h.outer.changeTracker.IncrementChangeStamp()
	return result
}

// PhaseOptimizer_Loop is a compound pass that contains atomic passes and
// runs them until they reach a fixed point.
//
// Notice that this is a non-static class, because it includes the closure
// of PhaseOptimizer.
type PhaseOptimizer_Loop struct {
	outer *PhaseOptimizer

	myPasses                        []*PhaseOptimizer_NamedPass
	myNames                         *jutil.LinkedHashSet[string]
	scopeHandler                    *PhaseOptimizer_ScopedChangeHandler
	isCodeRemovalLoop               bool
	howmanyIterationsUnderThreshold int
}

// Java: PhaseOptimizer.Loop()
func NewPhaseOptimizer_Loop(outer *PhaseOptimizer) *PhaseOptimizer_Loop {
	l := &PhaseOptimizer_Loop{}
	l.outer = outer
	l.myNames = jutil.NewLinkedHashSet[string]()
	l.isCodeRemovalLoop = false
	l.howmanyIterationsUnderThreshold = 0
	return l
}

// Java: PhaseOptimizer.Loop.addLoopedPass(PassFactory)
func (l *PhaseOptimizer_Loop) AddLoopedPass(factory *PassFactory) {
	name := factory.GetName()
	jutil.CheckArgumentMsg1(
		!l.myNames.Contains(name), "Already a pass with name '%s' in this loop", name)
	l.myNames.Add(name)
	l.myPasses = append(l.myPasses, NewPhaseOptimizer_NamedPass(l.outer, factory))
}

// Java: PhaseOptimizer.Loop.process(Node, Node)
func (l *PhaseOptimizer_Loop) Process(externs *rhino.Node, root *rhino.Node) {
	p := l.outer
	jutil.CheckStateMsg(!p.inLoop, "Nested loops are forbidden")
	p.inLoop = true
	l.isCodeRemovalLoop = l.IsCodeRemovalLoop()

	// Set up function-change tracking
	l.scopeHandler = NewPhaseOptimizer_ScopedChangeHandler(p)
	p.changeTracker.AddChangeHandler(l.scopeHandler)

	// lastRuns is initialized before each loop. This way, when a pass is run
	// in the 2nd loop for the 1st time, it looks at all scopes.
	p.lastRuns = jutil.NewLinkedHashMap[*PhaseOptimizer_NamedPass, int32]()
	for _, pass := range l.myPasses {
		p.lastRuns.Put(pass, PhaseOptimizer_START_TIME)
	}
	// Contains a pass iff it made changes the last time it was run.
	madeChanges := jutil.NewLinkedHashSet[*PhaseOptimizer_NamedPass]()
	// Contains a pass iff it was run during the last inner loop.
	runInPrevIter := jutil.NewLinkedHashSet[*PhaseOptimizer_NamedPass]()
	// Contains a pass iff it did not make changes. This set is cleared each time any pass makes
	// changes. The purpose of this is to ensure we do not rerun any passes that did not make
	// changes unless a later run pass did make changes.
	didNotMakeChanges := jutil.NewLinkedHashSet[*PhaseOptimizer_NamedPass]()
	state := PhaseOptimizer_State_RUN_PASSES_NOT_RUN_IN_PREV_ITER
	var lastIterMadeChanges bool
	count := 1
	trackAstSize := p.useSizeHeuristicToStopOptimizationLoop && l.isCodeRemovalLoop
	var astSize int
	if trackAstSize {
		astSize = NodeUtil_CountAstSize(root)
	}
	previousAstSize := astSize

	// The loop starts at state RUN_PASSES_NOT_RUN_IN_PREV_ITER and runs all passes.
	// After that, it goes to state RUN_PASSES_THAT_CHANGED_STH_IN_PREV_ITER, and
	// runs several iterations in that state, until there are no longer any changes
	// to the AST, and then it goes back to RUN_PASSES_NOT_RUN_IN_PREV_ITER.
	// We call one sequence of RUN_PASSES_NOT_RUN_IN_PREV_ITER followed by
	// RUN_PASSES_THAT_CHANGED_STH_IN_PREV_ITER a batch.
	// At the end of every loop batch, if the batch made so few changes that the
	// changed percentage of the AST is below some threshold, we stop the loop
	// without waiting to reach a fixpoint.

	defer func() {
		p.inLoop = false
		p.changeTracker.RemoveChangeHandler(l.scopeHandler)
		evictOptimizeCallsLoopCache()
	}()
	for {
		if count > p.optimizationLoopMaxIterations && l.isCodeRemovalLoop {
			return
		}
		if count > PhaseOptimizer_MAX_LOOPS {
			p.compiler.ThrowInternalError(PhaseOptimizer_OPTIMIZE_LOOP_ERROR, nil)
		}
		count++
		lastIterMadeChanges = false
		for _, pass := range l.myPasses {
			if (state == PhaseOptimizer_State_RUN_PASSES_NOT_RUN_IN_PREV_ITER &&
				!runInPrevIter.Contains(pass) &&
				!didNotMakeChanges.Contains(pass)) ||
				(state == PhaseOptimizer_State_RUN_PASSES_THAT_CHANGED_STH_IN_PREV_ITER &&
					madeChanges.Contains(pass)) {
				p.changeTracker.IncrementChangeStamp()
				p.currentPass = pass
				pass.Process(externs, root)
				runInPrevIter.Add(pass)
				p.lastRuns.Put(pass, p.changeTracker.GetChangeStamp())
				if p.HasHaltingErrors() {
					return
				} else if l.scopeHandler.HasCodeChangedSinceLastCall() {
					madeChanges.Add(pass)
					didNotMakeChanges.Clear()
					lastIterMadeChanges = true
				} else {
					madeChanges.Remove(pass)
					didNotMakeChanges.Add(pass)
				}
			} else {
				runInPrevIter.Remove(pass)
			}
		}

		if trackAstSize && lastIterMadeChanges {
			previousAstSize = astSize
			astSize = NodeUtil_CountAstSize(root)
		}
		if state == PhaseOptimizer_State_RUN_PASSES_NOT_RUN_IN_PREV_ITER {
			if lastIterMadeChanges && l.IsAstSufficientlyChanging(previousAstSize, astSize) {
				state = PhaseOptimizer_State_RUN_PASSES_THAT_CHANGED_STH_IN_PREV_ITER
			} else {
				return
			}
		} else {
			jutil.CheckState(state == PhaseOptimizer_State_RUN_PASSES_THAT_CHANGED_STH_IN_PREV_ITER)
			if !lastIterMadeChanges || !l.IsAstSufficientlyChanging(previousAstSize, astSize) {
				state = PhaseOptimizer_State_RUN_PASSES_NOT_RUN_IN_PREV_ITER
			}
		}
	}
}

// IsAstSufficientlyChanging: if two loop batches in a row made the code
// less than 0.05% smaller than the previous batches, stop before the
// fixpoint. The 0.05% threshold is based on the following heuristic: 1% size
// difference matters to our users. 0.1% size difference is borderline
// relevant. 0.05% difference between loop batches is unlikely to grow the
// final output more than 0.1%.
//
// Use this criterion only for the two code-removing loops. The code-motion
// loop may move code around but not remove code, so this criterion is not
// correct for stopping early.
//
// NOTE: the size heuristic is not robust when passes in the code-removing
// loop increase the AST size; all passes in the loop must make the code
// smaller. Otherwise, what may seem like a small size difference may indeed
// be big changes, and we miss it because we don't compute the AST size after
// each pass. This can happen because inlineFunctions may increase code size,
// and relies on peephole and inlineVariables to clean up. As long as these
// passes run after it in the loop, we should be OK.
//
// Java: PhaseOptimizer.Loop.isAstSufficientlyChanging(int, int)
func (l *PhaseOptimizer_Loop) IsAstSufficientlyChanging(oldAstSize int, newAstSize int) bool {
	if l.outer.useSizeHeuristicToStopOptimizationLoop && l.isCodeRemovalLoop {
		diff := int32(newAstSize) - int32(oldAstSize)
		if diff < 0 {
			diff = -diff
		}
		percentChange := float32(100) * (float32(diff) / float32(int32(oldAstSize)))
		if float64(percentChange) < 0.05 {
			l.howmanyIterationsUnderThreshold++
		} else {
			l.howmanyIterationsUnderThreshold = 0
		}
		return l.howmanyIterationsUnderThreshold < 2
	}
	return true
}

// Java: PhaseOptimizer.Loop.isPopulated()
func (l *PhaseOptimizer_Loop) IsPopulated() bool {
	return len(l.myPasses) != 0
}

// Java: PhaseOptimizer.Loop.isCodeRemovalLoop()
func (l *PhaseOptimizer_Loop) IsCodeRemovalLoop() bool {
	for _, pass := range l.myPasses {
		for _, name := range PhaseOptimizer_CODE_REMOVING_PASSES {
			if name == pass.name {
				return true
			}
		}
	}
	return false
}

// PhaseOptimizer_ProgressRange is an object used when running many
// NamedPass loopable passes as a Loop pass, to keep track of how far along
// we are.
type PhaseOptimizer_ProgressRange struct {
	initialValue float64
	maxValue     float64
}

// Java: PhaseOptimizer.ProgressRange(double, double)
func NewPhaseOptimizer_ProgressRange(initialValue float64, maxValue float64) *PhaseOptimizer_ProgressRange {
	r := &PhaseOptimizer_ProgressRange{}
	r.initialValue = initialValue
	r.maxValue = maxValue
	return r
}
