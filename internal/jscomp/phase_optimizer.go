// PhaseOptimizer schedules and executes one-time and fixed-point-loop compiler passes.
type PhaseOptimizer struct {
	compiler          AbstractCompiler
	changeTracker     *ChangeTracker
	tracker           *PerformanceTracker
	passes            []CompilerPass
	inLoop            bool
	validityCheck     *PassFactory
	printAstHashcodes bool

	currentPass *PhaseOptimizer_NamedPass
	lastChange  int32
	jsRoot      rhino.Node

	useSizeHeuristicToStopOptimizationLoop bool
	changeVerifier                         *ChangeVerifier
	optimizationLoopMaxIterations          int

	// Go-only: loop ordinal and iteration for DebugPassLogHook.
	debugLoopOrdinal, debugLoopIter int
}

var (
	PhaseOptimizer_logger               = jutil.Logger_GetLogger("com.google.javascript.jscomp.PhaseOptimizer")
	PhaseOptimizer_CODE_REMOVING_PASSES = []string{PassNames_PEEPHOLE_OPTIMIZATIONS}
	phaseOptimizerTracerType            = "Compiler"
)

const (
	PhaseOptimizer_START_TIME          int32 = 0
	PhaseOptimizer_MAX_LOOPS                 = 100
	PhaseOptimizer_OPTIMIZE_LOOP_ERROR       = "Fixed point loop exceeded the maximum number of iterations."
)

type phaseLoopState uint8

const (
	loopRunUnvisited phaseLoopState = iota
	loopRerunChanged
)

func NewPhaseOptimizer(comp AbstractCompiler, tracker *PerformanceTracker) *PhaseOptimizer {
	opts := comp.GetOptions()
	maxIterations := opts.GetMaxOptimizationLoopIterations()
	if maxIterations <= 0 || maxIterations > PhaseOptimizer_MAX_LOOPS {
		maxIterations = PhaseOptimizer_MAX_LOOPS
	}
	return &PhaseOptimizer{
		compiler:                               comp,
		jsRoot:                                 comp.GetJsRoot(),
		tracker:                                tracker,
		changeTracker:                          comp.GetChangeTracker(),
		useSizeHeuristicToStopOptimizationLoop: opts.ShouldUseSizeHeuristicToStopOptimizationLoop(),
		optimizationLoopMaxIterations:          maxIterations,
	}
}

// Consume adds the passes generated by the given factories to the compile
// sequence, grouping consecutive loopable passes into fixed-point loops.
func (p *PhaseOptimizer) Consume(factories []*PassFactory) {
	currentLoop := NewPhaseOptimizer_Loop(p)
	for _, factory := range factories {
		if factory.IsRunInFixedPointLoop() {
			currentLoop.AddLoopedPass(factory)
		} else {
			if currentLoop.IsPopulated() {
				p.passes = append(p.passes, currentLoop)
				currentLoop = NewPhaseOptimizer_Loop(p)
			}
			p.AddOneTimePass(factory)
		}
	}
	if currentLoop.IsPopulated() {
		p.passes = append(p.passes, currentLoop)
	}
}

func (p *PhaseOptimizer) AddOneTimePass(factory *PassFactory) {
	p.passes = append(p.passes, NewPhaseOptimizer_NamedPass(p, factory))
}

func (p *PhaseOptimizer) AddFixedPointLoop() *PhaseOptimizer_Loop {
	loop := NewPhaseOptimizer_Loop(p)
	p.passes = append(p.passes, loop)
	return loop
}

func (p *PhaseOptimizer) SetValidityCheck(validityCheck *PassFactory) {
	p.validityCheck = validityCheck
	p.changeVerifier = NewChangeVerifier(p.compiler).Snapshot(p.jsRoot)
}

func (p *PhaseOptimizer) SetPrintAstHashcodes(printAstHashcodes bool) {
	p.printAstHashcodes = printAstHashcodes
}

// Process runs all passes in the optimizer without retaining per-pass instances.
func (p *PhaseOptimizer) Process(externs rhino.Node, root rhino.Node) {
	for _, pass := range p.passes {
		if Platform_IsThreadInterrupted() {
			panic(jutil.NewRuntimeExceptionWithCause(jutil.NewInterruptedException()))
		}
		pass.Process(externs, root)
		if p.HasHaltingErrors() {
			return
		}
		if c, ok := p.compiler.(*Compiler); ok {
			name := ""
			if np, ok := pass.(*PhaseOptimizer_NamedPass); ok {
				name = np.name
			}
			c.maybeCompactAST(name, &externs, &root, nil)
		}
	}
}

func (p *PhaseOptimizer) MaybePrintAstHashcodes(passName string, root rhino.Node) {
	if p.printAstHashcodes {
		hashCodeMsg := "AST hashCode after " + passName + ": " +
			jutil.ToJavaString(jutil.StringHashCode(p.compiler.ToSourceOfNode(root)))
		PhaseOptimizer_logger.Info(hashCodeMsg)
	}
}

func (p *PhaseOptimizer) MaybeRunValidityCheck(passName string, externs rhino.Node, root rhino.Node) {
	if p.validityCheck == nil {
		return
	}
	defer func() {
		if rec := recover(); rec != nil {
			t, ok := rec.(jutil.Throwable)
			if !ok {
				t = jutil.AsThrowable(rec)
			}
			if e, ok := t.(jutil.IRuntimeException); ok {
				panic(jutil.NewIllegalStateExceptionWithMessageAndCause("Validity checks failed for pass: "+passName, e))
			}
			panic(rec)
		}
	}()
	p.validityCheck.Create(p.compiler).Process(externs, root)
	p.changeVerifier.CheckRecordedChangesWithPassName(passName, p.jsRoot)
}

func (p *PhaseOptimizer) HasHaltingErrors() bool {
	return p.compiler.HasHaltingErrors()
}

// PhaseOptimizer_NamedPass wraps a single compiler pass factory for execution.
type PhaseOptimizer_NamedPass struct {
	outer   *PhaseOptimizer
	name    string
	factory *PassFactory
	tracer  *Tracer

	// Per-loop execution tracking (used only when inside PhaseOptimizer_Loop).
	lastRun           int32
	inLoop            bool
	madeChanges       bool
	runInPrevIter     bool
	didNotMakeChanges bool
}

func NewPhaseOptimizer_NamedPass(outer *PhaseOptimizer, factory *PassFactory) *PhaseOptimizer_NamedPass {
	return &PhaseOptimizer_NamedPass{
		outer:   outer,
		name:    factory.GetName(),
		factory: factory,
	}
}

func (n *PhaseOptimizer_NamedPass) Process(externs rhino.Node, root rhino.Node) {
	p := n.outer
	PhaseOptimizer_logger.Fine("Running pass " + n.name)
	n.factory.ValidatePreconditions(p.compiler.GetOptions())
	if p.validityCheck != nil {
		p.changeVerifier = NewChangeVerifier(p.compiler).Snapshot(p.jsRoot)
	}
	if p.tracker != nil {
		p.tracker.RecordPassStart(n.name, !n.factory.IsRunInFixedPointLoop())
	}
	n.tracer = NewTracerWithType(&phaseOptimizerTracerType, &n.name)

	p.compiler.BeforePass(n.name)
	var debugEnd func()
	if DebugPassLogHook != nil {
		debugEnd = p.debugPassStart(n.name)
	}

	// Delay pass construction until immediately before execution.
	n.factory.Create(p.compiler).Process(externs, root)

	if debugEnd != nil {
		debugEnd()
	}
	p.compiler.AfterPass(n.name)

	// Always stop the tracer even when tracker is nil so ThreadTrace.events doesn't grow unbounded.
	traceRuntime := n.tracer.Stop()
	if p.tracker != nil {
		p.tracker.RecordPassStop(n.name, traceRuntime)
	}
	p.MaybePrintAstHashcodes(n.name, root)
	if p.validityCheck != nil {
		n.runValidityCheck(externs, root)
	}
}

func (n *PhaseOptimizer_NamedPass) runValidityCheck(externs rhino.Node, root rhino.Node) {
	defer func() {
		if rec := recover(); rec != nil {
			t, ok := rec.(jutil.Throwable)
			if !ok {
				t = jutil.AsThrowable(rec)
			}
			if e, ok := t.(jutil.IIllegalStateException); ok {
				panic(jutil.NewRuntimeExceptionWithMessageAndCause("Validity check failed for "+n.name, e))
			}
			panic(rec)
		}
	}()
	n.outer.MaybeRunValidityCheck(n.name, externs, root)
}

func (n *PhaseOptimizer_NamedPass) String() string {
	return "pass: " + n.name
}

func (p *PhaseOptimizer) HasScopeChanged(n rhino.Node) bool {
	if !p.inLoop {
		return true
	}
	cp := p.currentPass
	if cp == nil || !cp.inLoop {
		panic(jutil.NewNullPointerException())
	}
	return cp.lastRun == PhaseOptimizer_START_TIME || n.GetChangeTime() > cp.lastRun
}

// PhaseOptimizer_ScopedChangeHandler records the timestamp of the latest code change.
type PhaseOptimizer_ScopedChangeHandler struct {
	outer               *PhaseOptimizer
	lastCodeChangeQuery int32
}

func NewPhaseOptimizer_ScopedChangeHandler(outer *PhaseOptimizer) *PhaseOptimizer_ScopedChangeHandler {
	return &PhaseOptimizer_ScopedChangeHandler{
		outer:               outer,
		lastCodeChangeQuery: outer.changeTracker.GetChangeStamp(),
	}
}

func (h *PhaseOptimizer_ScopedChangeHandler) ReportChange() {
	h.outer.lastChange = h.outer.changeTracker.GetChangeStamp()
}

func (h *PhaseOptimizer_ScopedChangeHandler) HasCodeChangedSinceLastCall() bool {
	result := h.outer.lastChange > h.lastCodeChangeQuery
	h.lastCodeChangeQuery = h.outer.changeTracker.GetChangeStamp()
	h.outer.changeTracker.IncrementChangeStamp()
	return result
}

// PhaseOptimizer_Loop is a compound pass that runs atomic passes until reaching a fixed point.
type PhaseOptimizer_Loop struct {
	outer                           *PhaseOptimizer
	myPasses                        []*PhaseOptimizer_NamedPass
	myNames                         map[string]struct{}
	scopeHandler                    *PhaseOptimizer_ScopedChangeHandler
	isCodeRemovalLoop               bool
	howmanyIterationsUnderThreshold int
}

func NewPhaseOptimizer_Loop(outer *PhaseOptimizer) *PhaseOptimizer_Loop {
	return &PhaseOptimizer_Loop{
		outer:   outer,
		myNames: make(map[string]struct{}),
	}
}

func (l *PhaseOptimizer_Loop) AddLoopedPass(factory *PassFactory) {
	name := factory.GetName()
	_, dup := l.myNames[name]
	jutil.CheckArgumentMsg1(!dup, "Already a pass with name '%s' in this loop", name)
	l.myNames[name] = struct{}{}
	l.myPasses = append(l.myPasses, NewPhaseOptimizer_NamedPass(l.outer, factory))
}

func (l *PhaseOptimizer_Loop) Process(externs rhino.Node, root rhino.Node) {
	p := l.outer
	jutil.CheckStateMsg(!p.inLoop, "Nested loops are forbidden")
	p.inLoop = true
	l.isCodeRemovalLoop = l.IsCodeRemovalLoop()
	p.debugLoopOrdinal++

	l.scopeHandler = NewPhaseOptimizer_ScopedChangeHandler(p)
	p.changeTracker.AddChangeHandler(l.scopeHandler)

	for _, pass := range l.myPasses {
		pass.inLoop = true
		pass.lastRun = PhaseOptimizer_START_TIME
		pass.madeChanges = false
		pass.runInPrevIter = false
		pass.didNotMakeChanges = false
	}

	state := loopRunUnvisited
	count := 1
	const astSizeTimelineKey = "__phaseOptAstSize__"
	trackAstSize := p.useSizeHeuristicToStopOptimizationLoop && l.isCodeRemovalLoop
	var astSize int
	var scriptSizes map[rhino.Node]int
	sizeWorkers := fastLoopSizeWorkers(p.compiler)
	if trackAstSize {
		numScripts := root.GetChildCount()
		scriptSizes = make(map[rhino.Node]int, numScripts)
		astSize = 1
		scripts := make([]rhino.Node, 0, numScripts)
		for script := root.GetFirstChild(); !script.IsNil(); script = script.GetNext() {
			scripts = append(scripts, script)
		}
		for i, sz := range countAstSizes(scripts, sizeWorkers) {
			scriptSizes[scripts[i]] = sz
			astSize += sz
		}
		p.changeTracker.changeTimeline.Mark(astSizeTimelineKey)
	}
	previousAstSize := astSize

	defer func() {
		p.inLoop = false
		p.currentPass = nil
		for _, pass := range l.myPasses {
			pass.inLoop = false
		}
		p.changeTracker.RemoveChangeHandler(l.scopeHandler)
		if trackAstSize {
			p.changeTracker.changeTimeline.Unmark(astSizeTimelineKey)
		}
	}()

	for {
		if count > p.optimizationLoopMaxIterations && l.isCodeRemovalLoop {
			return
		}
		if count > PhaseOptimizer_MAX_LOOPS {
			p.compiler.ThrowInternalError(PhaseOptimizer_OPTIMIZE_LOOP_ERROR, nil)
		}
		count++
		p.debugLoopIter = count - 1
		lastIterMadeChanges := false
		for _, pass := range l.myPasses {
			shouldRun := (state == loopRunUnvisited && !pass.runInPrevIter && !pass.didNotMakeChanges) ||
				(state == loopRerunChanged && pass.madeChanges)
			if !shouldRun {
				pass.runInPrevIter = false
				continue
			}
			p.changeTracker.IncrementChangeStamp()
			p.currentPass = pass
			pass.Process(externs, root)
			pass.runInPrevIter = true
			pass.lastRun = p.changeTracker.GetChangeStamp()
			if p.HasHaltingErrors() {
				return
			}
			if l.scopeHandler.HasCodeChangedSinceLastCall() {
				pass.madeChanges = true
				for _, q := range l.myPasses {
					q.didNotMakeChanges = false
				}
				lastIterMadeChanges = true
			} else {
				pass.madeChanges = false
				pass.didNotMakeChanges = true
			}
		}

		if trackAstSize && lastIterMadeChanges {
			previousAstSize = astSize
			changedScopes := p.changeTracker.GetChangedScopeNodesForPass(astSizeTimelineKey)
			if changedScopes == nil {
				astSize = countAstSizes([]rhino.Node{root}, sizeWorkers)[0]
			} else {
				recounted := make(map[rhino.Node]struct{}, len(changedScopes))
				var toCount []rhino.Node
				for _, scopeNode := range changedScopes {
					cur := scopeNode
					for !cur.IsNil() && cur.GetParent() != root {
						cur = cur.GetParent()
					}
					if !cur.IsNil() && cur.GetParent() == root {
						if _, done := recounted[cur]; !done {
							recounted[cur] = struct{}{}
							toCount = append(toCount, cur)
						}
					}
				}
				for i, newSz := range countAstSizes(toCount, sizeWorkers) {
					cur := toCount[i]
					oldSz := scriptSizes[cur]
					scriptSizes[cur] = newSz
					astSize += newSz - oldSz
				}
				liveScripts := 0
				for script := root.GetFirstChild(); !script.IsNil(); script = script.GetNext() {
					liveScripts++
					if _, known := scriptSizes[script]; !known {
						sz := NodeUtil_CountAstSize(script)
						scriptSizes[script] = sz
						astSize += sz
					}
				}
				if liveScripts != len(scriptSizes) {
					// order-independent: deletes dead scripts and sums their sizes
					for script, oldSz := range scriptSizes {
						if script.GetParent() != root {
							delete(scriptSizes, script)
							astSize -= oldSz
						}
					}
				}
			}
		}
		if c, ok := p.compiler.(*Compiler); ok {
			c.maybeCompactAST("loop iteration", &externs, &root, func(fwd func(rhino.Node) rhino.Node) {
				if scriptSizes != nil {
					sizes := make(map[rhino.Node]int, len(scriptSizes))
					// order-independent: rebuilds the map with forwarded keys
					for script, sz := range scriptSizes {
						sizes[fwd(script)] = sz
					}
					scriptSizes = sizes
				}
			})
		}
		if state == loopRunUnvisited {
			if lastIterMadeChanges && l.IsAstSufficientlyChanging(previousAstSize, astSize) {
				state = loopRerunChanged
			} else {
				return
			}
		} else {
			if !lastIterMadeChanges || !l.IsAstSufficientlyChanging(previousAstSize, astSize) {
				state = loopRunUnvisited
			}
		}
	}
}

// IsAstSufficientlyChanging stops code-removal loops early when two consecutive
// loop batches shrink the AST by less than 0.05%.
func (l *PhaseOptimizer_Loop) IsAstSufficientlyChanging(oldAstSize int, newAstSize int) bool {
	if l.outer.useSizeHeuristicToStopOptimizationLoop && l.isCodeRemovalLoop {
		diff := int32(newAstSize) - int32(oldAstSize)
		if diff < 0 {
			diff = -diff
		}
		percentChange := float32(100) * (float32(diff) / float32(int32(oldAstSize)))
		if float64(percentChange) < 0.05 {
			l.howmanyIterationsUnderThreshold++
		} else {
			l.howmanyIterationsUnderThreshold = 0
		}
		return l.howmanyIterationsUnderThreshold < 2
	}
	return true
}

func (l *PhaseOptimizer_Loop) IsPopulated() bool {
	return len(l.myPasses) != 0
}

func (l *PhaseOptimizer_Loop) IsCodeRemovalLoop() bool {
	for _, pass := range l.myPasses {
		if slices.Contains(PhaseOptimizer_CODE_REMOVING_PASSES, pass.name) {
			return true
		}
	}
	return false
}

// Go-only: fast mode counts the AST sizes behind the optimization loop's
// size heuristic (PhaseOptimizer.Loop, useSizeHeuristicToStopOptimizationLoop)
// on worker goroutines. Counting is a pure read of the tree and the sums are
// exact, so the loop stops exactly where the sequential count would make it
// stop.

// fastLoopSizeWorkers is the number of workers for the loop's AST-size
// counts, or 1 to count sequentially.
func fastLoopSizeWorkers(compiler AbstractCompiler) int {
	opts := compiler.GetOptions()
	if !opts.isFastMode() {
		return 1
	}
	return parallelThreadCount(compiler, 1<<30)
}

// countAstSizes returns NodeUtil_CountAstSize of every node. With more than
// one worker the trees are cut into subtrees (a breadth-first frontier) that
// workers count; each node's size is 1 per expanded node plus the sizes of
// its frontier subtrees.
func countAstSizes(nodes []rhino.Node, workers int) []int {
	sizes := make([]int, len(nodes))
	if workers <= 1 {
		for i, n := range nodes {
			sizes[i] = NodeUtil_CountAstSize(n)
		}
		return sizes
	}
	type item struct {
		n     rhino.Node
		owner int32
	}
	target := 64 * workers
	frontier := make([]item, 0, len(nodes))
	for i, n := range nodes {
		frontier = append(frontier, item{n, int32(i)})
	}
	// Expand level by level until there is enough work to share.
	for depth := 0; len(frontier) < target && depth < 48; depth++ {
		next := make([]item, 0, 2*len(frontier))
		expanded := false
		for _, it := range frontier {
			if it.n.GetFirstChild().IsNil() {
				sizes[it.owner]++
				continue
			}
			expanded = true
			sizes[it.owner]++
			for c := it.n.GetFirstChild(); !c.IsNil(); c = c.GetNext() {
				next = append(next, item{c, it.owner})
			}
		}
		frontier = next
		if !expanded {
			break
		}
	}
	if len(frontier) == 0 {
		return sizes
	}
	partial := make([][]int, workers)
	var next atomic.Int64
	var wg sync.WaitGroup
	const chunk = 16
	for w := 0; w < workers; w++ {
		partial[w] = make([]int, len(nodes))
		wg.Add(1)
		go func(acc []int) {
			defer wg.Done()
			for {
				start := int(next.Add(chunk)) - chunk
				if start >= len(frontier) {
					return
				}
				end := min(start+chunk, len(frontier))
				for _, it := range frontier[start:end] {
					acc[it.owner] += NodeUtil_CountAstSize(it.n)
				}
			}
		}(partial[w])
	}
	wg.Wait()
	for _, acc := range partial {
		for i, v := range acc {
			sizes[i] += v
		}
	}
	return sizes
}
