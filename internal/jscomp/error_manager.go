// ErrorHandler is any generic sink for warnings and errors, after they've
// passed through any filtering WarningsGuards.
type ErrorHandler interface {
	// Report reports error at the reporting level. level may be nil (Java
	// callers pass null).
	//
	// Java: ErrorHandler.report(CheckLevel, JSError)
	Report(level *CheckLevel, error *JSError)
}

// ErrorManager is in charge of storing, organizing and displaying errors
// and warnings generated by the compiler.
type ErrorManager interface {
	ErrorHandler

	// Report reports an error. The errors will be displayed by the
	// GenerateReport at the discretion of the implementation. level may be
	// nil.
	//
	// Java: ErrorManager.report(CheckLevel, JSError)
	Report(level *CheckLevel, error *JSError)

	// GenerateReport writes a report to an implementation-specific medium.
	// The compiler calls this method after any and all Report calls.
	//
	// Java: ErrorManager.generateReport()
	GenerateReport()

	// GetErrorCount gets the number of reported errors.
	//
	// Java: ErrorManager.getErrorCount()
	GetErrorCount() int

	// GetWarningCount gets the number of reported warnings.
	//
	// Java: ErrorManager.getWarningCount()
	GetWarningCount() int

	// GetErrors gets all the errors.
	//
	// Java: ErrorManager.getErrors()
	GetErrors() []*JSError

	// GetWarnings gets all the warnings.
	//
	// Java: ErrorManager.getWarnings()
	GetWarnings() []*JSError

	// SetTypedPercent sets the percentage of typed expressions.
	//
	// Java: ErrorManager.setTypedPercent(double)
	SetTypedPercent(typedPercent float64)

	// GetTypedPercent gets the percentage of typed expressions.
	//
	// Java: ErrorManager.getTypedPercent()
	GetTypedPercent() float64

	// HasHaltingErrors returns if the error manager has errors that should
	// make compilation halt; see ErrorManager_HasHaltingErrors for the default.
	//
	// Java: ErrorManager.hasHaltingErrors()
	HasHaltingErrors() bool

	// ShouldReportConformanceViolation; see
	// ErrorManager_ShouldReportConformanceViolation for the default.
	//
	// Java: ErrorManager.shouldReportConformanceViolation(Requirement, Optional<RequirementScopeEntry>, JSError, LibraryLevelNonAllowlistedConformanceViolationsBehavior, boolean)
	ShouldReportConformanceViolation(
		requirement *Requirement,
		allowlistEntry *RequirementScopeEntry,
		diagnostic *JSError,
		behavior ConformanceConfig_LibraryLevelNonAllowlistedConformanceViolationsBehavior,
		isAllowlisted bool) bool
}

// ErrorManager_HasHaltingErrors is the default ErrorManager.hasHaltingErrors:
// it returns if the error manager has errors that should make compilation
// halt. This, for example, omits errors that were promoted from warnings by
// using the --strict flag.
//
// Java: ErrorManager.hasHaltingErrors()
func ErrorManager_HasHaltingErrors(m ErrorManager) bool {
	if m.GetErrorCount() == 0 {
		return false
	}
	for _, error := range m.GetErrors() {
		if error.Type().level == CheckLevel_ERROR {
			return true
		}
	}
	return false
}

// ErrorManager_ShouldReportConformanceViolation is the default
// ErrorManager.shouldReportConformanceViolation: it returns true if the
// conformance violation should be reported. This is called even if the
// violation is allowlisted and override implementations all can return true
// despite allowlisting. allowlistEntry is nil when absent.
//
// This method's name is misleading.
//
// It is called by the AbstractRule.report method, but none of the
// implementations of this method actually check whether the violation is
// allowlisted or not. The actual checking of allowlists is done later at the
// call-site in the AbstractRule.report method. See -
// https://source.corp.google.com/piper///depot/google3/third_party/java_src/jscomp/java/com/google/javascript/jscomp/ConformanceRules.java;rcl=783510053;l=364
//
// The implementations of this method always delegate to this method (return
// true) as long as the violation is not in a generated code file (which is
// always safe and never reported) or is being used by
// ConformanceAllowlister to generate allowlist updates (therefore not
// reported). For all violations other violations (except in generated
// code), this method returns true.
//
// Java: ErrorManager.shouldReportConformanceViolation(Requirement, Optional<RequirementScopeEntry>, JSError, LibraryLevelNonAllowlistedConformanceViolationsBehavior, boolean)
func ErrorManager_ShouldReportConformanceViolation(
	m ErrorManager,
	requirement *Requirement,
	allowlistEntry *RequirementScopeEntry,
	diagnostic *JSError,
	behavior ConformanceConfig_LibraryLevelNonAllowlistedConformanceViolationsBehavior,
	isAllowlisted bool) bool {
	// TODO: b/332922526 - Rename this method and all its overrides to
	// {@code shouldReportConformanceViolationIgnoringAllowlists} or similar.
	return behavior != ConformanceConfig_LibraryLevelNonAllowlistedConformanceViolationsBehavior_RECORD_ONLY
}

// BlackHoleErrorManager is an ErrorManager that silently swallows all
// messages.
type BlackHoleErrorManager struct {
	SortingErrorManagerBase
}

var _ SortingErrorManager = (*BlackHoleErrorManager)(nil)

// Java: BlackHoleErrorManager()
func NewBlackHoleErrorManager() *BlackHoleErrorManager {
	m := &BlackHoleErrorManager{}
	m.InitSortingErrorManagerBase(m, nil)
	return m
}

// ErrorPass is a compiler pass that just reports an error.
type ErrorPass struct {
	compiler AbstractCompiler
	error_   *JSError
}

// Java: ErrorPass(AbstractCompiler, DiagnosticType)
func NewErrorPass(compiler AbstractCompiler, error_ *DiagnosticType) *ErrorPass {
	return NewErrorPassWithJSError(compiler, JSError_Make(error_))
}

// Java: ErrorPass(AbstractCompiler, JSError)
func NewErrorPassWithJSError(compiler AbstractCompiler, error_ *JSError) *ErrorPass {
	return &ErrorPass{
		compiler: compiler,
		error_:   error_,
	}
}

// Java: ErrorPass.process(Node, Node)
func (p *ErrorPass) Process(externs rhino.Node, root rhino.Node) {
	p.compiler.Report(p.error_)
}
