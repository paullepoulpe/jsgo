// Tests correctness of type information after transpilation
// Java: Es6RewriteGeneratorsTest.testYield_withTypes()
func (c *Es6RewriteGeneratorsTest) TestYield_withTypes() {
	returnNode :=
		c.TestAndReturnBodyForNumericGenerator(
			"yield 1 + 2;", "", "return GEN_CONTEXT$0.yield(1 + 2, 0);")

	jutil.CheckStateMsg1(returnNode.IsReturn(), "%s", returnNode)
	callNode := returnNode.GetFirstChild()
	jutil.CheckStateMsg1(callNode.IsCall(), "%s", callNode)
	// TODO(b/142881197): we can't give a more accurate type right now.
	AssertNode(callNode).HasColorThat().IsEqualTo(colors.StandardColors_UNKNOWN)

	yieldFn := callNode.GetFirstChild()
	jscompGeneratorContext := yieldFn.GetFirstChild()
	generatorContext :=
		transpileTests_GetOnlyElement(
			CodeSubTree_FindFirstNode(
				c.GetLastCompiler().GetExternsRoot(),
				func(n rhino.Node) bool { return n.MatchesQualifiedName("$jscomp.generator.Context") }).
				GetColor().
				GetInstanceColors().All())
	AssertThat(jscompGeneratorContext.GetColor()).IsEqualTo(generatorContext)

	// Check types on "1 + 2" are still present after transpilation
	yieldedValue := callNode.GetSecondChild() // 1 + 2

	jutil.CheckStateMsg1(yieldedValue.IsAdd(), "%s", yieldedValue)
	AssertNode(yieldedValue).HasColorThat().IsEqualTo(colors.StandardColors_NUMBER)
	AssertNode(yieldedValue.GetFirstChild()).HasColorThat().IsEqualTo(colors.StandardColors_NUMBER)  // 1
	AssertNode(yieldedValue.GetSecondChild()).HasColorThat().IsEqualTo(colors.StandardColors_NUMBER) // 2

	zero := yieldedValue.GetNext()
	jutil.CheckStateMsg1(0 == zero.GetDouble(), "%s", zero)
	AssertNode(zero).HasColorThat().IsEqualTo(colors.StandardColors_NUMBER)
}

