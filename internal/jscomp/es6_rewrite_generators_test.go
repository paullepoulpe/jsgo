// GetAndCheckGeneratorProgram gets the "program" function from a tranpsiled
// generator
//
// Java: Es6RewriteGeneratorsTest.getAndCheckGeneratorProgram(Node)
func (c *Es6RewriteGeneratorsTest) GetAndCheckGeneratorProgram(genFunction rhino.Node) rhino.Node {
	returnNode := genFunction.GetLastChild().GetLastChild()
	callNode := returnNode.GetFirstChild()
	jutil.CheckStateMsg1(callNode.IsCall(), "%s", callNode)

	createGenerator := callNode.GetFirstChild()
	return createGenerator.GetNext().GetNext()
}

// transpileTests_GetOnlyElement is Guava's Iterables.getOnlyElement(iterable).
//
// Go-only: test-helper.
func transpileTests_GetOnlyElement[T any](elements iter.Seq[T]) T {
	var result T
	n := 0
	for e := range elements {
		if n == 0 {
			result = e
		}
		n++
	}
	if n == 0 {
		panic(jutil.NewNoSuchElementException())
	}
	if n > 1 {
		panic(jutil.NewIllegalArgumentExceptionMsg("expected one element but was: " + jutil.ToJavaString(n)))
	}
	return result
}

