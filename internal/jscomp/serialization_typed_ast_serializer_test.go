// typedAstSerializerTest_CONSOLE_EXTERNS: externs containing only
// definitions for `console.log` and `console.error`.
//
// We should not use `TestExternsBuilder` here because we want to have
// definitions for "log" and "error" console methods and definitely nothing
// else. The externs generated by `TestExternsBuilder` are expected to
// more-or-less mirror the "real" externs and to expand as needed for general
// use in testing.
//
// Java: TypedAstSerializerTest.CONSOLE_EXTERNS
var typedAstSerializerTest_CONSOLE_EXTERNS = CompilerTestCase_Externs_(
	`/** @constructor */
function Console() {};

/**
 * @param {...*} var_args
 * @return {undefined}
 */
Console.prototype.log = function(var_args) {};

/**
 * @param {...*} var_args
 * @return {undefined}
 */
Console.prototype.error = function(var_args) {};

/** @const {!Console} */
var console;
`)

// Proto fields commonly ignored in tests because hardcoding their values is
// brittle.
