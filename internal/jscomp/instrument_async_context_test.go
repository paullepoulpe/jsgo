// Java: InstrumentAsyncContextTest.getProcessor(Compiler)
func (c *InstrumentAsyncContextTest) GetProcessor(compiler *Compiler) CompilerPass {
	optimizer := NewPhaseOptimizer(compiler, nil)
	optimizer.AddOneTimePass(
		CompilerTestCase_MakePassFactory(
			"injectTranspilationRuntimeLibraries",
			func(abstractCompiler AbstractCompiler) CompilerPass {
				return NewInjectTranspilationRuntimeLibrariesWithInstrumentAsyncContext(
					compiler /* shouldInstrumentAsyncContext= */, true)
			}))
	optimizer.AddOneTimePass(
		CompilerTestCase_MakePassFactory(
			"instrumentAsyncContext",
			func(abstractCompiler AbstractCompiler) CompilerPass {
				return NewInstrumentAsyncContext(compiler, c.instrumentAwait)
			}))
	return optimizer
}

