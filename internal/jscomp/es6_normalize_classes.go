// FindPrivateMember finds the private member declaration in the enclosing
// class stack by its name (including the '#' prefix).
//
// Java: Es6NormalizeClasses.findPrivateMember(String)
func (e *Es6NormalizeClasses) FindPrivateMember(name string) *es6NormalizeClasses_ResolvedPrivateMember {
	for i := len(e.classStack) - 1; i >= 0; i-- {
		record := e.classStack[i]
		if record.HasPrivateMember(name) {
			return newEs6NormalizeClasses_ResolvedPrivateMember(record, record.GetPrivateMember(name))
		}
	}
	return nil
}

// RewritePrivateIn rewrites private identifier brand checks (e.g.
// `#field in obj`) to use `PRIVATE_MAP.has(obj)`.
//
// Java: Es6NormalizeClasses.rewritePrivateIn(NodeTraversal, Node)
func (e *Es6NormalizeClasses) RewritePrivateIn(t *NodeTraversal, inNode rhino.Node) {
	jutil.CheckArgumentMsg1(inNode.IsIn(), "%s", inNode)
	left := inNode.GetFirstChild()
	name := left.GetString()
	resolved := e.FindPrivateMember(name)
	if resolved == nil {
		e.MaybeReportPrivatePropertiesCannotConvertYet(left)
		return
	}

	right := inNode.GetLastChild().Detach()
	record := resolved.ClassRecord()
	isStatic := resolved.PrivateMember().isStatic
	var mapVarName string
	if isStatic {
		mapVarName = record.GetStaticPrivateMapVarName(e.compiler, t)
	} else {
		mapVarName = record.GetPrivateMapVarName(e.compiler, t)
	}

	mapNameNode := e.astFactory.CreateNameWithUnknownType(mapVarName)
	hasCallee := e.astFactory.CreateGetPropWithUnknownType(mapNameNode, "has")
	hasCall := e.astFactory.CreateCallWithUnknownType(hasCallee, right)

	inNode.ReplaceWith(hasCall.SrcrefTree(inNode))
	t.ReportCodeChange()
}

// RewritePrivateGetProp rewrites private property accesses (e.g.
// `obj.#field`) to use `PRIVATE_MAP.get(obj).field`.
//
// For non-static private methods:
//
//   - Direct calls: `obj.#method(args)` are rewritten to
//     `PRIVATE_MAP.get(obj).method.call(obj, args)`.
//   - Method access (tear-off): `obj.#method` is rewritten to
//     `PRIVATE_MAP.get(obj).method`.
//
// TODO(b/236744850): Consider memoizing PRIVATE_MAP.get(obj) into a local
// temporary variable when multiple private accesses occur on the same
// receiver within a single statement or method scope to reduce WeakMap
// lookup overhead.
//
// Java: Es6NormalizeClasses.rewritePrivateGetProp(NodeTraversal, Node)
func (e *Es6NormalizeClasses) RewritePrivateGetProp(t *NodeTraversal, getPropNode rhino.Node) {
	name := getPropNode.GetString()
	resolved := e.FindPrivateMember(name)
	if resolved == nil {
		e.MaybeReportPrivatePropertiesCannotConvertYet(getPropNode)
		return
	}

	record := resolved.ClassRecord()
	pm := resolved.PrivateMember()

	// Private methods are read-only and cannot be reassigned (e.g., `this.#method = fn`).
	// Report an error if a private method is used as an L-value.
	if NodeUtil_IsLValue(getPropNode) && pm.kind == es6NormalizeClasses_ClassRecord_PrivateMemberKind_METHOD {
		e.compiler.Report(
			JSError_MakeWithNode(getPropNode, Es6NormalizeClasses_ILLEGAL_PRIVATE_MEMBER_ASSIGNMENT, pm.PropertyName()))
		return
	}

	parent := getPropNode.GetParent()
	e.RewritePrivateMemberAccess(t, getPropNode, record, pm, parent)
}

// RewritePrivateMemberAccess rewrites a private member access or
// invocation.
//
// Handles three primary cases:
//
//  1. Direct member calls with side-effecting receivers (e.g.
//     `getObj()?.#method(a)` or `getObj()?.#field(a)`):
//
//     let TMP;
//     (TMP = getObj(), TMP == null ? void 0 : PRIVATE_MAP.get(TMP).member.call(TMP, a))
//
//  2. Direct member calls with side-effect-free receivers (e.g.
//     `this.#method(a)` or `obj?.#field?.(a)`):
//
//     obj == null ? void 0 : PRIVATE_MAP.get(obj).member.call(obj, a)
//
//  3. Indirect reads, field accesses, and method tear-offs (e.g.
//     `const fn = obj?.#method` or `obj?.#field`):
//
//     const fn = obj == null ? void 0 : PRIVATE_MAP.get(obj).member;
//
// Java: Es6NormalizeClasses.rewritePrivateMemberAccess(NodeTraversal, Node, ClassRecord, ClassRecord.PrivateMember, Node)
func (e *Es6NormalizeClasses) RewritePrivateMemberAccess(
	t *NodeTraversal,
	getPropNode rhino.Node,
	record *es6NormalizeClasses_ClassRecord,
	pm *es6NormalizeClasses_ClassRecord_PrivateMember,
	parent rhino.Node) {
	isStatic := pm.isStatic
	var mapVarName string
	if isStatic {
		mapVarName = record.GetStaticPrivateMapVarName(e.compiler, t)
	} else {
		mapVarName = record.GetPrivateMapVarName(e.compiler, t)
	}
	memberPropName := pm.PropertyName()

	receiver := getPropNode.GetFirstChild().Detach()
	mapNameNode := e.astFactory.CreateNameWithUnknownType(mapVarName)
	getCallee := e.astFactory.CreateGetPropWithUnknownType(mapNameNode, "get")

	isOptChain := getPropNode.IsOptChainGetProp()
	var endOfSegment rhino.Node
	if isOptChain {
		endOfSegment = NodeUtil_GetEndOfOptChainSegment(getPropNode)
	}

	isDirectCall :=
		(parent.IsCall() || parent.IsOptChainCall()) &&
			parent.GetFirstChild() == getPropNode

	if isDirectCall {
		isOptionalCall := parent.IsOptChainCall() && parent.IsOptionalChainStart()

		parent.SetIsOptionalChainStart(false)

		if e.ReceiverNeedsTempVar(receiver) {
			// If evaluating receiver twice could introduce side effects or alter execution state,
			// declare a temporary variable (e.g. `let TMP;`) and evaluate the call using a comma
			// expression:
			// `(TMP = receiver, PRIVATE_MAP.get(TMP).member.call(TMP, ...args))`
			tempName := e.GenerateUniqueTmpVarName(t)
			insertionBlock := e.GetDeclarationInsertionPoint(getPropNode, t)
			decl := e.astFactory.CreateSingleLetNameDeclaration(tempName)
			insertionBlock.AddChildToFront(decl.SrcrefTree(getPropNode))
			NodeUtil_AddFeatureToScript(t.GetCurrentScript(), parser.FeatureSet_Feature_LET_DECLARATIONS, e.compiler)

			tempNameNode1 := e.astFactory.CreateNameWithUnknownType(tempName).Srcref(getPropNode)
			assign := e.astFactory.CreateAssign(tempNameNode1, receiver).Srcref(getPropNode)
			receiver = e.astFactory.CreateNameWithUnknownType(tempName).Srcref(getPropNode)

			tempNameNode2 := e.astFactory.CreateNameWithUnknownType(tempName).Srcref(getPropNode)
			tempNameNode3 := e.astFactory.CreateNameWithUnknownType(tempName).Srcref(getPropNode)

			getCall :=
				e.astFactory.CreateCallWithUnknownType(getCallee, tempNameNode2).Srcref(getPropNode)
			methodGetProp := e.astFactory.CreateGetPropWithUnknownType(getCall, memberPropName)
			callCallee := e.CreateCallCallee(methodGetProp, isOptionalCall, getPropNode)
			if callCallee.IsOptChainGetProp() {
				parent.SetToken(rhino.Token_OPTCHAIN_CALL)
			} else {
				parent.SetToken(rhino.Token_CALL)
			}

			callCallee.SrcrefTreeIfMissing(getPropNode)
			tempNameNode3.SrcrefTree(getPropNode)

			getPropNode.Detach()
			parent.AddChildToFront(callCallee)
			tempNameNode3.InsertAfter(callCallee)

			resultExpr :=
				e.WrapOptionalChainStartIfNecessary(receiver, parent, endOfSegment, isOptChain)
			placeholder := rhino.IR_Empty()
			resultExpr.ReplaceWith(placeholder)
			comma := e.astFactory.CreateComma(assign, resultExpr).Srcref(getPropNode)
			placeholder.ReplaceWith(comma)

			t.ReportCodeChange()
		} else {
			// Direct private member call with a side-effect-free receiver (e.g. `this` or a simple
			// variable):
			// Rewritten to `PRIVATE_MAP.get(receiver).member.call(receiver, ...args)`.
			getCall := e.astFactory.CreateCallWithUnknownType(getCallee, receiver)
			methodGetProp := e.astFactory.CreateGetPropWithUnknownType(getCall, memberPropName)
			receiverArg := receiver.CloneTree()
			receiverArg.SrcrefTree(getPropNode)

			getPropNode.Detach()
			callCallee := e.CreateCallCallee(methodGetProp, isOptionalCall, getPropNode)
			if callCallee.IsOptChainGetProp() {
				parent.SetToken(rhino.Token_OPTCHAIN_CALL)
			} else {
				parent.SetToken(rhino.Token_CALL)
			}
			callCallee.SrcrefTreeIfMissing(getPropNode)
			parent.AddChildToFront(callCallee)
			receiverArg.InsertAfter(callCallee)
			e.WrapOptionalChainStartIfNecessary(receiver, parent, endOfSegment, isOptChain)
			t.ReportCodeChange()
		}
	} else {
		// Indirect read, field access, or method tear-off (e.g., `const fn = this.#method` or
		// `this.#field`):
		// Rewritten to `PRIVATE_MAP.get(receiver).propertyName`.
		assignComma := e.ExtractReceiverTmpIfNecessary(t, receiver, getPropNode, isOptChain)
		if !assignComma.IsNil() {
			receiver = assignComma.GetFirstChild().CloneTree()
		}
		getCall := e.astFactory.CreateCallWithUnknownType(getCallee, receiver)
		methodGetProp := e.astFactory.CreateGetPropWithUnknownType(getCall, memberPropName)
		getPropNode.ReplaceWith(methodGetProp.SrcrefTree(getPropNode))
		result :=
			e.WrapOptionalChainStartIfNecessary(receiver, methodGetProp, endOfSegment, isOptChain)

		if !assignComma.IsNil() {
			placeholder := rhino.IR_Empty()
			result.ReplaceWith(placeholder)
			comma := e.astFactory.CreateComma(assignComma, result).Srcref(getPropNode)
			placeholder.ReplaceWith(comma)
		}

		t.ReportCodeChange()
	}
}

// ExtractReceiverTmpIfNecessary extracts a temporary variable declaration
// for a side-effecting receiver in an optional chain.
//
// For example, when transpiling:
//
//	// JS input:
//	getObj()?.#field
//
//	// Transpiled JS output:
//	let TMP;
//	(TMP = getObj(), TMP == null ? void 0 : PRIVATE_MAP.get(TMP).field)
//
// Returns an assignment node `(TMP = receiver)` to prepend in a comma
// expression, or nil if no temporary variable is needed.
//
// Java: Es6NormalizeClasses.extractReceiverTmpIfNecessary(NodeTraversal, Node, Node, boolean)
func (e *Es6NormalizeClasses) ExtractReceiverTmpIfNecessary(
	t *NodeTraversal, receiver rhino.Node, getPropNode rhino.Node, isOptChain bool) rhino.Node {
	if !isOptChain || !e.ReceiverNeedsTempVar(receiver) {
		return rhino.Node{}
	}
	tempName := e.GenerateUniqueTmpVarName(t)
	insertionBlock := e.GetDeclarationInsertionPoint(getPropNode, t)
	decl := e.astFactory.CreateSingleLetNameDeclaration(tempName)
	insertionBlock.AddChildToFront(decl.SrcrefTree(getPropNode))
	NodeUtil_AddFeatureToScript(t.GetCurrentScript(), parser.FeatureSet_Feature_LET_DECLARATIONS, e.compiler)

	tempNameNode := e.astFactory.CreateNameWithUnknownType(tempName).Srcref(getPropNode)
	return e.astFactory.CreateAssign(tempNameNode, receiver).Srcref(getPropNode)
}

// WrapOptionalChainStartIfNecessary wraps an optional chained private
// member access with a nullish short-circuit check on the receiver,
// climbing to the end of the current optional chain segment.
//
// For example, transpiles:
//
//	// Trailing property access in optional chain segment:
//	obj?.#field.prop
//	// -> obj == null ? void 0 : PRIVATE_MAP.get(obj).field.prop
//
//	// Direct private method invocation:
//	obj?.#method(arg)
//	// -> obj == null ? void 0 : PRIVATE_MAP.get(obj).method.call(obj, arg)
//
// Java: Es6NormalizeClasses.wrapOptionalChainStartIfNecessary(Node, Node, Node, boolean)
func (e *Es6NormalizeClasses) WrapOptionalChainStartIfNecessary(
	receiver rhino.Node, accessExpr rhino.Node, endOfSegment rhino.Node, isOptChain bool) rhino.Node {
	if !isOptChain {
		return accessExpr
	}
	var segmentRoot rhino.Node
	if !endOfSegment.IsNil() && !endOfSegment.GetParent().IsNil() {
		segmentRoot = endOfSegment
	} else {
		segmentRoot = accessExpr
	}
	if segmentRoot != accessExpr {
		NodeUtil_ConvertToNonOptionalChainSegmentDownTo(segmentRoot, accessExpr)
	}

	placeholder := rhino.IR_Empty()
	if !segmentRoot.GetParent().IsNil() {
		segmentRoot.ReplaceWith(placeholder)
	}
	// We must short-circuit before calling PRIVATE_MAP.get(receiver), since PRIVATE_MAP.get throws
	// on nullish receivers.
	hook :=
		e.astFactory.
			CreateOptionalChainShortCircuit(receiver.CloneTree(), segmentRoot).
			SrcrefTreeIfMissing(segmentRoot)
	if !placeholder.GetParent().IsNil() {
		placeholder.ReplaceWith(hook)
	}
	hookParent := hook.GetParent()
	if !hookParent.IsNil() && (hookParent.IsCall() || hookParent.IsOptChainCall()) {
		hook.SetIsParenthesized(true)
		if hookParent.GetFirstChild() == hook {
			hookParent.PutBooleanProp(rhino.Node_FREE_CALL, true)
		}
	}
	return hook
}

// CreateCallCallee creates the `.call` property access node for a private
// method invocation.
//
// If the invocation itself was optional (e.g. `obj.#method?.(arg)`), starts
// a new optional chain segment (`.call?.(obj, arg)`). Otherwise creates a
// standard property access `.call(obj, arg)`.
//
// Java: Es6NormalizeClasses.createCallCallee(Node, boolean, Node)
func (e *Es6NormalizeClasses) CreateCallCallee(methodGetProp rhino.Node, isOptionalCall bool, getPropNode rhino.Node) rhino.Node {
	if isOptionalCall {
		return e.astFactory.CreateStartOptChainGetprop(methodGetProp, "call", AstFactory_Type_(getPropNode))
	} else {
		return e.astFactory.CreateGetPropWithUnknownType(methodGetProp, "call")
	}
}

// RewriteThisToThisDotSelf rewrites top-level `this` references inside a
// private accessor body to `this.$self`.
//
// Returns true if any `this` reference was rewritten.
//
// Java: Es6NormalizeClasses.rewriteThisToThisDotSelf(Node)
func (e *Es6NormalizeClasses) RewriteThisToThisDotSelf(fn rhino.Node) bool {
	fnBody := NodeUtil_GetFunctionBody(fn)
	if fnBody.IsNil() {
		return false
	}
	hasThis := false
	NodeUtil_VisitPostOrderWithPred(
		fnBody,
		NodeUtil_VisitorFunc(func(n rhino.Node) {
			if n.IsThis() {
				hasThis = true
				target :=
					e.astFactory.
						CreateGetPropWithUnknownType(
							e.astFactory.CreateThis(AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)), "$self").
						Srcref(n)
				n.ReplaceWith(target)
				e.compiler.ReportChangeToEnclosingScope(target)
			}
		}),
		func(n rhino.Node) bool { return !n.IsClass() && (!n.IsFunction() || n.IsArrowFunction()) })
	return hasThis
}

// Java: Es6NormalizeClasses.hasThisReference(Node)
func (e *Es6NormalizeClasses) HasThisReference(fn rhino.Node) bool {
	fnBody := NodeUtil_GetFunctionBody(fn)
	if fnBody.IsNil() {
		return false
	}
	hasThis := false
	NodeUtil_VisitPostOrderWithPred(
		fnBody,
		NodeUtil_VisitorFunc(func(n rhino.Node) {
			if n.IsThis() {
				hasThis = true
			}
		}),
		func(n rhino.Node) bool { return !n.IsClass() && (!n.IsFunction() || n.IsArrowFunction()) })
	return hasThis
}

// RewriteSuperReferencesInPrivateMember rewrites `super` references inside
// private methods or accessors into explicit target calls or Reflect calls.
//
//   - `super.method()` → `Base.method.call(this)`
//   - `super.prop` → `Reflect.get(Base, JSCompiler_renameProperty('prop',
//     Base), this)`
//   - `super.prop = val` → `Reflect.set(Base,
//     JSCompiler_renameProperty('prop', Base), val, this)`
//
// Java: Es6NormalizeClasses.rewriteSuperReferencesInPrivateMember(Node, ClassRecord)
func (e *Es6NormalizeClasses) RewriteSuperReferencesInPrivateMember(memberNode rhino.Node, record *es6NormalizeClasses_ClassRecord) {
	if record.normalizedNames.SuperClassNode().IsNil() {
		return
	}
	fn := memberNode.GetFirstChild()
	fnBody := NodeUtil_GetFunctionBody(fn)
	if fnBody.IsNil() || !NodeUtil_ReferencesSuper(fnBody) {
		return
	}

	isStatic := memberNode.IsStaticMember()
	NodeUtil_VisitPostOrderWithPred(
		fnBody,
		NodeUtil_VisitorFunc(func(n rhino.Node) {
			if n.IsSuper() {
				parent := n.GetParent()
				if parent.IsGetProp() || parent.IsGetElem() {
					var target rhino.Node
					if isStatic {
						target = record.CreateNewSuperclassReferenceNode().SrcrefTree(n)
					} else {
						// TODO(b/236744850): Consider emitting dynamic prototype chain lookups
						// (`Object.getPrototypeOf(Child.prototype).method`) rather than static prototype
						// accesses (`Base.prototype.method`) if dynamic prototype mutation must be
						// supported.
						target =
							e.astFactory.
								CreatePrototypeAccess(record.CreateNewSuperclassReferenceNode()).
								SrcrefTree(n)
					}

					grandParent := parent.GetParent()
					if !grandParent.IsNil() &&
						grandParent.IsCall() &&
						grandParent.GetFirstChild() == parent {
						// Method call: super.method(...)
						n.ReplaceWith(target)
						// Note: For instance super calls (`!isStatic`) or when static inheritance is
						// enabled
						// (`!getAssumeStaticInheritanceIsNotUsed()`), we invoke the method via
						// `.call(this)`
						// so the `this` receiver is preserved across the class hierarchy.
						if !isStatic || !e.compiler.GetOptions().GetAssumeStaticInheritanceIsNotUsed() {
							callCallee :=
								e.astFactory.CreateGetPropWithUnknownType(parent.Detach(), "call")
							grandParent.AddChildToFront(callCallee.SrcrefTreeIfMissing(parent))
							thisArg := e.astFactory.CreateThis(AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)).Srcref(n)
							thisArg.InsertAfter(callCallee)
						}
					} else if !grandParent.IsNil() &&
						grandParent.IsAssign() &&
						grandParent.GetFirstChild() == parent {
						// Setter write: super.prop = value
						rhs := grandParent.GetSecondChild().Detach()
						var propKey rhino.Node
						if parent.IsGetProp() {
							propKey = e.astFactory.CreateCall(
								e.astFactory.CreateName(
									NodeUtil_JSC_PROPERTY_NAME_FN, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)),
								AstFactory_Type_OfColor(colors.StandardColors_STRING),
								e.astFactory.CreateString(parent.GetString()),
								record.CreateNewSuperclassReferenceNode().SrcrefTree(n))
						} else {
							propKey = parent.GetSecondChild().Detach()
						}

						reflectSet :=
							e.astFactory.CreateCall(
								e.astFactory.CreateGetPropWithUnknownType(
									e.astFactory.CreateName("Reflect", AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)), "set"),
								AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN),
								target,
								propKey,
								rhs,
								e.astFactory.CreateThis(AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)).Srcref(n))
						grandParent.ReplaceWith(reflectSet.SrcrefTreeIfMissing(grandParent))
					} else {
						// Getter read: super.prop
						var propKey rhino.Node
						if parent.IsGetProp() {
							propKey = e.astFactory.CreateCall(
								e.astFactory.CreateName(
									NodeUtil_JSC_PROPERTY_NAME_FN, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)),
								AstFactory_Type_OfColor(colors.StandardColors_STRING),
								e.astFactory.CreateString(parent.GetString()),
								record.CreateNewSuperclassReferenceNode().SrcrefTree(n))
						} else {
							propKey = parent.GetSecondChild().Detach()
						}

						reflectGet :=
							e.astFactory.CreateCall(
								e.astFactory.CreateGetPropWithUnknownType(
									e.astFactory.CreateName("Reflect", AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)), "get"),
								AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN),
								target,
								propKey,
								e.astFactory.CreateThis(AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)).Srcref(n))
						parent.ReplaceWith(reflectGet.SrcrefTreeIfMissing(parent))
					}
					e.compiler.ReportChangeToEnclosingScope(fnBody)
				}
			}
		}),
		func(n rhino.Node) bool { return !n.IsClass() })
}

// RewriteSideEffectedComputedProps rewrites and moves all side effected
// computed field keys to the top
//
// Java: Es6NormalizeClasses.rewriteSideEffectedComputedProps(NodeTraversal, ClassRecord, Node)
func (e *Es6NormalizeClasses) RewriteSideEffectedComputedProps(
	t *NodeTraversal, record *es6NormalizeClasses_ClassRecord, insertionPoint rhino.Node) {
	computedPropsWithSideEffects := &record.computedPropsWithSideEffects

	if len(*computedPropsWithSideEffects) == 0 {
		return
	}

	for len(*computedPropsWithSideEffects) != 0 {
		computedPropMember := es6NormalizeClasses_dequeRemove(computedPropsWithSideEffects)
		e.ExtractExpressionFromCompField(t, record, computedPropMember, insertionPoint)
	}
	t.ReportCodeChange()
}

// Go-only: language-adapter — ArrayDeque.remove(): removes and returns the
// first element, throwing NoSuchElementException when empty.
func es6NormalizeClasses_dequeRemove(deque *[]rhino.Node) rhino.Node {
	if len(*deque) == 0 {
		panic(jutil.NewNoSuchElementException())
	}
	first := (*deque)[0]
	(*deque)[0] = rhino.Node{}
	*deque = (*deque)[1:]
	return first
}

// ExtractExpressionFromCompField extracts the expression in the LHS of a
// computed field to not disturb possible side effects and allow for this
// and super to be used in the LHS of a computed field in certain cases. Does
// not extract a computed field that was already moved into a computed
// function.
//
// E.g.
//
//	class Foo {
//	  [bar('str')] = 4;
//	}
//
// becomes
//
//	var $jscomp$computedfield$0 = bar('str');
//	class Foo {
//	  [$jscomp$computedfield$0] = 4;
//	}
//
// Java: Es6NormalizeClasses.extractExpressionFromCompField(NodeTraversal, ClassRecord, Node, Node)
func (e *Es6NormalizeClasses) ExtractExpressionFromCompField(
	t *NodeTraversal, record *es6NormalizeClasses_ClassRecord, memberField rhino.Node, insertionPoint rhino.Node) {
	jutil.CheckArgumentMsg1(memberField.IsComputedFieldDef() || memberField.IsComputedProp(), "%s", memberField)

	compExpression := memberField.RemoveFirstChild()
	compFieldVar := e.astFactory.
		CreateSingleVarNameDeclarationWithValue(e.GenerateUniqueCompFieldVarName(t), compExpression).
		SrcrefTreeIfMissing(record.classNode)
	compFieldName := compFieldVar.GetFirstChild()
	memberField.AddChildToFront(compFieldName.CloneNode())
	compFieldVar.InsertBefore(insertionPoint)
	compFieldVar.SrcrefTreeIfMissing(record.classNode)
}

// RewriteInstanceMembers rewrites and moves all instance fields into the
// constructor.
//
// E.g.
//
//	class Foo {
//	  field = 1;
//	  #privField = 2;
//	}
//
// becomes
//
//	class Foo {
//	  constructor() {
//	    const PRIVATE$uid = {};
//	    PRIVATE$uid.$self = this;
//	    PRIVATE_MAP$uid.set(this, PRIVATE$uid);
//	    PRIVATE$uid.privField = 2;
//	    this.field = 1;
//	  }
//	}
//
// Java: Es6NormalizeClasses.rewriteInstanceMembers(NodeTraversal, ClassRecord)
func (e *Es6NormalizeClasses) RewriteInstanceMembers(t *NodeTraversal, record *es6NormalizeClasses_ClassRecord) {
	instanceMembers := &record.instanceMembers
	hasPriv := e.transpilePrivateClassFields && record.hasInstancePrivateMembers

	if len(*instanceMembers) == 0 && !hasPriv {
		return
	}
	e.ctorCreator.SynthesizeClassConstructorIfMissing(t, record.classNode)
	ctor := NodeUtil_GetEs6ClassConstructorMemberFunctionDef(record.classNode)
	ctorBlock := ctor.GetFirstChild().GetLastChild()
	insertionPoint := e.AddTemporaryInsertionPoint(ctorBlock, record)

	if hasPriv {
		mapName := record.GetPrivateMapVarName(e.compiler, t)
		privName := record.GetPrivateVarName(e.compiler, t)

		var privInit rhino.Node
		if record.hasInstancePrivateMethodsOrAccessors {
			// Initializer: Object.create(PRIVATE_PROTO$uid)
			protoName :=
				e.astFactory.CreateNameWithUnknownType(record.GetPrivateProtoVarName(e.compiler, t))
			createProp :=
				e.astFactory.CreateGetPropWithUnknownType(
					e.astFactory.CreateNameWithUnknownType("Object"), "create")
			privInit = e.astFactory.CreateCallWithUnknownType(createProp, protoName)
		} else {
			// Initializer: Object.create(null)
			createProp :=
				e.astFactory.CreateGetPropWithUnknownType(
					e.astFactory.CreateNameWithUnknownType("Object"), "create")
			privInit = e.astFactory.CreateCallWithUnknownType(createProp, e.astFactory.CreateNull())
		}
		// Add `const PRIVATE$uid = privInit;` to the original code.
		privDecl :=
			e.astFactory.
				CreateSingleConstNameDeclaration(privName, privInit).
				SrcrefTreeIfMissing(record.classNode)
		privDecl.InsertBefore(insertionPoint)

		if record.needsInstanceSelf {
			// Add `PRIVATE$uid.$self = this;` to the original code.
			privSelf :=
				e.astFactory.CreateGetPropWithUnknownType(
					e.astFactory.CreateConstantName(privName, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)), "$self")
			assignSelf :=
				e.astFactory.
					CreateAssignStatement(privSelf, e.astFactory.CreateThisForEs6Class(record.classNode)).
					SrcrefTreeIfMissing(record.classNode)
			assignSelf.InsertBefore(insertionPoint)
		}

		// Add `PRIVATE_MAP$uid.set(this, PRIVATE$uid);` to the original code.
		mapNameNode := e.astFactory.CreateNameWithUnknownType(mapName)
		mapSetCallee := e.astFactory.CreateGetPropWithUnknownType(mapNameNode, "set")
		mapSetCall :=
			e.astFactory.CreateCallWithUnknownType(
				mapSetCallee,
				e.astFactory.CreateThisForEs6Class(record.classNode),
				e.astFactory.CreateConstantName(privName, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)))
		mapSetStmt := e.astFactory.ExprResult(mapSetCall).SrcrefTreeIfMissing(record.classNode)
		mapSetStmt.InsertBefore(insertionPoint)
	}

	for len(*instanceMembers) != 0 {
		instanceMember := es6NormalizeClasses_dequeRemove(instanceMembers)
		jutil.CheckStateMsg1(
			instanceMember.IsMemberFieldDef() || instanceMember.IsComputedFieldDef(), "%s", instanceMember)

		if instanceMember.IsPrivateIdentifier() {
			if e.transpilePrivateClassFields {
				privName := record.GetPrivateVarName(e.compiler, t)
				propName := jutil.StringSubstringFrom(instanceMember.GetString(), 1)
				// Add `PRIVATE$uid.field = fieldValue;` to the original code.
				lhs :=
					e.astFactory.CreateGetPropWithUnknownType(
						e.astFactory.CreateConstantName(privName, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)), propName)
				var fieldValue rhino.Node
				if instanceMember.HasChildren() {
					fieldValue = instanceMember.RemoveFirstChild()
				} else {
					fieldValue = e.astFactory.CreateUndefinedValue()
				}
				assign := e.astFactory.CreateAssignStatement(lhs, fieldValue)
				assign.SrcrefTreeIfMissing(instanceMember)
				assign.InsertBefore(insertionPoint)
				instanceMember.Detach()
			}
		} else {
			// Add `this.field = fieldValue;` or `this[field] = fieldValue;` to the original code.
			thisNode := e.astFactory.CreateThisForEs6ClassMember(instanceMember)
			var transpiledNode rhino.Node
			if instanceMember.IsMemberFieldDef() {
				transpiledNode = e.ConvNonCompFieldToGetProp(thisNode, instanceMember /* isStatic= */, false)
			} else {
				transpiledNode = e.ConvCompFieldToGetElem(thisNode, instanceMember /* isStatic= */, false)
			}

			if !transpiledNode.IsNil() {
				transpiledNode.InsertBefore(insertionPoint)
			}
		}
	}

	if e.transpilePrivateClassFields {
		// Remove original non-static private member declaration nodes (fields and methods) from the
		// class body AST now that their transpiled equivalents (e.g., constructor initializations,
		// PRIVATE_PROTO descriptors) have been generated.
		for _, pm := range record.privateMembers {
			if !pm.isStatic {
				for _, declNode := range pm.declarationNodes {
					if !declNode.GetParent().IsNil() {
						NodeUtil_DeleteNode(declNode, e.compiler)
					}
				}
			}
		}
	}

	insertionPoint.Detach()

	// We moved the field from the class body to the constructor, so we need both.
	t.ReportCodeChange()
	t.ReportCodeChangeWithNode(ctorBlock)
}

// AddTemporaryInsertionPoint finds the location of super() call in the
// constructor and add a temporary empty node after the super() call. If
// there is no super() call, add a temporary empty node at the beginning of
// the constructor body after all function declarations.
//
// Returns the added temporary empty node.
//
// Java: Es6NormalizeClasses.addTemporaryInsertionPoint(Node, ClassRecord)
func (e *Es6NormalizeClasses) AddTemporaryInsertionPoint(ctorBlock rhino.Node, classRecord *es6NormalizeClasses_ClassRecord) rhino.Node {
	jutil.CheckStateMsg1(
		len(classRecord.superCalls) <= 1,
		"classes with public fields must have only one super() call at the constructor root: %s",
		classRecord.classNode)

	tempNode := rhino.IR_Empty()
	if len(classRecord.superCalls) == 1 {
		stmt := e.EnsureSuperCallIsOwnStatement(classRecord.superCalls[0])
		tempNode.InsertAfter(stmt)
		return tempNode
	}
	// Search for super() calls added by SynthesizeExplicitConstructors.
	for stmt := ctorBlock.GetFirstChild(); !stmt.IsNil(); stmt = stmt.GetNext() {
		if NodeUtil_IsExprCall(stmt) && stmt.GetFirstFirstChild().IsSuper() {
			tempNode.InsertAfter(stmt)
			return tempNode
		}
	}
	insertionPoint := NodeUtil_GetInsertionPointAfterAllInnerFunctionDeclarations(ctorBlock)
	if !insertionPoint.IsNil() {
		tempNode.InsertBefore(insertionPoint)
	} else {
		// functionBody only contains hoisted function declarations
		ctorBlock.AddChildToBack(tempNode)
	}
	return tempNode
}

// EnsureSuperCallIsOwnStatement returns a statement containing either
// `super(...);` or `var tmp = super(...)`, extracting the given super call
// into a `tmp` variable if necessary.
//
// Java: Es6NormalizeClasses.ensureSuperCallIsOwnStatement(Node)
func (e *Es6NormalizeClasses) EnsureSuperCallIsOwnStatement(superCall rhino.Node) rhino.Node {
	parent := superCall.GetParent()
	if parent.IsExprResult() {
		return parent // No extraction needed.
	}
	jutil.CheckStateMsg1(
		e.expressionDecomposer.CanExposeExpression(superCall) != ExpressionDecomposer_DecompositionType_UNDECOMPOSABLE,
		"Cannot decompose super() call in a class with class fields. Move super() call to the"+
			" root of the constructor. %s",
		superCall)
	e.expressionDecomposer.MaybeExposeExpression(superCall)
	e.expressionDecomposer.MoveExpression(superCall)
	return NodeUtil_GetEnclosingStatement(superCall)
}

// MaybeReportPrivatePropertiesCannotConvertYet reports that transpilation
// of private class properties is not yet supported when attempting to
// rewrite or normalize private identifiers. See b/236744850.
//
// Java: Es6NormalizeClasses.maybeReportPrivatePropertiesCannotConvertYet(Node)
func (e *Es6NormalizeClasses) MaybeReportPrivatePropertiesCannotConvertYet(n rhino.Node) {
	if e.transpilePrivateClassFields && n.IsPrivateIdentifier() {
		TranspilationUtil_CannotConvertYet(e.compiler, n, "Private elements")
	}
}

// Java: Es6NormalizeClasses.createObjectDotDefineProperty()
func (e *Es6NormalizeClasses) CreateObjectDotDefineProperty() rhino.Node {
	e.compiler.GetRuntimeJsLibManager().InjectLibForField("$jscomp.global")
	global := e.compiler.GetRuntimeJsLibManager().GetJsLibField("$jscomp.global")
	jscompDotGlobal := e.astFactory.CreateQNameWithUnknownTypeOfField(global)
	objectNode := e.astFactory.CreateGetPropWithUnknownType(jscompDotGlobal, "Object")
	return e.astFactory.CreateGetPropWithUnknownType(objectNode, "defineProperty")
}

// ConvNonCompFieldToGetProp creates a node that represents receiver.key =
// value; where the key and value comes from the non-computed field, or an
// Object.defineProperty call if the property is "__proto__".
//
// Java: Es6NormalizeClasses.convNonCompFieldToGetProp(Node, Node, boolean)
func (e *Es6NormalizeClasses) ConvNonCompFieldToGetProp(
	receiver rhino.Node, noncomputedField rhino.Node, isStatic bool) rhino.Node {
	jutil.CheckArgument(noncomputedField.IsMemberFieldDef())
	jutil.CheckArgumentMsg1(receiver.GetParent().IsNil(), "%s", receiver)

	var fieldValue rhino.Node
	// We always move out the static field initialization.
	if isStatic || e.transpileClassFields {
		fieldValue = noncomputedField.GetFirstChild()
	}

	propName := noncomputedField.GetString()
	if propName == "__proto__" {
		return e.CreateFieldDefineProperty(
			noncomputedField, fieldValue, receiver, e.astFactory.CreateString(propName))
	}

	return e.CreateFieldAssignment(
		noncomputedField,
		fieldValue,
		func() rhino.Node {
			return e.astFactory.CreateGetProp(receiver, propName, AstFactory_Type_(noncomputedField))
		})
}

// ConvCompFieldToGetElem creates a node that represents receiver[key] =
// value; where the key and value comes from the computed field, or an
// Object.defineProperty call if the property evaluates to "__proto__".
//
// Java: Es6NormalizeClasses.convCompFieldToGetElem(Node, Node, boolean)
func (e *Es6NormalizeClasses) ConvCompFieldToGetElem(
	receiver rhino.Node, computedField rhino.Node, isStatic bool) rhino.Node {
	jutil.CheckArgumentMsg1(computedField.IsComputedFieldDef(), "%s", computedField)
	jutil.CheckArgumentMsg1(receiver.GetParent().IsNil(), "%s", receiver)

	var fieldValue rhino.Node
	if computedField.GetChildCount() == 2 && (isStatic || e.transpileClassFields) {
		fieldValue = computedField.GetLastChild()
	}

	var compFieldNameExpr rhino.Node
	if e.transpileClassFields {
		compFieldNameExpr = computedField.RemoveFirstChild()
	} else {
		compFieldNameExpr = computedField.GetFirstChild().CloneTree()
	}

	if v := NodeUtil_GetStringValue(compFieldNameExpr); v != nil && *v == "__proto__" {
		return e.CreateFieldDefineProperty(computedField, fieldValue, receiver, compFieldNameExpr)
	}

	return e.CreateFieldAssignment(
		computedField, fieldValue, func() rhino.Node { return e.astFactory.CreateGetElem(receiver, compFieldNameExpr) })
}

// CreateFieldDefineProperty is a helper to create an Object.defineProperty
// statement for class fields whose property key is "__proto__", avoiding
// unsafe prototype mutation.
//
// Java: Es6NormalizeClasses.createFieldDefineProperty(Node, Node, Node, Node)
func (e *Es6NormalizeClasses) CreateFieldDefineProperty(
	field rhino.Node, fieldValue rhino.Node, receiver rhino.Node, keyNode rhino.Node) rhino.Node {
	return e.CreateFieldInitializationStatement(
		field,
		fieldValue,
		func(val rhino.Node) rhino.Node {
			descriptor :=
				e.astFactory.CreateObjectLit(
					e.astFactory.CreateStringKey("configurable", e.astFactory.CreateBoolean(true)),
					e.astFactory.CreateStringKey("enumerable", e.astFactory.CreateBoolean(true)),
					e.astFactory.CreateStringKey("writable", e.astFactory.CreateBoolean(true)),
					e.astFactory.CreateStringKey("value", val))

			definePropertyCall :=
				e.astFactory.CreateCallWithUnknownType(
					e.CreateObjectDotDefineProperty(), receiver, keyNode, descriptor)

			return e.astFactory.ExprResult(definePropertyCall)
		})
}

// CreateFieldAssignment is a helper to create an assignment statement for
// a class field.
//
// Java: Es6NormalizeClasses.createFieldAssignment(Node, Node, Supplier<Node>)
func (e *Es6NormalizeClasses) CreateFieldAssignment(
	field rhino.Node, fieldValue rhino.Node, createAssignLhs func() rhino.Node) rhino.Node {
	return e.CreateFieldInitializationStatement(
		field, fieldValue, func(val rhino.Node) rhino.Node { return e.astFactory.CreateAssignStatement(createAssignLhs(), val) })
}

// CreateFieldInitializationStatement is a shared helper to create an
// initialization statement for a class field. Handles logic for creating
// undefined values for uninitialized fields during transpilation, detaching
// fields, as well as JSDoc transfer and source reference mapping.
//
// Java: Es6NormalizeClasses.createFieldInitializationStatement(Node, Node, Function<Node, Node>)
func (e *Es6NormalizeClasses) CreateFieldInitializationStatement(
	field rhino.Node, fieldValue rhino.Node, createStatement func(rhino.Node) rhino.Node) rhino.Node {
	// For public fields, we don't need to keep around the field declaration.
	// For private fields, we still need to keep them in the class body due to syntax requirements.
	if e.transpileClassFields && !field.IsPrivateIdentifier() {
		field.Detach()
	}

	// We don't make a copy of the static field declaration if it doesn't have an initializer and
	// we're not transpiling class fields.
	if fieldValue.IsNil() {
		if !e.transpileClassFields {
			return rhino.Node{}
		}

		// If we are transpiling class fields, we want an explicit undefined value so we properly
		// initialize the field.
		fieldValue = e.astFactory.CreateUndefinedValue()
	} else {
		// We are going to move fieldValue to a new parent, so detach it now.
		// (TODO: b/236744850): for private fields, consider keeping the initializers in the class
		// body.
		fieldValue.Detach()
	}

	result := createStatement(fieldValue)

	if e.transpileClassFields {
		// Move any JSDoc from the field declaration to the child of the EXPR_RESULT, which represents
		// the new declaration.
		// field is already detached, so there's no benefit to calling
		// NodeUtil.getBestJSDocInfo(field). For now at least, the JSDocInfo we want will always be
		// directly on field in all cases.
		result.GetFirstChild().SetJSDocInfo(field.GetJSDocInfo())
	}
	result.SrcrefTreeIfMissing(field)
	return result
}

// RewriteStaticMembers rewrites and moves all static blocks and fields
//
// Java: Es6NormalizeClasses.rewriteStaticMembers(NodeTraversal, ClassRecord, Node)
func (e *Es6NormalizeClasses) RewriteStaticMembers(t *NodeTraversal, record *es6NormalizeClasses_ClassRecord, insertionPoint rhino.Node) {
	staticMembers := &record.staticMembers
	hasPriv := e.transpilePrivateClassFields && record.hasStaticPrivateMembers
	if len(*staticMembers) == 0 && !hasPriv {
		return
	}

	staticInitTempParent := rhino.IR_Block()

	if hasPriv {
		staticMapName := record.GetStaticPrivateMapVarName(e.compiler, t)
		privName := record.GetStaticPrivateVarName(e.compiler, t)

		// Pre-scan static private accessors to check if any getter/setter references 'this'.
		// If so, we must set $self on the static private object.
		for _, pm := range record.privateMembers {
			if pm.isStatic && pm.kind == es6NormalizeClasses_ClassRecord_PrivateMemberKind_ACCESSOR {
				if !pm.getterNode.IsNil() &&
					pm.getterNode.HasChildren() &&
					e.HasThisReference(pm.getterNode.GetFirstChild()) {
					record.needsStaticSelf = true
				}
				if !pm.setterNode.IsNil() &&
					pm.setterNode.HasChildren() &&
					e.HasThisReference(pm.setterNode.GetFirstChild()) {
					record.needsStaticSelf = true
				}
			}
		}

		// Add `const PRIVATE$uid = Object.create(null);` to the original code.
		createProp :=
			e.astFactory.CreateGetPropWithUnknownType(
				e.astFactory.CreateNameWithUnknownType("Object"), "create")
		staticPrivInit :=
			e.astFactory.CreateCallWithUnknownType(createProp, e.astFactory.CreateNull())
		privDecl :=
			e.astFactory.
				CreateSingleConstNameDeclaration(privName, staticPrivInit).
				SrcrefTreeIfMissing(record.classNode)
		staticInitTempParent.AddChildToBack(privDecl)

		if record.needsStaticSelf {
			// Add `PRIVATE$uid.$self = ClassName;` to the original code.
			privSelf :=
				e.astFactory.CreateGetPropWithUnknownType(
					e.astFactory.CreateConstantName(privName, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)), "$self")
			assignSelf :=
				e.astFactory.
					CreateAssignStatement(
						privSelf,
						record.CreateNewNameReferenceNode().SrcrefTreeIfMissing(record.classNode)).
					SrcrefTreeIfMissing(record.classNode)
			staticInitTempParent.AddChildToBack(assignSelf)
		}

		// Add `STATIC_PRIVATE_MAP$uid.set(ClassName, PRIVATE$uid);` to the original code.
		mapNameNode := e.astFactory.CreateNameWithUnknownType(staticMapName)
		mapSetCallee := e.astFactory.CreateGetPropWithUnknownType(mapNameNode, "set")
		mapSetCall :=
			e.astFactory.CreateCallWithUnknownType(
				mapSetCallee,
				record.CreateNewNameReferenceNode().SrcrefTreeIfMissing(record.classNode),
				e.astFactory.CreateConstantName(privName, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)))
		mapSetStmt := e.astFactory.ExprResult(mapSetCall).SrcrefTreeIfMissing(record.classNode)
		staticInitTempParent.AddChildToBack(mapSetStmt)

		e.AddStaticPrivateMembers(record, privName, staticInitTempParent)
	}

	for len(*staticMembers) != 0 {
		staticMember := es6NormalizeClasses_dequeRemove(staticMembers)
		if staticMember.IsPrivateIdentifier() {
			if e.transpilePrivateClassFields {
				privName := record.GetStaticPrivateVarName(e.compiler, t)
				propName := jutil.StringSubstringFrom(staticMember.GetString(), 1)
				// Add `PRIVATE$uid.staticField = fieldValue;` to the original code.
				lhs :=
					e.astFactory.CreateGetPropWithUnknownType(
						e.astFactory.CreateConstantName(privName, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)), propName)
				var fieldValue rhino.Node
				if staticMember.HasChildren() {
					fieldValue = staticMember.RemoveFirstChild()
				} else {
					fieldValue = e.astFactory.CreateUndefinedValue()
				}
				assign := e.astFactory.CreateAssignStatement(lhs, fieldValue)
				assign.SrcrefTreeIfMissing(staticMember)
				staticInitTempParent.AddChildToBack(assign)
				staticMember.Detach()
			}
		} else {
			// if the name is a property access, we want the whole chain of accesses, while for other
			// cases we only want the name node
			nameToUse := record.CreateNewNameReferenceNode().SrcrefTree(staticMember)

			var transpiledNode rhino.Node
			switch staticMember.GetToken() {
			case rhino.Token_BLOCK:
				block := staticMember.Detach()
				t.ReportCodeChange()
				// We ignore empty static initialization blocks.
				if block.HasChildren() {
					transpiledNode = block
				}
			case rhino.Token_MEMBER_FIELD_DEF:
				transpiledNode = e.ConvNonCompFieldToGetProp(nameToUse, staticMember /* isStatic= */, true)
			case rhino.Token_COMPUTED_FIELD_DEF:
				transpiledNode = e.ConvCompFieldToGetElem(nameToUse, staticMember /* isStatic= */, true)
			default:
				panic(jutil.NewIllegalStateExceptionMsg(jutil.ToJavaString(staticMember)))
			}
			if !transpiledNode.IsNil() {
				staticInitTempParent.AddChildToBack(transpiledNode)
			}
		}
	}

	if e.transpilePrivateClassFields {
		// Remove original static private member declaration nodes (fields and methods) from the class
		// body AST now that their transpiled equivalents (e.g. static initialization statements) have
		// been generated, preventing duplicate declarations in downstream compiler passes.
		for _, pm := range record.privateMembers {
			if pm.isStatic {
				for _, declNode := range pm.declarationNodes {
					if !declNode.GetParent().IsNil() {
						NodeUtil_DeleteNode(declNode, e.compiler)
					}
				}
			}
		}
	}

	// If there is no static initialization logic, we are done.
	if !staticInitTempParent.HasChildren() {
		return
	}

	// If there are no super references or private field references, place all the static
	// initialization code after the class.
	if !hasPriv &&
		!NodeUtil_Has(
			staticInitTempParent,
			/* pred= */ func(n rhino.Node) bool { return n.IsSuper() || n.IsPrivateIdentifier() },
			/* traverseChildrenPred= */ func(n rhino.Node) bool {
				return !n.IsClass() && (!n.IsFunction() || n.IsArrowFunction())
			}) {
		for staticInitTempParent.HasChildren() {
			staticInitTempParent.GetLastChild().Detach().InsertAfter(insertionPoint)
		}
		t.ReportCodeChangeWithNode(insertionPoint.GetParent())
		return
	}

	// We will introduce a new static method and a call to it to contain static initialization code.

	// Add new static method "$jscomp$staticInit$[FILE_ID]$[number]".
	// All the static initialization logic goes into this method. We need a static method as opposed
	// to doing this logic alongside the class because #private members can only be accessed within
	// the class.
	staticInitMethodName := e.GenerateUniqueStaticInitMethodName(t)
	staticInitMethodFunc :=
		e.astFactory.CreateEmptyFunction(AstFactory_Type_OfJSTypeNativeAndColor(rhino.JSTypeNative_FUNCTION_TYPE, colors.StandardColors_TOP_OBJECT))
	staticInitMethod :=
		e.astFactory.CreateMemberFunctionDef(staticInitMethodName, staticInitMethodFunc)
	staticInitMethod.SetStaticMember(true)

	staticInitBlock := staticInitMethod.GetFirstChild().GetLastChild()
	staticInitBlock.AddChildrenToFront(staticInitTempParent.RemoveChildren())

	classMembers := NodeUtil_GetClassMembers(record.classNode)
	staticInitMethod.SrcrefTreeIfMissing(classMembers)
	classMembers.AddChildToBack(staticInitMethod)
	e.compiler.ReportChangeToChangeScope(staticInitMethodFunc)
	t.ReportCodeChangeWithNode(staticInitMethod)
	// Record the feature corresponding to a static method.
	NodeUtil_AddFeatureToScript(t.GetCurrentScript(), parser.FeatureSet_Feature_MEMBER_DECLARATIONS, e.compiler)

	// Add a call to the static initialization method after the class definition.
	staticInitCall := e.astFactory.
		CreateCall(
			e.astFactory.CreateGetProp(
				record.CreateNewNameReferenceNode(),
				staticInitMethodName,
				AstFactory_Type_(staticInitMethodFunc)),
			AstFactory_Type_OfJSTypeNativeAndColor(rhino.JSTypeNative_VOID_TYPE, colors.StandardColors_NULL_OR_VOID)).
		SrcrefTreeIfMissing(classMembers)
	staticInitCallStmt := e.astFactory.ExprResult(staticInitCall)
	staticInitCallStmt.InsertAfter(insertionPoint)
}

// AddStaticPrivateMembers attaches static private methods and accessors to
// the static private object.
//
// Java: Es6NormalizeClasses.addStaticPrivateMembers(ClassRecord, String, Node)
func (e *Es6NormalizeClasses) AddStaticPrivateMembers(
	record *es6NormalizeClasses_ClassRecord, privName string, staticInitTempParent rhino.Node) {
	for _, pm := range record.privateMembers {
		// Only process static private members for static initialization.
		if pm.isStatic {
			// Assign static private method definitions to the static private object (e.g.,
			// PRIVATE$uid.method = function() {}).
			if pm.kind == es6NormalizeClasses_ClassRecord_PrivateMemberKind_METHOD &&
				!pm.methodNode.IsNil() &&
				pm.methodNode.HasChildren() {
				e.RewriteSuperReferencesInPrivateMember(pm.methodNode, record)
				fnNode := pm.methodNode.GetFirstChild().Detach()
				pm.methodNode.Detach()
				lhs :=
					e.astFactory.CreateGetPropWithUnknownType(
						e.astFactory.CreateConstantName(privName, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)),
						pm.PropertyName())
				assign := e.astFactory.CreateAssignStatement(lhs, fnNode)
				assign.SrcrefTreeIfMissing(pm.methodNode)
				staticInitTempParent.AddChildToBack(assign)
			} else if pm.kind == es6NormalizeClasses_ClassRecord_PrivateMemberKind_ACCESSOR {
				// Assign static private accessor definitions to the static private object via
				// Object.defineProperty.
				descriptorLit := e.astFactory.CreateObjectLit()
				if !pm.getterNode.IsNil() && pm.getterNode.HasChildren() {
					e.RewriteSuperReferencesInPrivateMember(pm.getterNode, record)
					getFn := pm.getterNode.GetFirstChild().Detach()
					pm.getterNode.Detach()
					e.RewriteThisToThisDotSelf(getFn)
					descriptorLit.AddChildToBack(e.astFactory.CreateStringKey("get", getFn))
				}
				if !pm.setterNode.IsNil() && pm.setterNode.HasChildren() {
					e.RewriteSuperReferencesInPrivateMember(pm.setterNode, record)
					setFn := pm.setterNode.GetFirstChild().Detach()
					pm.setterNode.Detach()
					e.RewriteThisToThisDotSelf(setFn)
					descriptorLit.AddChildToBack(e.astFactory.CreateStringKey("set", setFn))
				}
				defineProp :=
					e.astFactory.CreateGetPropWithUnknownType(
						e.astFactory.CreateNameWithUnknownType("Object"), "defineProperty")
				call :=
					e.astFactory.CreateCallWithUnknownType(
						defineProp,
						e.astFactory.CreateConstantName(privName, AstFactory_Type_OfColor(colors.StandardColors_UNKNOWN)),
						e.astFactory.CreateString(pm.PropertyName()),
						descriptorLit)
				declNode := pm.GetPrimaryDeclarationNode()
				exprResult := e.astFactory.ExprResult(call)
				if !declNode.IsNil() {
					exprResult.SrcrefTreeIfMissing(declNode)
				}
				staticInitTempParent.AddChildToBack(exprResult)
			}
		}
	}
}

// Java: Es6NormalizeClasses.maybeUpdateClassSelfRef(NodeTraversal, Node)
func (e *Es6NormalizeClasses) MaybeUpdateClassSelfRef(t *NodeTraversal, nameNode rhino.Node) {
	for i := len(e.classStack) - 1; i >= 0; i-- {
		klass := e.classStack[i]
		if klass.bindingIdentifier.IsNil() {
			continue
		}

		bindingIdentifier := klass.bindingIdentifier
		if
		// Skip if the inner class name is the same as the class name (either this is a class
		// declaration or the outer and inner class names are the same).
		bindingIdentifier.MatchesNameNode(klass.normalizedNames.ClassNameNode()) ||
			// Skip if this IS the inner class name node (removed later when we visit the class).
			nameNode == bindingIdentifier ||
			// Skip if this nameNode is not equal to the inner class name.
			!nameNode.MatchesQualifiedNameNode(bindingIdentifier) {
			continue
		}

		// Ensure that this nameNode is not being shadowed by a different variable with the same name
		// as the inner class name.
		var_ := t.GetScope().GetVar(nameNode.GetString())
		if var_ == nil || var_.GetNameNode() != bindingIdentifier {
			continue
		}

		newNameNode := klass.CreateNewNameReferenceNode().Srcref(nameNode)
		nameNode.ReplaceWith(newNameNode)
		e.compiler.ReportChangeToEnclosingScope(newNameNode)

		return // We made the replacement so bail.
	}
}

// VisitThisAndSuper visits `this` and `super` nodes in the class. Only
// makes changes in static contexts and records super calls in the
// constructor for later.
//
// For static `this`, we can only replace with the class name if in a static
// initialization context (i.e. in a static field initializer or a static
// block).
//
// For static `super`, we can always replace with the extended class name.
//
// Note: This runs before #rewriteStaticMembers so the static members are
// still there.
//
// Java: Es6NormalizeClasses.visitThisAndSuper(NodeTraversal, Node)
func (e *Es6NormalizeClasses) VisitThisAndSuper(t *NodeTraversal, n rhino.Node) {
	if Es6NormalizeClasses_IsSuperCall(n.GetParent()) {
		// super(...); calls are only legal in a constructor so we don't need to check for static
		// context.
		classRecord := e.peekClassRecord()
		classRecord.superCalls = append(classRecord.superCalls, n.GetParent())
		return
	}
	rootNode := t.GetClosestScopeRootNodeBindingThisOrSuper()
	rootParent := rootNode.GetParent()
	if rootNode.IsFunction() &&
		(rootParent.IsMemberFunctionDef() ||
			rootParent.IsComputedProp() ||
			rootParent.IsGetterDef() ||
			rootParent.IsSetterDef()) {
		rootNode = rootParent
	}
	inStaticBlock := rootNode.IsBlock() && rootNode.GetParent().IsClassMembers()
	if !rootNode.IsStaticMember() && !inStaticBlock {
		return
	}

	// We always rewrite static this to the class name in a static initialization context so that we
	// can normalize-away static initialization from field initializers and static blocks.
	forceRewriteStaticThis := n.IsThis() && Es6NormalizeClasses_IsInStaticInitializationContext(rootNode)

	if !e.doStaticInheritanceRewrites && !forceRewriteStaticThis {
		return
	}

	classNode := rootNode.GetGrandparent()
	classRecord := e.peekClassRecord()
	jutil.CheckStateMsg2(
		classRecord.classNode == classNode,
		"wrong class node: %s != %s",
		classRecord.classNode,
		classNode)

	var newNameNode rhino.Node
	if forceRewriteStaticThis {
		// For static this, we can only universally replace with the class name in a static
		// initialization context.
		newNameNode = classRecord.CreateNewNameReferenceNode().SrcrefTree(n)
	} else if e.doStaticSuperRewrites && n.IsSuper() {
		// For a static super, we can always rewrite the super as something else.
		newNameNode = classRecord.CreateNewSuperclassReferenceNode()
	}

	if !newNameNode.IsNil() {
		originalName := jutil.CheckNotNull(n.GetQualifiedName())
		newNameNode.SrcrefTree(n).SetOriginalName(originalName)
		n.ReplaceWith(newNameNode)
		t.ReportCodeChangeWithNode(newNameNode)
	}
}

// Java: Es6NormalizeClasses.isSuperCall(Node)
func Es6NormalizeClasses_IsSuperCall(n rhino.Node) bool {
	return n.IsCall() && n.GetFirstChild().IsSuper()
}

// Es6NormalizeClasses_IsInStaticInitializationContext assumes that we have
// already filtered out non-static members and non-static blocks.
//
// Java: Es6NormalizeClasses.isInStaticInitializationContext(Node)
func Es6NormalizeClasses_IsInStaticInitializationContext(rootNode rhino.Node) bool {
	switch rootNode.GetToken() {
	case rhino.Token_MEMBER_FUNCTION_DEF, rhino.Token_COMPUTED_PROP, rhino.Token_GETTER_DEF, rhino.Token_SETTER_DEF:
		jutil.CheckState(rootNode.IsStaticMember())
		return false
	case rhino.Token_MEMBER_FIELD_DEF, rhino.Token_COMPUTED_FIELD_DEF:
		jutil.CheckState(rootNode.IsStaticMember())
		return true
	case rhino.Token_BLOCK:
		jutil.CheckState(rootNode.GetParent().IsClassMembers())
		return true
	default:
		panic(jutil.NewIllegalArgumentExceptionMsg("invalid root " + jutil.ToJavaString(rootNode)))
	}
}

